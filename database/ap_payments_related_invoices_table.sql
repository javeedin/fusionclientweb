-- Add comments
COMMENT ON TABLE RR_AP_PAYMENTS_RELATED_INVOICES IS 'Stores related invoices for AP Payments from Oracle Fusion';
COMMENT ON COLUMN RR_AP_PAYMENTS_RELATED_INVOICES.INVOICE_PAYMENT_ID IS 'Unique identifier for invoice payment relationship';
COMMENT ON COLUMN RR_AP_PAYMENTS_RELATED_INVOICES.CHECK_ID IS 'Reference to parent payment (RR_AP_PAYMENTS_ALL.CHECK_ID)';
COMMENT ON COLUMN RR_AP_PAYMENTS_RELATED_INVOICES.INVOICE_ID IS 'Invoice ID from Fusion';
COMMENT ON COLUMN RR_AP_PAYMENTS_RELATED_INVOICES.AMOUNT_PAID_PAYMENT_CURRENCY IS 'Amount paid in payment currency';
