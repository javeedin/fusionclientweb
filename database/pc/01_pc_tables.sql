-- ============================================================
-- Petty Cash Module — Table DDL  (idempotent — safe to re-run)
-- File: database/pc/01_pc_tables.sql
-- Run order: 1st
-- ============================================================

-- ============================================================
-- 1. RR_PC_REGISTERS  (Petty Cash Register Header)
-- ============================================================
DECLARE
    l_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO l_count FROM user_tables WHERE table_name = 'RR_PC_REGISTERS';
    IF l_count = 0 THEN
        EXECUTE IMMEDIATE q'[
CREATE TABLE RR_PC_REGISTERS (
    REGISTER_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REGISTER_NAME       VARCHAR2(200)  NOT NULL,
    BUSINESS_UNIT       VARCHAR2(240)  NOT NULL,
    START_DATE          DATE,
    END_DATE            DATE,
    COMMENTS            VARCHAR2(1000),
    CASH_ACCOUNT_CCID   NUMBER,
    CASH_ACCOUNT_DESC   VARCHAR2(400),
    CURRENCY            VARCHAR2(10)   DEFAULT 'AED',
    STATUS              VARCHAR2(50)   DEFAULT 'DRAFT',
    CREATED_BY          VARCHAR2(150),
    CREATION_DATE       TIMESTAMP      DEFAULT SYSTIMESTAMP,
    LAST_UPDATED_BY     VARCHAR2(150),
    LAST_UPDATE_DATE    TIMESTAMP      DEFAULT SYSTIMESTAMP,
    CONSTRAINT RR_PC_REG_STATUS_CK  CHECK (STATUS IN ('DRAFT','ACTIVE','INACTIVE','CLOSED')),
    CONSTRAINT RR_PC_REG_NAME_UK    UNIQUE (REGISTER_NAME)
)]';
    END IF;
END;
/

-- Indexes
DECLARE l_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO l_count FROM user_indexes WHERE index_name = 'IDX_RR_PC_REG_STATUS';
    IF l_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_RR_PC_REG_STATUS ON RR_PC_REGISTERS(STATUS)';
    END IF;
END;
/

DECLARE l_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO l_count FROM user_indexes WHERE index_name = 'IDX_RR_PC_REG_DATES';
    IF l_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_RR_PC_REG_DATES ON RR_PC_REGISTERS(START_DATE, END_DATE)';
    END IF;
END;
/

COMMENT ON TABLE  RR_PC_REGISTERS                   IS 'Petty cash register headers';
COMMENT ON COLUMN RR_PC_REGISTERS.BUSINESS_UNIT     IS 'Oracle Fusion Business Unit that owns this petty cash register';
COMMENT ON COLUMN RR_PC_REGISTERS.CASH_ACCOUNT_CCID IS 'GL code combination ID for the petty cash GL account';
COMMENT ON COLUMN RR_PC_REGISTERS.STATUS            IS 'DRAFT = setup; ACTIVE = open for transactions; INACTIVE = closed (balance must be 0); CLOSED = legacy';

-- Safe: add BUSINESS_UNIT if missing (older installs)
DECLARE l_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO l_count FROM user_tab_columns
    WHERE  table_name = 'RR_PC_REGISTERS' AND column_name = 'BUSINESS_UNIT';
    IF l_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE RR_PC_REGISTERS ADD (BUSINESS_UNIT VARCHAR2(240))';
    END IF;
END;
