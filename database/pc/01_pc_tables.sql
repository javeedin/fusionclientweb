COMMENT ON COLUMN RR_PC_REGISTERS.OWNED_BY   IS 'Person or department responsible for this petty cash register';
COMMENT ON COLUMN RR_PC_REGISTERS.CASH_LIMIT IS 'Maximum allowed balance / spending limit for this register';

-- Safe: update STATUS constraint to DRAFT | ACTIVE | INACTIVE | CLOSED
DECLARE l_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO l_count FROM user_constraints
    WHERE  table_name = 'RR_PC_REGISTERS' AND constraint_name = 'RR_PC_REG_STATUS_CK';
    IF l_count > 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE RR_PC_REGISTERS DROP CONSTRAINT RR_PC_REG_STATUS_CK';
    END IF;
    EXECUTE IMMEDIATE q'[ALTER TABLE RR_PC_REGISTERS ADD CONSTRAINT RR_PC_REG_STATUS_CK CHECK (STATUS IN ('DRAFT','ACTIVE','INACTIVE','CLOSED'))]';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- ============================================================
-- 2. RR_PC_TRANSACTIONS  (Petty Cash Lines)
-- ============================================================
DECLARE l_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO l_count FROM user_tables WHERE table_name = 'RR_PC_TRANSACTIONS';
    IF l_count = 0 THEN
        EXECUTE IMMEDIATE q'[
CREATE TABLE RR_PC_TRANSACTIONS (
    TRANSACTION_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REGISTER_ID         NUMBER        NOT NULL,
    LINE_NUMBER         NUMBER,
    TRANSACTION_DATE    DATE          NOT NULL,
    TRANSACTION_TYPE    VARCHAR2(100) NOT NULL,
    EXPENSE_TYPE        VARCHAR2(200),
    CHARGE_ACCOUNT_CCID NUMBER,
    CHARGE_ACCOUNT_DESC VARCHAR2(400),
    ACCOUNTING_DATE     DATE,
    POSTING_STATUS      VARCHAR2(50)  DEFAULT 'Unposted',
    CURRENCY            VARCHAR2(10)  DEFAULT 'AED',
    DEBIT_AMOUNT        NUMBER(18,2)  DEFAULT 0,
    CREDIT_AMOUNT       NUMBER(18,2)  DEFAULT 0,
    COMMENTS            VARCHAR2(1000),
    REFERENCE_NO        VARCHAR2(200),
    ATTACHMENT          VARCHAR2(1000),
    CREATED_BY          VARCHAR2(150),
    CREATION_DATE       TIMESTAMP     DEFAULT SYSTIMESTAMP,
    LAST_UPDATED_BY     VARCHAR2(150),
    LAST_UPDATE_DATE    TIMESTAMP     DEFAULT SYSTIMESTAMP,
    CONSTRAINT RR_PC_TXN_REG_FK      FOREIGN KEY (REGISTER_ID) REFERENCES RR_PC_REGISTERS(REGISTER_ID),
    CONSTRAINT RR_PC_TXN_TYPE_CK     CHECK (TRANSACTION_TYPE IN ('Balance Refill','Expense','Adjustment')),
    CONSTRAINT RR_PC_TXN_POSTING_CK  CHECK (POSTING_STATUS   IN ('Unposted','Posted','Error')),
    CONSTRAINT RR_PC_TXN_DEBIT_CK    CHECK (DEBIT_AMOUNT  >= 0),
    CONSTRAINT RR_PC_TXN_CREDIT_CK   CHECK (CREDIT_AMOUNT >= 0)
)]';
    END IF;
END;
/

