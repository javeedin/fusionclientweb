-- ---------------------------------------------------------------------------
-- 5a.  GET fa/assets/:assetId/attachments  — list
-- ---------------------------------------------------------------------------
BEGIN
  ORDS.DEFINE_HANDLER(
    p_module_name   => 'reerp',
    p_pattern       => 'fa/assets/:assetId/attachments',
    p_method        => 'GET',
    p_source_type   => 'plsql/block',
    p_mimes_allowed => '',
    p_comments      => 'List attachments for an asset',
    p_source        => q'[
DECLARE
  v_result CLOB;
BEGIN
  v_result     := RR_FA_ASSET_ATTACH_PKG.list_attachments(p_asset_id => TO_NUMBER(:assetId));
  :status_code := 200;
  OWA_UTIL.MIME_HEADER('application/json', TRUE);
  HTP.PRN(v_result);
EXCEPTION
  WHEN OTHERS THEN
    :status_code := 500;
    OWA_UTIL.MIME_HEADER('application/json', TRUE);
    HTP.PRN('{"error":"' || REPLACE(SQLERRM,'"','\"') || '"}');
END;]'
  );
  COMMIT;
END;
/


-- ---------------------------------------------------------------------------
-- 5b.  POST fa/assets/:assetId/attachments  — upload
--      Body: JSON { fileName, mimeType, fileSize, fileContent (base64), description, uploadedBy }
-- ---------------------------------------------------------------------------
BEGIN
  ORDS.DEFINE_HANDLER(
    p_module_name   => 'reerp',
    p_pattern       => 'fa/assets/:assetId/attachments',
    p_method        => 'POST',
    p_source_type   => 'plsql/block',
    p_mimes_allowed => 'application/json',
    p_comments      => 'Upload a file attachment for an asset',
    p_source        => q'[
DECLARE
  v_body        CLOB := :body_text;
  v_json        JSON_OBJECT_T;
  v_asset_id      NUMBER  := TO_NUMBER(:assetId);
  v_file_name   VARCHAR2(500);
  v_mime_type   VARCHAR2(200);
  v_file_size   NUMBER;
  v_desc        VARCHAR2(1000);
  v_up_by       VARCHAR2(200);
  v_b64         CLOB;
  v_blob        BLOB;
  v_attach_id   NUMBER;
BEGIN
  v_json := JSON_OBJECT_T.PARSE(v_body);

  v_file_name  := v_json.GET_STRING('fileName');
  v_mime_type  := NVL(v_json.GET_STRING('mimeType'), 'application/octet-stream');
  v_file_size  := v_json.GET_NUMBER('fileSize');
  v_desc       := v_json.GET_STRING('description');
  v_up_by      := v_json.GET_STRING('uploadedBy');
  v_b64        := v_json.GET_CLOB('fileContent');

  RR_FA_ASSET_ATTACH_PKG.base64_to_blob(p_base64 => v_b64, p_blob => v_blob);

  RR_FA_ASSET_ATTACH_PKG.upload_attachment(
    p_asset_id => v_asset_id,
    p_file_name     => v_file_name,
    p_mime_type     => v_mime_type,
    p_file_size     => v_file_size,
    p_file_content  => v_blob,
    p_description   => v_desc,
    p_uploaded_by   => v_up_by,
    p_attach_id     => v_attach_id
  );

  :status_code := 201;
  OWA_UTIL.MIME_HEADER('application/json', TRUE);
  HTP.PRN('{"success": true,"attachmentId":' || v_attach_id || '}');
EXCEPTION
  WHEN OTHERS THEN
    :status_code := 500;
    OWA_UTIL.MIME_HEADER('application/json', TRUE);
    HTP.PRN('{"success": false,"error":"' || REPLACE(SQLERRM,'"','\"') || '"}');
END;]'
  );
  COMMIT;
END;
/


-- ---------------------------------------------------------------------------
-- 6a.  GET fa/assets/:assetId/attachments/:attachmentId  — download
-- ---------------------------------------------------------------------------
BEGIN
  ORDS.DEFINE_HANDLER(
    p_module_name   => 'reerp',
    p_pattern       => 'fa/assets/:assetId/attachments/:attachmentId',
    p_method        => 'GET',
    p_source_type   => 'plsql/block',
    p_mimes_allowed => '',
    p_comments      => 'Download a specific asset attachment as binary',
    p_source        => q'[
DECLARE
  v_file_name VARCHAR2(500);
  v_mime_type VARCHAR2(200);
  v_file_size NUMBER;
  v_content   BLOB;
BEGIN
  RR_FA_ASSET_ATTACH_PKG.get_attachment(
    p_attach_id  => TO_NUMBER(:attachmentId),
    p_file_name  => v_file_name,
    p_mime_type  => v_mime_type,
    p_file_size  => v_file_size,
    p_content    => v_content
  );

  IF v_file_name IS NULL THEN
    :status_code := 404;
    OWA_UTIL.MIME_HEADER('application/json', TRUE);
    HTP.PRN('{"error":"Attachment not found"}');
    RETURN;
  END IF;

  OWA_UTIL.MIME_HEADER(NVL(v_mime_type, 'application/octet-stream'), FALSE);
  HTP.P('Content-Disposition: attachment; filename="' || v_file_name || '"');
  HTP.P('Content-Length: ' || DBMS_LOB.GETLENGTH(v_content));
  OWA_UTIL.HTTP_HEADER_CLOSE;
  WPG_DOCLOAD.DOWNLOAD_FILE(v_content);
  :status_code := 200;
EXCEPTION
  WHEN OTHERS THEN
    :status_code := 500;
    OWA_UTIL.MIME_HEADER('application/json', TRUE);
    HTP.PRN('{"error":"' || REPLACE(SQLERRM,'"','\"') || '"}');
END;]'
  );
  COMMIT;
END;
/


