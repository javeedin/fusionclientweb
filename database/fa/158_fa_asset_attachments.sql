-- ---------------------------------------------------------------------------
-- 3.  Package body
-- ---------------------------------------------------------------------------
CREATE OR REPLACE PACKAGE BODY RR_FA_ASSET_ATTACH_PKG AS

  -- ── JSON helpers ────────────────────────────────────────────────────────
  FUNCTION esc(p IN VARCHAR2) RETURN VARCHAR2 IS
  BEGIN
    RETURN REPLACE(REPLACE(p, CHR(92), CHR(92)||CHR(92)), '"', CHR(92)||'"');
  END;
  FUNCTION jstr(p IN VARCHAR2) RETURN VARCHAR2 IS
  BEGIN
    RETURN CASE WHEN p IS NULL THEN 'null' ELSE '"'||esc(p)||'"' END;
  END;
  FUNCTION jnum(p IN NUMBER) RETURN VARCHAR2 IS
  BEGIN
    RETURN CASE WHEN p IS NULL THEN 'null' ELSE TO_CHAR(p) END;
  END;
  FUNCTION jts(p IN TIMESTAMP) RETURN VARCHAR2 IS
  BEGIN
    RETURN CASE WHEN p IS NULL THEN 'null'
           ELSE '"'||TO_CHAR(p,'YYYY-MM-DD"T"HH24:MI:SS')||'"' END;
  END;

  -- ── base64 → BLOB ────────────────────────────────────────────────────────
  PROCEDURE base64_to_blob (
    p_base64  IN  CLOB,
    p_blob    OUT BLOB
  ) IS
    v_chunk  VARCHAR2(32767);
    v_raw    RAW(24576);
    v_offset PLS_INTEGER := 1;
    v_total  PLS_INTEGER;
    c_amt    CONSTANT PLS_INTEGER := 24576;  -- multiple of 4 → clean base64 boundary
  BEGIN
    DBMS_LOB.CREATETEMPORARY(p_blob, TRUE, DBMS_LOB.SESSION);
    v_total := DBMS_LOB.GETLENGTH(p_base64);
    WHILE v_offset <= v_total LOOP
      v_chunk := DBMS_LOB.SUBSTR(p_base64, c_amt, v_offset);
      EXIT WHEN v_chunk IS NULL OR LENGTH(v_chunk) = 0;
      v_raw := UTL_ENCODE.BASE64_DECODE(UTL_RAW.CAST_TO_RAW(v_chunk));
      DBMS_LOB.WRITEAPPEND(p_blob, UTL_RAW.LENGTH(v_raw), v_raw);
      v_offset := v_offset + c_amt;
    END LOOP;
  EXCEPTION
    WHEN OTHERS THEN
      IF DBMS_LOB.ISTEMPORARY(p_blob) = 1 THEN
        DBMS_LOB.FREETEMPORARY(p_blob);
      END IF;
      RAISE;
  END base64_to_blob;

  -- ── Upload ───────────────────────────────────────────────────────────────
  PROCEDURE upload_attachment (
    p_asset_id IN  NUMBER,
    p_file_name     IN  VARCHAR2,
    p_mime_type     IN  VARCHAR2,
    p_file_size     IN  NUMBER,
    p_file_content  IN  BLOB,
    p_description   IN  VARCHAR2,
    p_uploaded_by   IN  VARCHAR2,
    p_attach_id     OUT NUMBER
  ) IS
  BEGIN
    INSERT INTO RR_FA_ASSET_ATTACHMENTS (
      ASSET_ID, FILE_NAME, FILE_SIZE, MIME_TYPE,
      FILE_CONTENT, DESCRIPTION, STATUS, UPLOADED_BY, UPLOAD_DATE
    ) VALUES (
      p_asset_id, p_file_name, p_file_size, p_mime_type,
      p_file_content, p_description, 'ACTIVE', p_uploaded_by, SYSTIMESTAMP
    )
    RETURNING ATTACHMENT_ID INTO p_attach_id;
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN ROLLBACK; RAISE;
  END upload_attachment;

  -- ── List ─────────────────────────────────────────────────────────────────
  FUNCTION list_attachments (
    p_asset_id IN NUMBER
  ) RETURN CLOB IS
    v_buf   CLOB    := '{"attachments":[';
    v_first BOOLEAN := TRUE;
  BEGIN
    FOR r IN (
      SELECT ATTACHMENT_ID, FILE_NAME, FILE_SIZE, MIME_TYPE,
             DESCRIPTION, UPLOADED_BY, UPLOAD_DATE
        FROM RR_FA_ASSET_ATTACHMENTS
       WHERE ASSET_ID = p_asset_id
         AND STATUS        = 'ACTIVE'
       ORDER BY UPLOAD_DATE DESC
    ) LOOP
      IF NOT v_first THEN v_buf := v_buf || ','; END IF;
      v_first := FALSE;
      v_buf := v_buf || '{'
        || '"attachmentId":'  || jnum(r.ATTACHMENT_ID) || ','
        || '"fileName":'      || jstr(r.FILE_NAME)     || ','
        || '"fileSize":'      || jnum(r.FILE_SIZE)     || ','
        || '"mimeType":'      || jstr(r.MIME_TYPE)     || ','
        || '"description":'   || jstr(r.DESCRIPTION)   || ','
        || '"uploadedBy":'    || jstr(r.UPLOADED_BY)   || ','
        || '"uploadDate":'    || jts(r.UPLOAD_DATE)
      || '}';
    END LOOP;
    RETURN v_buf || ']}';
  END list_attachments;

  -- ── Get one (for download) ────────────────────────────────────────────────
  PROCEDURE get_attachment (
    p_attach_id   IN  NUMBER,
    p_file_name   OUT VARCHAR2,
    p_mime_type   OUT VARCHAR2,
    p_file_size   OUT NUMBER,
    p_content     OUT BLOB
  ) IS
  BEGIN
    SELECT FILE_NAME, MIME_TYPE, FILE_SIZE, FILE_CONTENT
      INTO p_file_name, p_mime_type, p_file_size, p_content
      FROM RR_FA_ASSET_ATTACHMENTS
     WHERE ATTACHMENT_ID = p_attach_id
       AND STATUS        = 'ACTIVE';
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      p_file_name := NULL; p_mime_type := NULL;
      p_file_size := NULL; p_content   := NULL;
  END get_attachment;

  -- ── Soft delete ──────────────────────────────────────────────────────────
  PROCEDURE delete_attachment (
    p_attach_id  IN NUMBER,
    p_deleted_by IN VARCHAR2
  ) IS
  BEGIN
    UPDATE RR_FA_ASSET_ATTACHMENTS
       SET STATUS = 'DELETED'
     WHERE ATTACHMENT_ID = p_attach_id;
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN ROLLBACK; RAISE;
  END delete_attachment;

END RR_FA_ASSET_ATTACH_PKG;
