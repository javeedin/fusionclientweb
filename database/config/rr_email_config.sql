-- ============================================================
-- Table: RR_EMAIL_CONFIG
-- Description: SMTP email configuration stored in DB so credentials
--              can be updated without rebuilding the Electron exe.
-- ============================================================

CREATE TABLE RR_EMAIL_CONFIG (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SMTP_HOST    VARCHAR2(200)  NOT NULL,
    SMTP_PORT    NUMBER         DEFAULT 587,
    SMTP_SECURE  VARCHAR2(5)   DEFAULT 'false',
    SMTP_USER    VARCHAR2(200)  NOT NULL,
    SMTP_PASS    VARCHAR2(1000) NOT NULL,
    FROM_NAME    VARCHAR2(200)  DEFAULT 'ReactERP',
    UPDATED_DATE TIMESTAMP      DEFAULT SYSTIMESTAMP,
    UPDATED_BY   VARCHAR2(150)
);

