-- ============================================================
-- Table: RR_EXTERNAL_TRX_ATTACHMENTS
-- Stores file attachments for external cash transactions
-- ============================================================

CREATE TABLE RR_EXTERNAL_TRX_ATTACHMENTS (
    ID                      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EXTERNAL_TRANSACTION_ID NUMBER NOT NULL,
    FILE_NAME               VARCHAR2(500) NOT NULL,
    FILE_TYPE               VARCHAR2(100),
    FILE_SIZE               NUMBER,
    FILE_CONTENT            CLOB,  -- Base64-encoded file content
    CREATED_BY              VARCHAR2(150),
    CREATED_DATE            TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT FK_EXT_TRX_ATT FOREIGN KEY (EXTERNAL_TRANSACTION_ID)
        REFERENCES RR_EXTERNAL_CASH_TRANSACTIONS(EXTERNAL_TRANSACTION_ID)
);

CREATE INDEX IDX_RR_ETA_TRX_ID ON RR_EXTERNAL_TRX_ATTACHMENTS(EXTERNAL_TRANSACTION_ID);

