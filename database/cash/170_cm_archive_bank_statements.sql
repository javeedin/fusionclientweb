-- =============================================================================
-- Cash Management — 170: archive bank reconciliations
--
--   An archive freezes a reconciled bank statement together with the GL account
--   analysis of the bank's cash account for the chosen period, the manual
--   reconciliation working the user pastes in, and supporting attachments.
--
--   Tables
--     RR_ARCHIVE_BANK_STATEMENTS      one row per archive (header, balances, summary)
--     RR_ARCHIVE_BANK_STMT_GL_LINES   account analysis snapshot (GL lines of the cash account)
--     RR_ARCHIVE_BANK_STMT_MANUAL     manual reconciled data, one row per pasted line
--     RR_ARCHIVE_BANK_STMT_ATTACH     attachments (BLOB)
--     RR_CM_PROC_REGISTRY / RR_CM_EXEC_LOG   write gateway registry + call log
--
--   Writes  — POST reerp/cash/execute  { "proc": "...", "params": {...}, "user": "..." }
--             (RR_CM_EXECUTE: only procedures registered in RR_CM_PROC_REGISTRY;
--              commit on S/W, rollback on E; every call logged in RR_CM_EXEC_LOG)
--     RR_CM_ARCHIVE_PKG.CREATE_ARCHIVE     (p_json)
--     RR_CM_ARCHIVE_PKG.UPDATE_ARCHIVE     (p_archive_id, p_json)
--     RR_CM_ARCHIVE_PKG.REFRESH_ANALYSIS   (p_archive_id)
--     RR_CM_ARCHIVE_PKG.ADD_ATTACHMENT     (p_archive_id, p_json: fileName, mimeType, description, fileContent base64)
--     RR_CM_ARCHIVE_PKG.DELETE_ATTACHMENT  (p_attachment_id)
--     RR_CM_ARCHIVE_PKG.CANCEL_ARCHIVE     (p_archive_id, p_reason)
--
--   Reads   — POST reerp/ai/executequery (guarded SELECT gateway) over
--     RR_CM_V_ARCHIVES, RR_CM_V_ARCHIVE_GL_LINES, RR_CM_V_ARCHIVE_MANUAL,
--     RR_CM_V_ARCHIVE_ATTACH, RR_CM_V_ARCHIVE_ATT_CHUNKS (file content, base64, 2400-byte chunks)
--
--   The cash account comes from RR_BANK_ACCOUNTS.CASH_ACCOUNT_COMBINATION, found by the
--   statement's bank account number (then by name). The account analysis reads
--   V_GL_JOURNAL_LINES_SEGMENTS — the same source as the GL Account Analysis page.
--
-- Run as the schema owner (SQL Developer / SQLcl, run as script). Safe to re-run.
-- =============================================================================

