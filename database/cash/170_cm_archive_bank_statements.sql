CREATE OR REPLACE PACKAGE BODY RR_CM_ARCHIVE_PKG AS

    C_CHUNK     CONSTANT PLS_INTEGER := 2400;           -- bytes per downloaded chunk (3200 base64 chars)
    C_MAX_FILE  CONSTANT PLS_INTEGER := 20 * 1024 * 1024;

    -- ── helpers ──────────────────────────────────────────────────────────────
    PROCEDURE err (p_msg IN VARCHAR2) IS
    BEGIN
        RAISE_APPLICATION_ERROR(-20001, SUBSTR(p_msg, 1, 2000));
    END;

    FUNCTION err_text (p_sqlerrm IN VARCHAR2) RETURN VARCHAR2 IS
        v VARCHAR2(4000) := p_sqlerrm;
    BEGIN
        IF v LIKE 'ORA-20001:%' THEN
            v := TRIM(SUBSTR(v, 11));
            IF INSTR(v, CHR(10) || 'ORA-06512') > 0 THEN v := SUBSTR(v, 1, INSTR(v, CHR(10) || 'ORA-06512') - 1); END IF;
        END IF;
        RETURN SUBSTR(v, 1, 4000);
    END;

    FUNCTION to_num (p IN VARCHAR2) RETURN NUMBER IS
    BEGIN
        RETURN TO_NUMBER(REPLACE(TRIM(p), ',', '') DEFAULT NULL ON CONVERSION ERROR);
    END;

    FUNCTION jstr (o IN JSON_OBJECT_T, k IN VARCHAR2) RETURN VARCHAR2 IS
        e JSON_ELEMENT_T;
    BEGIN
        IF o IS NULL OR NOT o.has(k) THEN RETURN NULL; END IF;
        e := o.get(k);
        IF e IS NULL OR e.is_null THEN RETURN NULL; END IF;
        IF e.is_string THEN RETURN o.get_string(k);
        ELSIF e.is_number THEN RETURN TO_CHAR(o.get_number(k), 'TM9', 'NLS_NUMERIC_CHARACTERS=''.,''');
        ELSE RETURN e.to_string;
        END IF;
    END;

    FUNCTION jnum (o IN JSON_OBJECT_T, k IN VARCHAR2) RETURN NUMBER IS
        e JSON_ELEMENT_T;
    BEGIN
        IF o IS NULL OR NOT o.has(k) THEN RETURN NULL; END IF;
        e := o.get(k);
        IF e IS NULL OR e.is_null THEN RETURN NULL; END IF;
        IF e.is_number THEN RETURN o.get_number(k); END IF;
        RETURN to_num(jstr(o, k));
    END;

    FUNCTION jdate (o IN JSON_OBJECT_T, k IN VARCHAR2) RETURN DATE IS
        v VARCHAR2(4000) := jstr(o, k);
    BEGIN
        IF v IS NULL THEN RETURN NULL; END IF;
        RETURN TO_DATE(SUBSTR(TRIM(v), 1, 10) DEFAULT NULL ON CONVERSION ERROR, 'YYYY-MM-DD');
    END;

    FUNCTION jclob (o IN JSON_OBJECT_T, k IN VARCHAR2) RETURN CLOB IS
        e JSON_ELEMENT_T;
    BEGIN
        IF o IS NULL OR NOT o.has(k) THEN RETURN NULL; END IF;
        e := o.get(k);
        IF e IS NULL OR e.is_null THEN RETURN NULL; END IF;
        IF e.is_string THEN RETURN o.get_clob(k); END IF;
        RETURN e.to_clob;
    END;

    FUNCTION comments_of (o IN JSON_OBJECT_T) RETURN VARCHAR2 IS
        v VARCHAR2(32767) := jstr(o, 'comments');
    BEGIN
        IF LENGTHB(v) > 4000 THEN err('Comments are too long (at most 4000 bytes)'); END IF;
        RETURN v;
    END;

    FUNCTION arc (p_id IN NUMBER, p_lock IN BOOLEAN DEFAULT TRUE) RETURN RR_ARCHIVE_BANK_STATEMENTS%ROWTYPE IS
        r RR_ARCHIVE_BANK_STATEMENTS%ROWTYPE;
    BEGIN
        IF p_lock THEN SELECT * INTO r FROM RR_ARCHIVE_BANK_STATEMENTS WHERE ARCHIVE_ID = p_id FOR UPDATE;
        ELSE SELECT * INTO r FROM RR_ARCHIVE_BANK_STATEMENTS WHERE ARCHIVE_ID = p_id; END IF;
        RETURN r;
    EXCEPTION WHEN NO_DATA_FOUND THEN err('Archive ' || p_id || ' not found'); RETURN r;
    END;

    -- the bank account's cash account: by account number, then by name
    FUNCTION cash_account_of (p_number IN VARCHAR2, p_name IN VARCHAR2) RETURN VARCHAR2 IS
        v VARCHAR2(500);
    BEGIN
        IF p_number IS NOT NULL THEN
            SELECT MAX(CASH_ACCOUNT_COMBINATION) INTO v FROM RR_BANK_ACCOUNTS
            WHERE  (BANK_ACCOUNT_NUMBER = p_number OR BANK_ACCOUNT_NUMBER_ELECTRONIC = p_number OR IBAN_NUMBER = p_number)
            AND    CASH_ACCOUNT_COMBINATION IS NOT NULL;
        END IF;
        IF v IS NULL AND p_name IS NOT NULL THEN
            SELECT MAX(CASH_ACCOUNT_COMBINATION) INTO v FROM RR_BANK_ACCOUNTS
            WHERE  UPPER(BANK_ACCOUNT_NAME) = UPPER(TRIM(REGEXP_REPLACE(p_name, '\s*\([A-Z]{3}\)\s*$', '')))
            AND    CASH_ACCOUNT_COMBINATION IS NOT NULL;
        END IF;
        RETURN v;
    END;

    -- account analysis of the cash account for the archive period → GL lines + summary
    PROCEDURE snapshot_analysis (p_id IN NUMBER) IS
        a      RR_ARCHIVE_BANK_STATEMENTS%ROWTYPE := arc(p_id, FALSE);
        v_n    NUMBER;
        v_dr   NUMBER;
        v_cr   NUMBER;
        v_open NUMBER;
    BEGIN
        DELETE FROM RR_ARCHIVE_BANK_STMT_GL_LINES WHERE ARCHIVE_ID = p_id;
        INSERT INTO RR_ARCHIVE_BANK_STMT_GL_LINES (
            ARCHIVE_ID, LINE_SEQ, JE_BATCH_ID, JE_HEADER_ID, JE_LINE_NUMBER, ACCOUNTING_DATE, PERIOD_NAME, BATCH_NAME,
            JOURNAL_NAME, JE_SOURCE, JE_CATEGORY, ACCOUNT_COMBINATION, ACCOUNT_DESCRIPTION, LINE_DESCRIPTION, CURRENCY_CODE,
            ENTERED_DR, ENTERED_CR, ACCOUNTED_DR, ACCOUNTED_CR, REFERENCE1, REFERENCE2, REFERENCE3, REFERENCE4, REFERENCE5,
            APPROVAL_STATUS, LEDGER_NAME)
        SELECT p_id, ROW_NUMBER() OVER (ORDER BY x.ACCOUNTING_DATE, x.JE_HEADER_ID, x.JE_LINE_NUMBER),
               x.BATCH_ID, x.JE_HEADER_ID, x.JE_LINE_NUMBER, x.ACCOUNTING_DATE, SUBSTRB(x.DEFAULT_PERIOD_NAME, 1, 30),
               SUBSTRB(x.BATCH_NAME, 1, 240), SUBSTRB(x.JOURNAL_NAME, 1, 240), SUBSTRB(x.USER_JE_SOURCE_NAME, 1, 240),
               SUBSTRB(x.USER_JE_CATEGORY_NAME, 1, 240), SUBSTRB(x.ACCOUNT_COMBINATION, 1, 500), SUBSTRB(x.ACCOUNT_DESCRIPTION, 1, 240),
               SUBSTRB(x.LINE_DESCRIPTION, 1, 4000), x.CURRENCY_CODE, x.ENTERED_DR, x.ENTERED_CR, x.ACCOUNTED_DR, x.ACCOUNTED_CR,
               x.REFERENCE1, x.REFERENCE2, x.REFERENCE3, x.REFERENCE4, x.REFERENCE5,
               SUBSTRB(x.APPROVAL_STATUS_MEANING, 1, 80), SUBSTRB(x.LEDGER_NAME, 1, 240)
        FROM (
            SELECT v.*, h.JOURNAL_NAME,
                   COALESCE(l.DESCRIPTION, h.JOURNAL_DESCRIPTION, h.JOURNAL_NAME) AS LINE_DESCRIPTION,
                   l.REFERENCE1, l.REFERENCE2, l.REFERENCE3, l.REFERENCE4, l.REFERENCE5,
                   ROW_NUMBER() OVER (PARTITION BY v.JE_HEADER_ID, v.JE_LINE_NUMBER ORDER BY v.BATCH_ID) AS RN
            FROM   V_GL_JOURNAL_LINES_SEGMENTS v
            LEFT   JOIN RR_GL_JE_LINES_ALL l ON l.JE_HEADER_ID = v.JE_HEADER_ID AND l.JE_LINE_NUMBER = v.JE_LINE_NUMBER
            LEFT   JOIN RR_GL_JE_HEADERS   h ON h.JE_HEADER_ID = v.JE_HEADER_ID
            WHERE  v.ACCOUNT_COMBINATION = a.CASH_ACCOUNT
            AND    v.ACCOUNTING_DATE >= a.DATE_FROM
            AND    v.ACCOUNTING_DATE <  a.DATE_TO + 1
        ) x
        WHERE x.RN = 1;

        SELECT COUNT(*), NVL(SUM(ENTERED_DR), 0), NVL(SUM(ENTERED_CR), 0) INTO v_n, v_dr, v_cr
        FROM   RR_ARCHIVE_BANK_STMT_GL_LINES WHERE ARCHIVE_ID = p_id;

        BEGIN   -- balance brought forward: everything on the cash account before the period
            SELECT NVL(SUM(NVL(dr, 0) - NVL(cr, 0)), 0) INTO v_open
            FROM  (SELECT MAX(ENTERED_DR) dr, MAX(ENTERED_CR) cr
                   FROM   V_GL_JOURNAL_LINES_SEGMENTS
                   WHERE  ACCOUNT_COMBINATION = a.CASH_ACCOUNT AND ACCOUNTING_DATE < a.DATE_FROM
                   GROUP  BY JE_HEADER_ID, JE_LINE_NUMBER);
        EXCEPTION WHEN OTHERS THEN v_open := NULL;
        END;

        UPDATE RR_ARCHIVE_BANK_STATEMENTS
        SET    GL_LINE_COUNT = v_n, GL_TOTAL_DR = v_dr, GL_TOTAL_CR = v_cr, GL_OPENING_BALANCE = v_open,
               GL_CLOSING_BALANCE = CASE WHEN v_open IS NULL THEN NULL ELSE v_open + v_dr - v_cr END,
               ANALYSIS_DATE = SYSTIMESTAMP
        WHERE  ARCHIVE_ID = p_id;
    END;

    -- manual reconciled data: one row per pasted line (cells stay tab-separated)
    PROCEDURE save_manual (p_id IN NUMBER, p_text IN CLOB) IS
        v_len  NUMBER := NVL(DBMS_LOB.GETLENGTH(p_text), 0);
        v_pos  NUMBER := 1;
        v_nl   NUMBER;
        v_line VARCHAR2(32767);
        v_n    NUMBER := 0;
        v_last NUMBER := 0;
    BEGIN
        DELETE FROM RR_ARCHIVE_BANK_STMT_MANUAL WHERE ARCHIVE_ID = p_id;
        WHILE v_pos <= v_len LOOP
            v_nl := DBMS_LOB.INSTR(p_text, CHR(10), v_pos);
            IF v_nl = 0 THEN v_nl := v_len + 1; END IF;
            IF v_nl - v_pos > 8000 THEN err('Manual data line ' || (v_n + 1) || ' is too long (more than 4000 bytes)'); END IF;
            v_line := CASE WHEN v_nl > v_pos THEN DBMS_LOB.SUBSTR(p_text, v_nl - v_pos, v_pos) END;
            v_line := RTRIM(v_line, CHR(13));
            IF LENGTHB(v_line) > 4000 THEN err('Manual data line ' || (v_n + 1) || ' is too long (more than 4000 bytes)'); END IF;
            v_n := v_n + 1;
            IF v_n > 50000 THEN err('Manual data has more than 50,000 lines'); END IF;
            INSERT INTO RR_ARCHIVE_BANK_STMT_MANUAL (ARCHIVE_ID, LINE_NUM, LINE_TEXT) VALUES (p_id, v_n, v_line);
            IF TRIM(REPLACE(v_line, CHR(9))) IS NOT NULL THEN v_last := v_n; END IF;
            v_pos := v_nl + 1;
        END LOOP;
        DELETE FROM RR_ARCHIVE_BANK_STMT_MANUAL WHERE ARCHIVE_ID = p_id AND LINE_NUM > v_last;   -- trailing blank lines
    END;

