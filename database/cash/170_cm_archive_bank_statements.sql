    PROCEDURE CREATE_ARCHIVE (p_json IN CLOB, p_user IN VARCHAR2,
                              p_id OUT NUMBER, p_number OUT VARCHAR2, p_status OUT VARCHAR2, p_message OUT VARCHAR2) IS
        o      JSON_OBJECT_T;
        h      RR_BANK_STATEMENT_HEADER%ROWTYPE;
        v_stmt NUMBER;
        v_from DATE;
        v_to   DATE;
        v_rec  DATE;
        v_cmt  VARCHAR2(4000);
        v_cash VARCHAR2(4000);
        v_prev VARCHAR2(30);
        v_id   NUMBER;
        v_num  VARCHAR2(30);
        v_tot  NUMBER; v_rcn NUMBER;
        v_gl   NUMBER;
    BEGIN
        o := JSON_OBJECT_T.parse(p_json);
        v_stmt := jnum(o, 'statementId');
        IF v_stmt IS NULL THEN err('Choose the bank statement to archive'); END IF;
        BEGIN
            SELECT * INTO h FROM RR_BANK_STATEMENT_HEADER WHERE STATEMENT_ID = v_stmt;
        EXCEPTION WHEN NO_DATA_FOUND THEN err('Bank statement ' || v_stmt || ' not found');
        END;
        SELECT MAX(ARCHIVE_NUMBER) INTO v_prev FROM RR_ARCHIVE_BANK_STATEMENTS WHERE STATEMENT_ID = v_stmt AND STATUS = 'ARCHIVED';
        IF v_prev IS NOT NULL THEN
            err('Statement ' || h.STATEMENT_NUMBER || ' is already archived as ' || v_prev
                || '. Open it from Archived Statements to change it, or cancel that archive first.');
        END IF;

        v_from := jdate(o, 'dateFrom');
        v_to   := jdate(o, 'dateTo');
        IF v_from IS NULL OR v_to IS NULL THEN err('Date from and date to are required'); END IF;
        IF v_from > v_to THEN err('Date from must not be after date to'); END IF;
        v_rec := NVL(jdate(o, 'reconciledDate'), TRUNC(SYSDATE));
        v_cmt := comments_of(o);
        v_cash := TRIM(jstr(o, 'cashAccount'));
        IF v_cash IS NULL THEN v_cash := cash_account_of(h.BANK_ACCOUNT_NUMBER, h.BANK_ACCOUNT_NAME); END IF;
        IF v_cash IS NULL THEN
            err('Bank account ' || NVL(h.BANK_ACCOUNT_NUMBER, h.BANK_ACCOUNT_NAME)
                || ' has no cash account combination — set it on the bank account first');
        END IF;
        IF LENGTH(v_cash) > 500 THEN err('Cash account is too long'); END IF;

        SELECT COUNT(*), NVL(SUM(CASE WHEN NVL(RECON_STATUS, 'UNRECONCILED') = 'RECONCILED' THEN 1 ELSE 0 END), 0)
        INTO   v_tot, v_rcn
        FROM   RR_BANK_STATEMENT_LINES WHERE STATEMENT_ID = v_stmt;

        INSERT INTO RR_ARCHIVE_BANK_STATEMENTS (
            STATEMENT_ID, STATEMENT_NUMBER, STATEMENT_DATE, BUSINESS_UNIT_NAME, BANK_ACCOUNT_NAME, BANK_ACCOUNT_NUMBER,
            CURRENCY_CODE, CASH_ACCOUNT, DATE_FROM, DATE_TO, RECONCILED_DATE, COMMENTS,
            STMT_OPENING_BALANCE, STMT_CLOSING_BALANCE, STMT_TOTAL_LINES, STMT_RECON_LINES, STMT_UNRECON_LINES,
            STATUS, CREATED_BY, LAST_UPDATED_BY, LAST_UPDATE_DATE)
        VALUES (
            v_stmt, h.STATEMENT_NUMBER, h.STATEMENT_DATE, h.BUSINESS_UNIT_NAME, h.BANK_ACCOUNT_NAME, h.BANK_ACCOUNT_NUMBER,
            h.CURRENCY_CODE, v_cash, v_from, v_to, v_rec, v_cmt,
            h.OPENING_BALANCE, h.CLOSING_BALANCE, v_tot, v_rcn, v_tot - v_rcn,
            'ARCHIVED', p_user, p_user, SYSTIMESTAMP)
        RETURNING ARCHIVE_ID INTO v_id;

        v_num := 'ARC-' || LPAD(TO_CHAR(v_id), GREATEST(6, LENGTH(TO_CHAR(v_id))), '0');
        UPDATE RR_ARCHIVE_BANK_STATEMENTS SET ARCHIVE_NUMBER = v_num WHERE ARCHIVE_ID = v_id;

        snapshot_analysis(v_id);
        IF o.has('manualText') THEN save_manual(v_id, jclob(o, 'manualText')); END IF;

        SELECT GL_LINE_COUNT INTO v_gl FROM RR_ARCHIVE_BANK_STATEMENTS WHERE ARCHIVE_ID = v_id;
        p_id := v_id; p_number := v_num; p_status := 'S';
        p_message := 'Statement ' || h.STATEMENT_NUMBER || ' archived as ' || v_num || ' (' || v_gl || ' GL line'
                     || CASE WHEN v_gl = 1 THEN '' ELSE 's' END || ')';
    EXCEPTION WHEN OTHERS THEN
        p_status := 'E'; p_message := err_text(SQLERRM);
    END;

    PROCEDURE UPDATE_ARCHIVE (p_archive_id IN VARCHAR2, p_json IN CLOB, p_user IN VARCHAR2,
                              p_id OUT NUMBER, p_number OUT VARCHAR2, p_status OUT VARCHAR2, p_message OUT VARCHAR2) IS
        v_id   NUMBER := to_num(p_archive_id);
        a      RR_ARCHIVE_BANK_STATEMENTS%ROWTYPE;
        o      JSON_OBJECT_T;
        v_from DATE;
        v_to   DATE;
        v_rec  DATE;
        v_cmt  VARCHAR2(4000);
        v_redo BOOLEAN := FALSE;
    BEGIN
        a := arc(v_id);
        IF a.STATUS <> 'ARCHIVED' THEN err('Archive ' || a.ARCHIVE_NUMBER || ' is ' || a.STATUS || ' and cannot be changed'); END IF;
        o := JSON_OBJECT_T.parse(p_json);
        -- JSON values are read into variables first: SQL cannot take PL/SQL JSON objects (ORA-40573)
        v_from := a.DATE_FROM; v_to := a.DATE_TO; v_rec := a.RECONCILED_DATE; v_cmt := a.COMMENTS;
        IF o.has('dateFrom') THEN v_from := NVL(jdate(o, 'dateFrom'), a.DATE_FROM); END IF;
        IF o.has('dateTo')   THEN v_to   := NVL(jdate(o, 'dateTo'),   a.DATE_TO);   END IF;
        IF o.has('reconciledDate') THEN v_rec := jdate(o, 'reconciledDate'); END IF;
        IF o.has('comments') THEN v_cmt := comments_of(o); END IF;
        IF v_from > v_to THEN err('Date from must not be after date to'); END IF;
        v_redo := v_from <> a.DATE_FROM OR v_to <> a.DATE_TO;

        UPDATE RR_ARCHIVE_BANK_STATEMENTS
        SET    DATE_FROM = v_from, DATE_TO = v_to, RECONCILED_DATE = v_rec, COMMENTS = v_cmt,
               LAST_UPDATED_BY = p_user, LAST_UPDATE_DATE = SYSTIMESTAMP
        WHERE  ARCHIVE_ID = v_id;
        IF o.has('manualText') THEN save_manual(v_id, jclob(o, 'manualText')); END IF;
        IF v_redo THEN snapshot_analysis(v_id); END IF;

        p_id := v_id; p_number := a.ARCHIVE_NUMBER; p_status := 'S';
        p_message := a.ARCHIVE_NUMBER || ' saved' || CASE WHEN v_redo THEN ' — account analysis taken again for the new dates' END;
    EXCEPTION WHEN OTHERS THEN
        p_status := 'E'; p_message := err_text(SQLERRM);
    END;

    PROCEDURE REFRESH_ANALYSIS (p_archive_id IN VARCHAR2, p_user IN VARCHAR2,
                                p_id OUT NUMBER, p_number OUT VARCHAR2, p_status OUT VARCHAR2, p_message OUT VARCHAR2) IS
        v_id NUMBER := to_num(p_archive_id);
        a    RR_ARCHIVE_BANK_STATEMENTS%ROWTYPE;
        v_n  NUMBER;
    BEGIN
        a := arc(v_id);
        IF a.STATUS <> 'ARCHIVED' THEN err('Archive ' || a.ARCHIVE_NUMBER || ' is ' || a.STATUS); END IF;
        snapshot_analysis(v_id);
        UPDATE RR_ARCHIVE_BANK_STATEMENTS SET LAST_UPDATED_BY = p_user, LAST_UPDATE_DATE = SYSTIMESTAMP WHERE ARCHIVE_ID = v_id;
        SELECT GL_LINE_COUNT INTO v_n FROM RR_ARCHIVE_BANK_STATEMENTS WHERE ARCHIVE_ID = v_id;
        p_id := v_id; p_number := a.ARCHIVE_NUMBER; p_status := 'S';
        p_message := 'Account analysis taken again (' || v_n || ' GL line' || CASE WHEN v_n = 1 THEN '' ELSE 's' END || ')';
    EXCEPTION WHEN OTHERS THEN
        p_status := 'E'; p_message := err_text(SQLERRM);
    END;

    PROCEDURE ADD_ATTACHMENT (p_archive_id IN VARCHAR2, p_json IN CLOB, p_user IN VARCHAR2,
                              p_id OUT NUMBER, p_number OUT VARCHAR2, p_status OUT VARCHAR2, p_message OUT VARCHAR2) IS
        v_id   NUMBER := to_num(p_archive_id);
        a      RR_ARCHIVE_BANK_STATEMENTS%ROWTYPE;
        o      JSON_OBJECT_T;
        v_b64  CLOB;
        v_blob BLOB;
        v_name VARCHAR2(4000);
        v_pos  PLS_INTEGER := 1;
        v_len  PLS_INTEGER;
        v_amt  CONSTANT PLS_INTEGER := 24576;    -- multiple of 4: clean base64 chunks
        v_raw  RAW(24576);
        v_att  NUMBER;
        v_mime VARCHAR2(200);
        v_desc VARCHAR2(1000);
    BEGIN
        a := arc(v_id, FALSE);
        IF a.STATUS <> 'ARCHIVED' THEN err('Archive ' || a.ARCHIVE_NUMBER || ' is ' || a.STATUS); END IF;
        o := JSON_OBJECT_T.parse(p_json);
        v_name := TRIM(jstr(o, 'fileName'));
        IF v_name IS NULL THEN err('File name is required'); END IF;
        v_mime := SUBSTR(jstr(o, 'mimeType'), 1, 200);      -- read first: SQL cannot take PL/SQL JSON objects
        v_desc := SUBSTRB(jstr(o, 'description'), 1, 1000);
        v_b64 := jclob(o, 'fileContent');
        IF v_b64 IS NULL OR DBMS_LOB.GETLENGTH(v_b64) = 0 THEN err('The file is empty'); END IF;
        IF DBMS_LOB.GETLENGTH(v_b64) > C_MAX_FILE * 4 / 3 + 8 THEN err('The file is larger than 20 MB'); END IF;
        DBMS_LOB.CREATETEMPORARY(v_blob, TRUE);
        v_len := DBMS_LOB.GETLENGTH(v_b64);
        WHILE v_pos <= v_len LOOP
            v_raw := UTL_ENCODE.BASE64_DECODE(UTL_RAW.CAST_TO_RAW(DBMS_LOB.SUBSTR(v_b64, v_amt, v_pos)));
            DBMS_LOB.WRITEAPPEND(v_blob, UTL_RAW.LENGTH(v_raw), v_raw);
            v_pos := v_pos + v_amt;
        END LOOP;
        INSERT INTO RR_ARCHIVE_BANK_STMT_ATTACH (ARCHIVE_ID, FILE_NAME, MIME_TYPE, FILE_SIZE, FILE_CONTENT, DESCRIPTION, UPLOADED_BY)
        VALUES (v_id, SUBSTRB(v_name, 1, 500), v_mime, DBMS_LOB.GETLENGTH(v_blob), v_blob, v_desc, p_user)
        RETURNING ATTACHMENT_ID INTO v_att;
        DBMS_LOB.FREETEMPORARY(v_blob);
        p_id := v_att; p_number := a.ARCHIVE_NUMBER; p_status := 'S'; p_message := SUBSTR(v_name, 1, 500) || ' attached';
    EXCEPTION WHEN OTHERS THEN
        p_status := 'E'; p_message := err_text(SQLERRM);
    END;

    PROCEDURE DELETE_ATTACHMENT (p_attachment_id IN VARCHAR2, p_user IN VARCHAR2,
                                 p_id OUT NUMBER, p_number OUT VARCHAR2, p_status OUT VARCHAR2, p_message OUT VARCHAR2) IS
        v_att  NUMBER := to_num(p_attachment_id);
        v_arc  NUMBER;
        v_name VARCHAR2(500);
        a      RR_ARCHIVE_BANK_STATEMENTS%ROWTYPE;
    BEGIN
        BEGIN
            SELECT ARCHIVE_ID, FILE_NAME INTO v_arc, v_name FROM RR_ARCHIVE_BANK_STMT_ATTACH WHERE ATTACHMENT_ID = v_att;
        EXCEPTION WHEN NO_DATA_FOUND THEN err('Attachment not found');
        END;
        a := arc(v_arc, FALSE);
        IF a.STATUS <> 'ARCHIVED' THEN err('Archive ' || a.ARCHIVE_NUMBER || ' is ' || a.STATUS); END IF;
        DELETE FROM RR_ARCHIVE_BANK_STMT_ATTACH WHERE ATTACHMENT_ID = v_att;
        p_id := v_att; p_number := a.ARCHIVE_NUMBER; p_status := 'S'; p_message := v_name || ' removed';
    EXCEPTION WHEN OTHERS THEN
        p_status := 'E'; p_message := err_text(SQLERRM);
    END;

    PROCEDURE CANCEL_ARCHIVE (p_archive_id IN VARCHAR2, p_reason IN VARCHAR2, p_user IN VARCHAR2,
                              p_id OUT NUMBER, p_number OUT VARCHAR2, p_status OUT VARCHAR2, p_message OUT VARCHAR2) IS
        v_id NUMBER := to_num(p_archive_id);
        a    RR_ARCHIVE_BANK_STATEMENTS%ROWTYPE;
    BEGIN
        a := arc(v_id);
        IF a.STATUS <> 'ARCHIVED' THEN err('Archive ' || a.ARCHIVE_NUMBER || ' is already ' || a.STATUS); END IF;
        IF TRIM(p_reason) IS NULL THEN err('Enter the reason for cancelling the archive'); END IF;
        UPDATE RR_ARCHIVE_BANK_STATEMENTS
        SET    STATUS = 'CANCELLED', CANCEL_REASON = SUBSTRB(p_reason, 1, 1000), LAST_UPDATED_BY = p_user, LAST_UPDATE_DATE = SYSTIMESTAMP
        WHERE  ARCHIVE_ID = v_id;
        p_id := v_id; p_number := a.ARCHIVE_NUMBER; p_status := 'S';
        p_message := a.ARCHIVE_NUMBER || ' cancelled — statement ' || a.STATEMENT_NUMBER || ' can be archived again';
    EXCEPTION WHEN OTHERS THEN
        p_status := 'E'; p_message := err_text(SQLERRM);
    END;

    FUNCTION ATT_CHUNK (p_attachment_id IN NUMBER, p_chunk_no IN NUMBER) RETURN VARCHAR2 IS
        v_blob BLOB;
        v_raw  RAW(2400);
    BEGIN
        SELECT FILE_CONTENT INTO v_blob FROM RR_ARCHIVE_BANK_STMT_ATTACH WHERE ATTACHMENT_ID = p_attachment_id;
        v_raw := DBMS_LOB.SUBSTR(v_blob, C_CHUNK, (p_chunk_no - 1) * C_CHUNK + 1);
        IF v_raw IS NULL THEN RETURN NULL; END IF;
        RETURN REPLACE(REPLACE(UTL_RAW.CAST_TO_VARCHAR2(UTL_ENCODE.BASE64_ENCODE(v_raw)), CHR(13)), CHR(10));
    EXCEPTION WHEN NO_DATA_FOUND THEN RETURN NULL;
    END;
