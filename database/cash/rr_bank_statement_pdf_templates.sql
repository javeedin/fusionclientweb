-- ============================================================
-- Table: RR_BANK_STATEMENT_PDF_TEMPLATES
-- Description: User-defined templates for parsing bank statement PDFs
--              Each template maps PDF column X-positions to statement fields
-- ============================================================

CREATE TABLE RR_BANK_STATEMENT_PDF_TEMPLATES (
    TEMPLATE_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TEMPLATE_NAME       VARCHAR2(200)   NOT NULL,
    DESCRIPTION         VARCHAR2(500),
    BUSINESS_UNIT_NAME  VARCHAR2(360),          -- NULL = applies to all BUs
    COLUMN_MAPPINGS     CLOB,                   -- JSON array: [{text,x,xMin,xMax,field}]
    HEADER_ROW_TEXT     VARCHAR2(2000),         -- concatenated header texts for auto-detection
    DATE_FORMAT         VARCHAR2(50)  DEFAULT 'DD/MM/YYYY',
    CREATED_BY          VARCHAR2(150),
    CREATION_DATE       TIMESTAMP     DEFAULT SYSTIMESTAMP,
    LAST_UPDATED_BY     VARCHAR2(150),
    LAST_UPDATE_DATE    TIMESTAMP     DEFAULT SYSTIMESTAMP,
    CONSTRAINT UK_RR_PDF_TPL_NAME UNIQUE (TEMPLATE_NAME)
);

CREATE INDEX IDX_RR_PDF_TPL_BU ON RR_BANK_STATEMENT_PDF_TEMPLATES(BUSINESS_UNIT_NAME);

COMMENT ON TABLE  RR_BANK_STATEMENT_PDF_TEMPLATES IS 'Templates for parsing PDF bank statements by column X-position mapping';
COMMENT ON COLUMN RR_BANK_STATEMENT_PDF_TEMPLATES.COLUMN_MAPPINGS IS 'JSON array of column objects: [{text,x,xMin,xMax,field}]';
COMMENT ON COLUMN RR_BANK_STATEMENT_PDF_TEMPLATES.HEADER_ROW_TEXT IS 'Space-joined header column texts — used for auto-template detection';
COMMENT ON COLUMN RR_BANK_STATEMENT_PDF_TEMPLATES.DATE_FORMAT     IS 'Date format string: DD/MM/YYYY | MM/DD/YYYY | DD-MMM-YYYY | YYYY-MM-DD';


