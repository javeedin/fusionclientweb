-- ── POST cash/pdf-templates (upsert) ────────────────────────
BEGIN
    ORDS.DEFINE_HANDLER(
        p_module_name    => 'reerp',
        p_pattern        => 'cash/pdf-templates',
        p_method         => 'POST',
        p_source_type    => 'plsql/block',
        p_items_per_page => 0,
        p_mimes_allowed  => 'application/json',
        p_comments       => 'Upsert a PDF template — update if template_id provided, else insert',
        p_source         => q'[
DECLARE
    l_id        NUMBER;
    l_name      VARCHAR2(200);
    l_desc      VARCHAR2(500);
    l_bu        VARCHAR2(360);
    l_mappings  CLOB;
    l_hdr       VARCHAR2(2000);
    l_fmt       VARCHAR2(50);
    l_created   VARCHAR2(150);
    l_updated   VARCHAR2(150);
BEGIN
    APEX_JSON.PARSE(:body_text);

    l_id       := APEX_JSON.GET_NUMBER(p_path => 'template_id');
    l_name     := APEX_JSON.GET_VARCHAR2(p_path => 'template_name');
    l_desc     := APEX_JSON.GET_VARCHAR2(p_path => 'description');
    l_bu       := APEX_JSON.GET_VARCHAR2(p_path => 'business_unit_name');
    l_mappings := TO_CLOB(APEX_JSON.GET_VARCHAR2(p_path => 'column_mappings'));
    l_hdr      := APEX_JSON.GET_VARCHAR2(p_path => 'header_row_text');
    l_fmt      := NVL(APEX_JSON.GET_VARCHAR2(p_path => 'date_format'), 'DD/MM/YYYY');
    l_created  := APEX_JSON.GET_VARCHAR2(p_path => 'created_by');
    l_updated  := APEX_JSON.GET_VARCHAR2(p_path => 'last_updated_by');

    IF l_name IS NULL AND l_id IS NULL THEN
        :status_code := 400;
        HTP.PRN('{"status":"error","message":"template_name is required"}');
        RETURN;
    END IF;

    IF l_id IS NOT NULL THEN
        UPDATE RR_BANK_STATEMENT_PDF_TEMPLATES
        SET    TEMPLATE_NAME      = NVL(l_name,     TEMPLATE_NAME),
               DESCRIPTION        = l_desc,
               BUSINESS_UNIT_NAME = l_bu,
               COLUMN_MAPPINGS    = NVL(l_mappings,  COLUMN_MAPPINGS),
               HEADER_ROW_TEXT    = l_hdr,
               DATE_FORMAT        = NVL(l_fmt,       DATE_FORMAT),
               LAST_UPDATED_BY    = l_updated,
               LAST_UPDATE_DATE   = SYSTIMESTAMP
        WHERE  TEMPLATE_ID = l_id;

        IF SQL%ROWCOUNT = 0 THEN
            :status_code := 404;
            HTP.PRN('{"status":"error","message":"Template not found"}');
            RETURN;
        END IF;
        COMMIT;
        :status_code := 200;
        HTP.PRN('{"status":"success","template_id":' || l_id || ',"message":"Template updated"}');
    ELSE
        INSERT INTO RR_BANK_STATEMENT_PDF_TEMPLATES (
            TEMPLATE_NAME, DESCRIPTION, BUSINESS_UNIT_NAME,
            COLUMN_MAPPINGS, HEADER_ROW_TEXT, DATE_FORMAT,
            CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE
        ) VALUES (
            l_name, l_desc, l_bu, l_mappings, l_hdr, l_fmt,
            l_created, SYSTIMESTAMP, NVL(l_updated, l_created), SYSTIMESTAMP
        ) RETURNING TEMPLATE_ID INTO l_id;
        COMMIT;
        :status_code := 201;
        HTP.PRN('{"status":"success","template_id":' || l_id || ',"message":"Template created"}');
    END IF;

EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    :status_code := 500;
    HTP.PRN('{"status":"error","message":' || APEX_JSON.STRINGIFY(SQLERRM) || '}');
END;
]'
    );
    COMMIT;
END;
