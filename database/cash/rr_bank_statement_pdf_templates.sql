-- ── GET cash/pdf-templates ───────────────────────────────────
BEGIN
    ORDS.DEFINE_HANDLER(
        p_module_name    => 'reerp',
        p_pattern        => 'cash/pdf-templates',
        p_method         => 'GET',
        p_source_type    => 'json/collection',
        p_items_per_page => 0,
        p_mimes_allowed  => '',
        p_comments       => 'List PDF templates; optional business_unit filter (also returns NULL-BU templates)',
        p_source         => q'[
SELECT
    TEMPLATE_ID         AS "templateId",
    TEMPLATE_NAME       AS "templateName",
    DESCRIPTION         AS "description",
    BUSINESS_UNIT_NAME  AS "businessUnitName",
    COLUMN_MAPPINGS     AS "columnMappings",
    HEADER_ROW_TEXT     AS "headerRowText",
    DATE_FORMAT         AS "dateFormat",
    CREATED_BY          AS "createdBy",
    TO_CHAR(CREATION_DATE,    'YYYY-MM-DD"T"HH24:MI:SS') AS "creationDate",
    LAST_UPDATED_BY     AS "lastUpdatedBy",
    TO_CHAR(LAST_UPDATE_DATE, 'YYYY-MM-DD"T"HH24:MI:SS') AS "lastUpdateDate"
FROM RR_BANK_STATEMENT_PDF_TEMPLATES
WHERE (:business_unit IS NULL
       OR BUSINESS_UNIT_NAME = :business_unit
       OR BUSINESS_UNIT_NAME IS NULL)
ORDER BY TEMPLATE_NAME
]'
    );
    COMMIT;
END;
