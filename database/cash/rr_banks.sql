-- ============================================
-- Table: RR_BANKS
-- Description: Stores bank information from Oracle Fusion
-- ============================================

CREATE TABLE RR_BANKS (
    ID                      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BANK_PARTY_ID           NUMBER NOT NULL,
    BANK_NAME               VARCHAR2(360) NOT NULL,
    BANK_NAME_ALT           VARCHAR2(360),
    BANK_NUMBER             VARCHAR2(60),
    DESCRIPTION             VARCHAR2(240),
    TAXPAYER_ID_NUMBER      VARCHAR2(50),
    TAX_REGISTRATION_NUMBER VARCHAR2(50),
    BANK_PARTY_NUMBER       VARCHAR2(60),
    COUNTRY_NAME            VARCHAR2(100),
    CREATED_BY              VARCHAR2(150),
    CREATION_DATE           TIMESTAMP,
    LAST_UPDATE_DATE        TIMESTAMP,
    LAST_UPDATE_LOGIN       VARCHAR2(100),
    LAST_UPDATED_BY         VARCHAR2(150),
    SYNC_DATE               TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT UK_RR_BANKS_PARTY_ID UNIQUE (BANK_PARTY_ID)
);

-- Indexes
CREATE INDEX IDX_RR_BANKS_NAME ON RR_BANKS(BANK_NAME);
CREATE INDEX IDX_RR_BANKS_NUMBER ON RR_BANKS(BANK_NUMBER);
CREATE INDEX IDX_RR_BANKS_COUNTRY ON RR_BANKS(COUNTRY_NAME);

-- Comments
COMMENT ON TABLE RR_BANKS IS 'Bank master data synced from Oracle Fusion';
COMMENT ON COLUMN RR_BANKS.BANK_PARTY_ID IS 'Unique bank party identifier from Fusion';
COMMENT ON COLUMN RR_BANKS.BANK_NAME IS 'Bank name';
COMMENT ON COLUMN RR_BANKS.BANK_NAME_ALT IS 'Alternate bank name';
COMMENT ON COLUMN RR_BANKS.BANK_NUMBER IS 'Bank number/code';
COMMENT ON COLUMN RR_BANKS.COUNTRY_NAME IS 'Country where bank is located';
COMMENT ON COLUMN RR_BANKS.SYNC_DATE IS 'Timestamp when record was synced';

-- ============================================
-- Procedure: RR_SYNC_BANKS
-- Description: Upsert banks from JSON payload
-- ============================================

CREATE OR REPLACE PROCEDURE RR_SYNC_BANKS (
    p_json IN CLOB,
    p_count OUT NUMBER,
    p_error OUT VARCHAR2
) AS
    v_bank_party_id           NUMBER;
    v_bank_name               VARCHAR2(360);
    v_bank_name_alt           VARCHAR2(360);
    v_bank_number             VARCHAR2(60);
    v_description             VARCHAR2(240);
    v_taxpayer_id_number      VARCHAR2(50);
    v_tax_registration_number VARCHAR2(50);
    v_bank_party_number       VARCHAR2(60);
    v_country_name            VARCHAR2(100);
    v_created_by              VARCHAR2(150);
    v_creation_date           TIMESTAMP;
    v_last_update_date        TIMESTAMP;
    v_last_update_login       VARCHAR2(100);
    v_last_updated_by         VARCHAR2(150);
BEGIN
    p_count := 0;
    p_error := NULL;

    FOR rec IN (
        SELECT *
        FROM JSON_TABLE(p_json, '$.items[*]'
            COLUMNS (
                bank_party_id           NUMBER          PATH '$.BankPartyId',
                bank_name               VARCHAR2(360)   PATH '$.BankName',
                bank_name_alt           VARCHAR2(360)   PATH '$.BankNameAlt',
                bank_number             VARCHAR2(60)    PATH '$.BankNumber',
                description             VARCHAR2(240)   PATH '$.Description',
                taxpayer_id_number      VARCHAR2(50)    PATH '$.TaxpayerIdNumber',
                tax_registration_number VARCHAR2(50)    PATH '$.TaxRegistrationNumber',
                bank_party_number       VARCHAR2(60)    PATH '$.BankPartyNumber',
                country_name            VARCHAR2(100)   PATH '$.CountryName',
                created_by              VARCHAR2(150)   PATH '$.CreatedBy',
                creation_date           TIMESTAMP       PATH '$.CreationDate',
                last_update_date        TIMESTAMP       PATH '$.LastUpdateDate',
                last_update_login       VARCHAR2(100)   PATH '$.LastUpdateLogin',
                last_updated_by         VARCHAR2(150)   PATH '$.LastUpdatedBy'
            )
        )
    ) LOOP
        -- Store values in local variables
        v_bank_party_id           := rec.bank_party_id;
        v_bank_name               := rec.bank_name;
        v_bank_name_alt           := rec.bank_name_alt;
        v_bank_number             := rec.bank_number;
        v_description             := rec.description;
        v_taxpayer_id_number      := rec.taxpayer_id_number;
        v_tax_registration_number := rec.tax_registration_number;
        v_bank_party_number       := rec.bank_party_number;
        v_country_name            := rec.country_name;
        v_created_by              := rec.created_by;
        v_creation_date           := rec.creation_date;
        v_last_update_date        := rec.last_update_date;
        v_last_update_login       := rec.last_update_login;
        v_last_updated_by         := rec.last_updated_by;

        -- Merge (upsert) the record
        MERGE INTO RR_BANKS tgt
        USING (
            SELECT
                v_bank_party_id           AS bank_party_id,
                v_bank_name               AS bank_name,
                v_bank_name_alt           AS bank_name_alt,
                v_bank_number             AS bank_number,
                v_description             AS description,
                v_taxpayer_id_number      AS taxpayer_id_number,
                v_tax_registration_number AS tax_registration_number,
                v_bank_party_number       AS bank_party_number,
                v_country_name            AS country_name,
                v_created_by              AS created_by,
                v_creation_date           AS creation_date,
                v_last_update_date        AS last_update_date,
                v_last_update_login       AS last_update_login,
                v_last_updated_by         AS last_updated_by
            FROM DUAL
        ) src
        ON (tgt.BANK_PARTY_ID = src.bank_party_id)
        WHEN MATCHED THEN
            UPDATE SET
                tgt.BANK_NAME               = src.bank_name,
                tgt.BANK_NAME_ALT           = src.bank_name_alt,
                tgt.BANK_NUMBER             = src.bank_number,
                tgt.DESCRIPTION             = src.description,
                tgt.TAXPAYER_ID_NUMBER      = src.taxpayer_id_number,
                tgt.TAX_REGISTRATION_NUMBER = src.tax_registration_number,
                tgt.BANK_PARTY_NUMBER       = src.bank_party_number,
                tgt.COUNTRY_NAME            = src.country_name,
                tgt.CREATED_BY              = src.created_by,
                tgt.CREATION_DATE           = src.creation_date,
                tgt.LAST_UPDATE_DATE        = src.last_update_date,
                tgt.LAST_UPDATE_LOGIN       = src.last_update_login,
                tgt.LAST_UPDATED_BY         = src.last_updated_by,
                tgt.SYNC_DATE               = SYSTIMESTAMP
        WHEN NOT MATCHED THEN
            INSERT (
                BANK_PARTY_ID,
                BANK_NAME,
                BANK_NAME_ALT,
                BANK_NUMBER,
                DESCRIPTION,
                TAXPAYER_ID_NUMBER,
                TAX_REGISTRATION_NUMBER,
                BANK_PARTY_NUMBER,
                COUNTRY_NAME,
                CREATED_BY,
                CREATION_DATE,
                LAST_UPDATE_DATE,
                LAST_UPDATE_LOGIN,
                LAST_UPDATED_BY,
                SYNC_DATE
            ) VALUES (
                src.bank_party_id,
                src.bank_name,
                src.bank_name_alt,
                src.bank_number,
                src.description,
                src.taxpayer_id_number,
                src.tax_registration_number,
                src.bank_party_number,
                src.country_name,
                src.created_by,
                src.creation_date,
                src.last_update_date,
                src.last_update_login,
                src.last_updated_by,
                SYSTIMESTAMP
            );

        p_count := p_count + 1;
    END LOOP;

    COMMIT;

EXCEPTION
    WHEN OTHERS THEN
        p_error := SQLERRM;
        ROLLBACK;
END RR_SYNC_BANKS;
