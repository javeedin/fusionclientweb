-- ============================================================
-- ORDS: GET /settings/claudekey
-- Returns the active API key so the Electron main process can
-- call Claude API without embedding the key in the app bundle.
-- ============================================================
BEGIN
    BEGIN
        ORDS.DELETE_HANDLER(
            p_module_name => 'reerp',
            p_pattern     => 'settings/claudekey',
            p_method      => 'GET'
        );
    EXCEPTION WHEN OTHERS THEN NULL;
    END;

    BEGIN
        ORDS.DEFINE_TEMPLATE(
            p_module_name => 'reerp',
            p_pattern     => 'settings/claudekey'
        );
    EXCEPTION WHEN OTHERS THEN NULL;
    END;

    ORDS.DEFINE_HANDLER(
        p_module_name    => 'reerp',
        p_pattern        => 'settings/claudekey',
        p_method         => 'GET',
        p_source_type    => ORDS.source_type_plsql,
        p_mimes_allowed  => '',
        p_comments       => 'Return active Claude API key for Electron AI agents',
        p_source         => q'[
DECLARE
    l_key VARCHAR2(300);
BEGIN
    BEGIN
        SELECT TRIM(API_KEY) INTO l_key
        FROM   RR_CLAUDE_KEY
        WHERE  IS_ACTIVE = 'Y'
        ORDER BY ID DESC
        FETCH FIRST 1 ROWS ONLY;
    EXCEPTION WHEN NO_DATA_FOUND THEN
        l_key := NULL;
    END;

    IF l_key IS NULL THEN
        :status_code := 404;
        HTP.PRN('{"status":"error","message":"No active Claude API key found in RR_CLAUDE_KEY"}');
    ELSE
        :status_code := 200;
        APEX_JSON.OPEN_OBJECT;
        APEX_JSON.WRITE('status', 'success');
        APEX_JSON.WRITE('apiKey', l_key);
        APEX_JSON.CLOSE_OBJECT;
    END IF;
END;
]'
    );

    COMMIT;
END;
