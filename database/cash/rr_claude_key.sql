-- ============================================================
-- Table: RR_CLAUDE_KEY
-- Description: Stores the Claude (Anthropic) API key for AI agents
-- All active users can read the key via the ORDS endpoint.
-- Only DBAs / admins should INSERT/UPDATE rows directly.
-- ============================================================

CREATE TABLE RR_CLAUDE_KEY (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    API_KEY          VARCHAR2(300) NOT NULL,
    DESCRIPTION      VARCHAR2(200),
    IS_ACTIVE        VARCHAR2(1) DEFAULT 'Y' NOT NULL,
    CREATED_BY       VARCHAR2(150),
    CREATION_DATE    TIMESTAMP DEFAULT SYSTIMESTAMP,
    LAST_UPDATED_BY  VARCHAR2(150),
    LAST_UPDATE_DATE TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT CHK_RR_CLAUDE_KEY_ACTIVE CHECK (IS_ACTIVE IN ('Y', 'N'))
);

COMMENT ON TABLE  RR_CLAUDE_KEY            IS 'Stores Anthropic Claude API keys for ERP AI agents';
COMMENT ON COLUMN RR_CLAUDE_KEY.API_KEY    IS 'Claude API key — sk-ant-api03-...';
COMMENT ON COLUMN RR_CLAUDE_KEY.IS_ACTIVE  IS 'Y = in use, N = disabled';

