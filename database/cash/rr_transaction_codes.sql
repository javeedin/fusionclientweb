-- ============================================================
-- Table: RR_TRANSACTION_CODES
-- Description: Cash transaction codes for classifying cash transactions
-- ============================================================

CREATE TABLE RR_TRANSACTION_CODES (
    TC_ID                       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BUSINESS_UNIT_NAME          VARCHAR2(360)   NOT NULL,
    TRANSACTION_CODE            VARCHAR2(50)    NOT NULL,
    DESCRIPTION                 VARCHAR2(500),
    DEFAULT_ACCOUNT_COMBINATION VARCHAR2(360),
    END_TRANSACTION             VARCHAR2(100),  -- e.g. 'External Transaction', 'Manual Journal', 'Bank Transfer'
    CREATED_BY                  VARCHAR2(150),
    CREATION_DATE               TIMESTAMP       DEFAULT SYSTIMESTAMP,
    LAST_UPDATED_BY             VARCHAR2(150),
    LAST_UPDATE_DATE            TIMESTAMP       DEFAULT SYSTIMESTAMP,
    CONSTRAINT UK_RR_TC_BU_CODE UNIQUE (BUSINESS_UNIT_NAME, TRANSACTION_CODE)
);

-- Indexes
CREATE INDEX IDX_RR_TC_BU   ON RR_TRANSACTION_CODES(BUSINESS_UNIT_NAME);
CREATE INDEX IDX_RR_TC_CODE ON RR_TRANSACTION_CODES(TRANSACTION_CODE);

-- Comments
COMMENT ON TABLE  RR_TRANSACTION_CODES                              IS 'Cash transaction codes used to classify cash transactions by business unit';
COMMENT ON COLUMN RR_TRANSACTION_CODES.TC_ID                        IS 'Surrogate primary key';
COMMENT ON COLUMN RR_TRANSACTION_CODES.BUSINESS_UNIT_NAME           IS 'Business unit this transaction code belongs to';
COMMENT ON COLUMN RR_TRANSACTION_CODES.TRANSACTION_CODE             IS 'Short code identifying the transaction type';
COMMENT ON COLUMN RR_TRANSACTION_CODES.DESCRIPTION                  IS 'Human-readable description of the transaction code';
COMMENT ON COLUMN RR_TRANSACTION_CODES.DEFAULT_ACCOUNT_COMBINATION  IS 'Default GL account combination for this transaction code';
COMMENT ON COLUMN RR_TRANSACTION_CODES.END_TRANSACTION              IS 'End transaction type, e.g. External Transaction, Manual Journal, Bank Transfer';


