-- ============================================================
-- Table: RR_BANK_TRANSFER_ATTACHMENTS
-- Stores file attachments for bank account transfers
-- No FK to bank transfers table (transfers may be Oracle-sourced)
-- ============================================================

CREATE TABLE RR_BANK_TRANSFER_ATTACHMENTS (
    ID                      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BANK_ACCOUNT_TRANSFER_ID NUMBER NOT NULL,
    FILE_NAME               VARCHAR2(500) NOT NULL,
    FILE_TYPE               VARCHAR2(100),
    FILE_SIZE               NUMBER,
    FILE_CONTENT            CLOB,  -- Base64-encoded file content
    CREATED_BY              VARCHAR2(150),
    CREATED_DATE            TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE INDEX IDX_RR_BTA_TRF_ID ON RR_BANK_TRANSFER_ATTACHMENTS(BANK_ACCOUNT_TRANSFER_ID);

