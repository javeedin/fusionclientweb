-- =============================================================================
-- Cash Management — 169: the cash/execute web service (write gateway)
--
--   POST reerp/cash/execute
--     body: { "proc": "RR_CM_ARCHIVE_PKG.CREATE_ARCHIVE",
--             "params": { "p_json": {...} | "...", "p_archive_id": "123" },
--             "user": "jdoe" }
--     resp: { "success": true|false, "status": "S"|"W"|"E",
--             "id": 123, "number": "ARC-000123", "message": "..." }
--
--   * Only procedures registered (and enabled) in RR_CM_PROC_REGISTRY can be called;
--     only the IN parameters listed in PARAMS_CSV are bound (by name, never
--     concatenated); p_user and the 4 OUT parameters are implicit.
--   * CLOB_PARAMS: parameters bound as CLOB (JSON objects / arrays are serialised).
--   * Commit on S/W, rollback on E. Every call is logged in RR_CM_EXEC_LOG
--     (file contents are not written to the log).
--   Same contract as po/execute (database/po/303_po_execute.sql).
--
-- HOW TO RUN (schema owner — the schema that owns the ORDS module "reerp"):
--   SQL Developer / SQLcl : open this file, Run Script (F5)
--   APEX                  : SQL Workshop → SQL Scripts → Upload → Run
--                           (not "SQL Commands": it runs one statement only)
-- Then run 170_cm_archive_bank_statements.sql (it registers the archive procedures).
--
-- CHECK: a GET on …/reerp/cash/execute answers 405 (method not allowed) once the
-- service exists, and 404 while it does not. The app's API button runs this check.
-- Safe to re-run.
-- =============================================================================

-- ── registry and call log ────────────────────────────────────────────────────
BEGIN EXECUTE IMMEDIATE q'[
CREATE TABLE RR_CM_PROC_REGISTRY (
    PROC_NAME     VARCHAR2(128) PRIMARY KEY,
    PARAMS_CSV    VARCHAR2(2000),
    CLOB_PARAMS   VARCHAR2(500),
    ENABLED_FLAG  VARCHAR2(1) DEFAULT 'Y' NOT NULL,
    DESCRIPTION   VARCHAR2(400),
    CREATED_BY VARCHAR2(150), CREATION_DATE TIMESTAMP DEFAULT SYSTIMESTAMP,
    LAST_UPDATED_BY VARCHAR2(150), LAST_UPDATE_DATE TIMESTAMP
)]';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;
/

BEGIN EXECUTE IMMEDIATE q'[
CREATE TABLE RR_CM_EXEC_LOG (
    LOG_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_NAME    VARCHAR2(150),
    PROC_NAME    VARCHAR2(128),
    PARAMS_TEXT  VARCHAR2(4000),     -- first 4000 characters (file contents are not kept)
    STATUS       VARCHAR2(1),
    MESSAGE      VARCHAR2(4000),
    RESULT_ID    NUMBER,
    ELAPSED_MS   NUMBER,
    CREATION_DATE TIMESTAMP DEFAULT SYSTIMESTAMP
)]';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;
/

-- ═════════════════════════════════════════════════════════════════════════════
-- Write gateway: POST reerp/cash/execute
-- ═════════════════════════════════════════════════════════════════════════════
CREATE OR REPLACE PROCEDURE RR_CM_LOG_EXEC (
    p_user IN VARCHAR2, p_proc IN VARCHAR2, p_params IN VARCHAR2, p_status IN VARCHAR2,
    p_message IN VARCHAR2, p_id IN NUMBER, p_ms IN NUMBER
) AS
    PRAGMA AUTONOMOUS_TRANSACTION;
BEGIN
    INSERT INTO RR_CM_EXEC_LOG (USER_NAME, PROC_NAME, PARAMS_TEXT, STATUS, MESSAGE, RESULT_ID, ELAPSED_MS)
    VALUES (p_user, p_proc, SUBSTR(p_params, 1, 4000), p_status, SUBSTR(p_message, 1, 4000), p_id, p_ms);
    COMMIT;
EXCEPTION WHEN OTHERS THEN ROLLBACK;
END RR_CM_LOG_EXEC;
/

CREATE OR REPLACE PROCEDURE RR_CM_PRINT_CLOB (p_clob IN CLOB) AS
    v_len NUMBER := NVL(DBMS_LOB.GETLENGTH(p_clob), 0);
    v_pos NUMBER := 1;
BEGIN
    WHILE v_pos <= v_len LOOP
        HTP.PRN(DBMS_LOB.SUBSTR(p_clob, 8000, v_pos));
        v_pos := v_pos + 8000;
    END LOOP;
END RR_CM_PRINT_CLOB;
/

CREATE OR REPLACE PROCEDURE RR_CM_EXECUTE (
    p_body   IN  CLOB,
    p_http   OUT NUMBER,
    p_result OUT CLOB
) AS
    v_t0      TIMESTAMP := SYSTIMESTAMP;
    v_body    JSON_OBJECT_T;
    v_params  JSON_OBJECT_T;
    v_proc    VARCHAR2(128);
    v_user    VARCHAR2(150);
    v_reg     RR_CM_PROC_REGISTRY%ROWTYPE;
    v_sql     VARCHAR2(32767);
    v_cur     INTEGER;
    v_dummy   INTEGER;
    v_name    VARCHAR2(128);
    v_clobs   VARCHAR2(600);
    v_el      JSON_ELEMENT_T;
    v_txt     VARCHAR2(32767);
    v_clob    CLOB;
    v_id      NUMBER;
    v_number  VARCHAR2(200);
    v_status  VARCHAR2(10);
    v_message VARCHAR2(4000);
    v_out     JSON_OBJECT_T := JSON_OBJECT_T();
    v_ms      NUMBER;
    v_plist   SYS.ODCIVARCHAR2LIST := SYS.ODCIVARCHAR2LIST();

    FUNCTION ms RETURN NUMBER IS
        d INTERVAL DAY TO SECOND := SYSTIMESTAMP - v_t0;
    BEGIN
        RETURN ROUND(EXTRACT(SECOND FROM d) * 1000 + EXTRACT(MINUTE FROM d) * 60000);
    END;
    -- params for the log, without long values (file contents)
    FUNCTION log_params RETURN VARCHAR2 IS
    BEGIN
        RETURN REGEXP_REPLACE(DBMS_LOB.SUBSTR(v_params.to_clob, 4000, 1), '"fileContent":"[^"]{200,}', '"fileContent":"(omitted)');
    EXCEPTION WHEN OTHERS THEN RETURN NULL;
    END;
BEGIN
    p_http := 200;
    BEGIN
        v_body := JSON_OBJECT_T.parse(p_body);
    EXCEPTION WHEN OTHERS THEN
        p_http := 400;
        p_result := '{"success":false,"status":"E","message":"Body must be JSON: {proc, params, user}"}';
        RETURN;
    END;

    v_proc := UPPER(TRIM(v_body.get_string('proc')));
    v_user := SUBSTR(NVL(v_body.get_string('user'), 'UNKNOWN'), 1, 150);
    v_params := CASE WHEN v_body.has('params') AND v_body.get('params').is_object
                     THEN TREAT(v_body.get('params') AS JSON_OBJECT_T) ELSE JSON_OBJECT_T() END;

    BEGIN
        SELECT * INTO v_reg FROM RR_CM_PROC_REGISTRY WHERE PROC_NAME = v_proc AND ENABLED_FLAG = 'Y';
    EXCEPTION WHEN NO_DATA_FOUND THEN
        p_http := 403;
        v_out.put('success', FALSE); v_out.put('status', 'E');
        v_out.put('message', 'Procedure ' || NVL(v_proc, '(none)') || ' is not registered for cash/execute');
        p_result := v_out.to_clob;
        RR_CM_LOG_EXEC(v_user, v_proc, NULL, 'E', 'not registered', NULL, ms);
        RETURN;
    END;

    FOR r IN (SELECT LOWER(TRIM(REGEXP_SUBSTR(v_reg.PARAMS_CSV, '[^,]+', 1, LEVEL))) p
                FROM dual CONNECT BY REGEXP_SUBSTR(v_reg.PARAMS_CSV, '[^,]+', 1, LEVEL) IS NOT NULL) LOOP
        IF r.p IS NOT NULL THEN
            IF NOT REGEXP_LIKE(r.p, '^p_[a-z0-9_]{1,60}$') THEN
                RAISE_APPLICATION_ERROR(-20001, 'Bad registry parameter ' || r.p);
            END IF;
            v_plist.EXTEND; v_plist(v_plist.COUNT) := r.p;
        END IF;
    END LOOP;
    v_clobs := ',' || LOWER(REPLACE(NVL(v_reg.CLOB_PARAMS, ''), ' ', '')) || ',';

    -- the call text is built from the registry only (never from the request)
    v_sql := 'BEGIN ' || DBMS_ASSERT.QUALIFIED_SQL_NAME(v_reg.PROC_NAME) || '(';
    FOR i IN 1 .. v_plist.COUNT LOOP
        v_sql := v_sql || v_plist(i) || ' => :' || v_plist(i) || ', ';
    END LOOP;
    v_sql := v_sql || 'p_user => :p_user, p_id => :o_id, p_number => :o_number, '
                   || 'p_status => :o_status, p_message => :o_message); END;';

    SAVEPOINT rr_cm_exec;
    v_cur := DBMS_SQL.OPEN_CURSOR;
    BEGIN
        DBMS_SQL.PARSE(v_cur, v_sql, DBMS_SQL.NATIVE);
        FOR i IN 1 .. v_plist.COUNT LOOP
            v_name := v_plist(i);
            v_el := NULL;
            IF v_params.has(v_name) THEN v_el := v_params.get(v_name); END IF;
            IF INSTR(v_clobs, ',' || v_name || ',') > 0 THEN
                IF v_el IS NULL OR v_el.is_null THEN v_clob := NULL;
                ELSIF v_el.is_string THEN v_clob := v_params.get_clob(v_name);
                ELSE v_clob := v_el.to_clob;
                END IF;
                DBMS_SQL.BIND_VARIABLE(v_cur, ':' || v_name, v_clob);
            ELSE
                IF v_el IS NULL OR v_el.is_null THEN v_txt := NULL;
                ELSIF v_el.is_string THEN v_txt := v_params.get_string(v_name);
                ELSIF v_el.is_boolean THEN v_txt := CASE WHEN v_params.get_boolean(v_name) THEN 'Y' ELSE 'N' END;
                ELSE v_txt := v_el.to_string;
                END IF;
                DBMS_SQL.BIND_VARIABLE(v_cur, ':' || v_name, v_txt, 32767);
            END IF;
        END LOOP;
        DBMS_SQL.BIND_VARIABLE(v_cur, ':p_user', v_user, 150);
        DBMS_SQL.BIND_VARIABLE(v_cur, ':o_id', v_id);
        DBMS_SQL.BIND_VARIABLE(v_cur, ':o_number', v_number, 200);
        DBMS_SQL.BIND_VARIABLE(v_cur, ':o_status', v_status, 10);
        DBMS_SQL.BIND_VARIABLE(v_cur, ':o_message', v_message, 4000);
        v_dummy := DBMS_SQL.EXECUTE(v_cur);
        DBMS_SQL.VARIABLE_VALUE(v_cur, ':o_id', v_id);
        DBMS_SQL.VARIABLE_VALUE(v_cur, ':o_number', v_number);
        DBMS_SQL.VARIABLE_VALUE(v_cur, ':o_status', v_status);
        DBMS_SQL.VARIABLE_VALUE(v_cur, ':o_message', v_message);
        DBMS_SQL.CLOSE_CURSOR(v_cur);
    EXCEPTION WHEN OTHERS THEN
        IF DBMS_SQL.IS_OPEN(v_cur) THEN DBMS_SQL.CLOSE_CURSOR(v_cur); END IF;
        v_status := 'E';
        v_message := SUBSTR(REGEXP_REPLACE(SQLERRM, '^ORA-2[0-9]{4}: ', ''), 1, 4000);
    END;

    IF NVL(v_status, 'E') IN ('S', 'W') THEN
        COMMIT;
    ELSE
        ROLLBACK TO rr_cm_exec;
        v_status := 'E';
    END IF;

    v_ms := ms;
    v_out.put('success', v_status IN ('S', 'W'));
    v_out.put('status', v_status);
    IF v_id IS NULL THEN v_out.put_null('id'); ELSE v_out.put('id', v_id); END IF;
    v_out.put('number', v_number);
    v_out.put('message', v_message);
    v_out.put('elapsedMs', v_ms);
    p_result := v_out.to_clob;
    RR_CM_LOG_EXEC(v_user, v_proc, log_params, v_status, v_message, v_id, v_ms);
END RR_CM_EXECUTE;
/

-- ── ORDS handler: POST reerp/cash/execute ─────────────────────────────────────
BEGIN
    BEGIN
        ORDS.DELETE_TEMPLATE(p_module_name => 'reerp', p_pattern => 'cash/execute');
    EXCEPTION WHEN OTHERS THEN NULL; END;
    ORDS.DEFINE_TEMPLATE(p_module_name => 'reerp', p_pattern => 'cash/execute');
    ORDS.DEFINE_HANDLER(
        p_module_name    => 'reerp',
        p_pattern        => 'cash/execute',
        p_method         => 'POST',
        p_source_type    => 'plsql/block',
        p_items_per_page => 0,
        p_mimes_allowed  => 'application/json',
        p_comments       => 'Cash Management write dispatcher (registry-whitelisted procedures)',
        p_source         => q'[
DECLARE
    l_http   NUMBER;
    l_result CLOB;
BEGIN
    RR_CM_EXECUTE(:body_text, l_http, l_result);
    :status_code := l_http;
    RR_CM_PRINT_CLOB(l_result);
EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    :status_code := 500;
    HTP.PRN('{"success":false,"status":"E","message":"' ||
            REPLACE(REPLACE(SQLERRM, '\', ' '), '"', '''') || '"}');
END;
]'
    );
    COMMIT;
END;
/

