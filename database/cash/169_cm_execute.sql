 WHERE OBJECT_NAME IN ('RR_CM_PROC_REGISTRY', 'RR_CM_EXEC_LOG', 'RR_CM_LOG_EXEC', 'RR_CM_PRINT_CLOB', 'RR_CM_EXECUTE')
 ORDER BY OBJECT_TYPE, OBJECT_NAME;
SELECT NAME, TYPE, LINE, TEXT FROM USER_ERRORS WHERE NAME IN ('RR_CM_EXECUTE', 'RR_CM_LOG_EXEC', 'RR_CM_PRINT_CLOB') ORDER BY NAME, LINE;
SELECT m.NAME AS MODULE, m.URI_PREFIX, t.URI_TEMPLATE, h.METHOD
  FROM USER_ORDS_MODULES m JOIN USER_ORDS_TEMPLATES t ON t.MODULE_ID = m.ID JOIN USER_ORDS_HANDLERS h ON h.TEMPLATE_ID = t.ID
 WHERE t.URI_TEMPLATE = 'cash/execute';
