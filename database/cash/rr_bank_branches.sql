-- ============================================
-- Table: RR_BANK_BRANCHES
-- Description: Stores bank branch information from Oracle Fusion
-- ============================================

CREATE TABLE RR_BANK_BRANCHES (
    ID                      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BRANCH_PARTY_ID         NUMBER NOT NULL,
    BANK_NAME               VARCHAR2(360),
    BANK_NAME_ALT           VARCHAR2(360),
    BANK_NUMBER             VARCHAR2(60),
    BANK_BRANCH_NAME        VARCHAR2(360) NOT NULL,
    BANK_BRANCH_NAME_ALT    VARCHAR2(360),
    BRANCH_NUMBER           VARCHAR2(60),
    DESCRIPTION             VARCHAR2(240),
    EFT_SWIFT_CODE          VARCHAR2(60),
    EFT_USER_NUMBER         VARCHAR2(60),
    EDI_ID_NUMBER           VARCHAR2(60),
    EDI_LOCATION            VARCHAR2(60),
    BANK_PARTY_NUMBER       VARCHAR2(60),
    BRANCH_PARTY_NUMBER     VARCHAR2(60),
    COUNTRY_NAME            VARCHAR2(100),
    RFC_IDENTIFIER          VARCHAR2(60),
    BANK_BRANCH_TYPE        VARCHAR2(60),
    BRANCH_NUMBER_TYPE      VARCHAR2(60),
    CREATED_BY              VARCHAR2(150),
    CREATION_DATE           TIMESTAMP,
    LAST_UPDATE_DATE        TIMESTAMP,
    LAST_UPDATE_LOGIN       VARCHAR2(100),
    LAST_UPDATED_BY         VARCHAR2(150),
    SYNC_DATE               TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT UK_RR_BANK_BRANCHES_PARTY_ID UNIQUE (BRANCH_PARTY_ID)
);

-- Indexes
CREATE INDEX IDX_RR_BANK_BRANCHES_NAME ON RR_BANK_BRANCHES(BANK_BRANCH_NAME);
CREATE INDEX IDX_RR_BANK_BRANCHES_BANK ON RR_BANK_BRANCHES(BANK_NAME);
CREATE INDEX IDX_RR_BANK_BRANCHES_NUMBER ON RR_BANK_BRANCHES(BRANCH_NUMBER);
CREATE INDEX IDX_RR_BANK_BRANCHES_COUNTRY ON RR_BANK_BRANCHES(COUNTRY_NAME);

-- Comments
COMMENT ON TABLE RR_BANK_BRANCHES IS 'Bank branch master data synced from Oracle Fusion';
COMMENT ON COLUMN RR_BANK_BRANCHES.BRANCH_PARTY_ID IS 'Unique branch party identifier from Fusion';
COMMENT ON COLUMN RR_BANK_BRANCHES.BANK_NAME IS 'Parent bank name';
COMMENT ON COLUMN RR_BANK_BRANCHES.BANK_BRANCH_NAME IS 'Branch name';
COMMENT ON COLUMN RR_BANK_BRANCHES.EFT_SWIFT_CODE IS 'SWIFT/BIC code for international transfers';
COMMENT ON COLUMN RR_BANK_BRANCHES.COUNTRY_NAME IS 'Country where branch is located';
COMMENT ON COLUMN RR_BANK_BRANCHES.SYNC_DATE IS 'Timestamp when record was synced';

-- ============================================
-- Procedure: RR_SYNC_BANK_BRANCHES
-- Description: Upsert bank branches from JSON payload
-- ============================================

CREATE OR REPLACE PROCEDURE RR_SYNC_BANK_BRANCHES (
    p_json IN CLOB,
    p_count OUT NUMBER,
    p_error OUT VARCHAR2
) AS
    v_branch_party_id       NUMBER;
    v_bank_name             VARCHAR2(360);
    v_bank_name_alt         VARCHAR2(360);
    v_bank_number           VARCHAR2(60);
    v_bank_branch_name      VARCHAR2(360);
    v_bank_branch_name_alt  VARCHAR2(360);
    v_branch_number         VARCHAR2(60);
    v_description           VARCHAR2(240);
    v_eft_swift_code        VARCHAR2(60);
    v_eft_user_number       VARCHAR2(60);
    v_edi_id_number         VARCHAR2(60);
    v_edi_location          VARCHAR2(60);
    v_bank_party_number     VARCHAR2(60);
    v_branch_party_number   VARCHAR2(60);
    v_country_name          VARCHAR2(100);
    v_rfc_identifier        VARCHAR2(60);
    v_bank_branch_type      VARCHAR2(60);
    v_branch_number_type    VARCHAR2(60);
    v_created_by            VARCHAR2(150);
    v_creation_date         TIMESTAMP;
    v_last_update_date      TIMESTAMP;
    v_last_update_login     VARCHAR2(100);
    v_last_updated_by       VARCHAR2(150);
BEGIN
    p_count := 0;
    p_error := NULL;

    FOR rec IN (
        SELECT *
        FROM JSON_TABLE(p_json, '$.items[*]'
            COLUMNS (
                branch_party_id       NUMBER          PATH '$.BranchPartyId',
                bank_name             VARCHAR2(360)   PATH '$.BankName',
                bank_name_alt         VARCHAR2(360)   PATH '$.BankNameAlt',
                bank_number           VARCHAR2(60)    PATH '$.BankNumber',
                bank_branch_name      VARCHAR2(360)   PATH '$.BankBranchName',
                bank_branch_name_alt  VARCHAR2(360)   PATH '$.BankBranchNameAlt',
                branch_number         VARCHAR2(60)    PATH '$.BranchNumber',
                description           VARCHAR2(240)   PATH '$.Description',
                eft_swift_code        VARCHAR2(60)    PATH '$.EFTSWIFTCode',
                eft_user_number       VARCHAR2(60)    PATH '$.EFTUserNumber',
                edi_id_number         VARCHAR2(60)    PATH '$.EDIIdNumber',
                edi_location          VARCHAR2(60)    PATH '$.EDILocation',
                bank_party_number     VARCHAR2(60)    PATH '$.BankPartyNumber',
                branch_party_number   VARCHAR2(60)    PATH '$.BranchPartyNumber',
                country_name          VARCHAR2(100)   PATH '$.CountryName',
                rfc_identifier        VARCHAR2(60)    PATH '$.RFCIdentifier',
                bank_branch_type      VARCHAR2(60)    PATH '$.BankBranchType',
                branch_number_type    VARCHAR2(60)    PATH '$.BranchNumberType',
                created_by            VARCHAR2(150)   PATH '$.CreatedBy',
                creation_date         TIMESTAMP       PATH '$.CreationDate',
                last_update_date      TIMESTAMP       PATH '$.LastUpdateDate',
                last_update_login     VARCHAR2(100)   PATH '$.LastUpdateLogin',
                last_updated_by       VARCHAR2(150)   PATH '$.LastUpdatedBy'
            )
        )
    ) LOOP
        -- Store values in local variables
        v_branch_party_id       := rec.branch_party_id;
        v_bank_name             := rec.bank_name;
        v_bank_name_alt         := rec.bank_name_alt;
        v_bank_number           := rec.bank_number;
        v_bank_branch_name      := rec.bank_branch_name;
        v_bank_branch_name_alt  := rec.bank_branch_name_alt;
        v_branch_number         := rec.branch_number;
        v_description           := rec.description;
        v_eft_swift_code        := rec.eft_swift_code;
        v_eft_user_number       := rec.eft_user_number;
        v_edi_id_number         := rec.edi_id_number;
        v_edi_location          := rec.edi_location;
        v_bank_party_number     := rec.bank_party_number;
        v_branch_party_number   := rec.branch_party_number;
        v_country_name          := rec.country_name;
        v_rfc_identifier        := rec.rfc_identifier;
        v_bank_branch_type      := rec.bank_branch_type;
        v_branch_number_type    := rec.branch_number_type;
        v_created_by            := rec.created_by;
        v_creation_date         := rec.creation_date;
        v_last_update_date      := rec.last_update_date;
        v_last_update_login     := rec.last_update_login;
        v_last_updated_by       := rec.last_updated_by;

        -- Merge (upsert) the record
        MERGE INTO RR_BANK_BRANCHES tgt
        USING (
            SELECT
                v_branch_party_id       AS branch_party_id,
                v_bank_name             AS bank_name,
                v_bank_name_alt         AS bank_name_alt,
                v_bank_number           AS bank_number,
                v_bank_branch_name      AS bank_branch_name,
                v_bank_branch_name_alt  AS bank_branch_name_alt,
                v_branch_number         AS branch_number,
                v_description           AS description,
                v_eft_swift_code        AS eft_swift_code,
                v_eft_user_number       AS eft_user_number,
                v_edi_id_number         AS edi_id_number,
                v_edi_location          AS edi_location,
                v_bank_party_number     AS bank_party_number,
                v_branch_party_number   AS branch_party_number,
                v_country_name          AS country_name,
                v_rfc_identifier        AS rfc_identifier,
                v_bank_branch_type      AS bank_branch_type,
                v_branch_number_type    AS branch_number_type,
                v_created_by            AS created_by,
                v_creation_date         AS creation_date,
                v_last_update_date      AS last_update_date,
                v_last_update_login     AS last_update_login,
                v_last_updated_by       AS last_updated_by
            FROM DUAL
        ) src
        ON (tgt.BRANCH_PARTY_ID = src.branch_party_id)
        WHEN MATCHED THEN
            UPDATE SET
                tgt.BANK_NAME               = src.bank_name,
                tgt.BANK_NAME_ALT           = src.bank_name_alt,
                tgt.BANK_NUMBER             = src.bank_number,
                tgt.BANK_BRANCH_NAME        = src.bank_branch_name,
                tgt.BANK_BRANCH_NAME_ALT    = src.bank_branch_name_alt,
                tgt.BRANCH_NUMBER           = src.branch_number,
                tgt.DESCRIPTION             = src.description,
                tgt.EFT_SWIFT_CODE          = src.eft_swift_code,
                tgt.EFT_USER_NUMBER         = src.eft_user_number,
                tgt.EDI_ID_NUMBER           = src.edi_id_number,
                tgt.EDI_LOCATION            = src.edi_location,
                tgt.BANK_PARTY_NUMBER       = src.bank_party_number,
                tgt.BRANCH_PARTY_NUMBER     = src.branch_party_number,
                tgt.COUNTRY_NAME            = src.country_name,
                tgt.RFC_IDENTIFIER          = src.rfc_identifier,
                tgt.BANK_BRANCH_TYPE        = src.bank_branch_type,
                tgt.BRANCH_NUMBER_TYPE      = src.branch_number_type,
                tgt.CREATED_BY              = src.created_by,
                tgt.CREATION_DATE           = src.creation_date,
                tgt.LAST_UPDATE_DATE        = src.last_update_date,
                tgt.LAST_UPDATE_LOGIN       = src.last_update_login,
                tgt.LAST_UPDATED_BY         = src.last_updated_by,
                tgt.SYNC_DATE               = SYSTIMESTAMP
        WHEN NOT MATCHED THEN
            INSERT (
                BRANCH_PARTY_ID,
                BANK_NAME,
                BANK_NAME_ALT,
                BANK_NUMBER,
                BANK_BRANCH_NAME,
                BANK_BRANCH_NAME_ALT,
                BRANCH_NUMBER,
                DESCRIPTION,
                EFT_SWIFT_CODE,
                EFT_USER_NUMBER,
                EDI_ID_NUMBER,
                EDI_LOCATION,
                BANK_PARTY_NUMBER,
                BRANCH_PARTY_NUMBER,
                COUNTRY_NAME,
                RFC_IDENTIFIER,
                BANK_BRANCH_TYPE,
                BRANCH_NUMBER_TYPE,
                CREATED_BY,
                CREATION_DATE,
                LAST_UPDATE_DATE,
                LAST_UPDATE_LOGIN,
                LAST_UPDATED_BY,
                SYNC_DATE
            ) VALUES (
                src.branch_party_id,
                src.bank_name,
                src.bank_name_alt,
                src.bank_number,
                src.bank_branch_name,
                src.bank_branch_name_alt,
                src.branch_number,
                src.description,
                src.eft_swift_code,
                src.eft_user_number,
                src.edi_id_number,
                src.edi_location,
                src.bank_party_number,
                src.branch_party_number,
                src.country_name,
                src.rfc_identifier,
                src.bank_branch_type,
                src.branch_number_type,
                src.created_by,
                src.creation_date,
                src.last_update_date,
                src.last_update_login,
                src.last_updated_by,
                SYSTIMESTAMP
            );

        p_count := p_count + 1;
    END LOOP;

    COMMIT;

EXCEPTION
    WHEN OTHERS THEN
        p_error := SQLERRM;
        ROLLBACK;
END RR_SYNC_BANK_BRANCHES;
