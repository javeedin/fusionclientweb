-- ============================================================
-- ORDS: GET /admin/mcplogs — query logs for monitoring
-- Params: server, tool, ok (Y/N), hours (default 168 = 7 days), limit
-- ============================================================
BEGIN
    BEGIN
        ORDS.DELETE_HANDLER(p_module_name => 'reerp', p_pattern => 'admin/mcplogs', p_method => 'GET');
    EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN
        ORDS.DEFINE_TEMPLATE(p_module_name => 'reerp', p_pattern => 'admin/mcplogs');
    EXCEPTION WHEN OTHERS THEN NULL; END;

    ORDS.DEFINE_HANDLER(
        p_module_name    => 'reerp',
        p_pattern        => 'admin/mcplogs',
        p_method         => 'GET',
        p_source_type    => ORDS.source_type_plsql,
        p_mimes_allowed  => '',
        p_source         => q'[
DECLARE
    v_hours NUMBER := NVL(TO_NUMBER(:hours), 168);
    v_limit NUMBER := NVL(TO_NUMBER(:limit), 200);
BEGIN
    :status_code := 200;
    APEX_JSON.INITIALIZE_CLOB_OUTPUT;
    APEX_JSON.OPEN_OBJECT;
    APEX_JSON.WRITE('status', 'success');
    APEX_JSON.OPEN_ARRAY('items');
    FOR r IN (
        SELECT ID, TO_CHAR(LOG_TIME,'YYYY-MM-DD HH24:MI:SS') LOG_TIME,
               SERVER_NAME, TOOL_NAME, ARGS, OK, DURATION_MS,
               DBMS_LOB.SUBSTR(RESULT_PREVIEW, 2000, 1) RESULT_PREVIEW, ERROR_MSG,
               HOST_NAME, OS_USER, IP_ADDR, PLATFORM
        FROM   RR_MCP_CALL_LOG
        WHERE  LOG_TIME > SYSTIMESTAMP - NUMTODSINTERVAL(v_hours, 'HOUR')
          AND (:server IS NULL OR SERVER_NAME = :server)
          AND (:tool   IS NULL OR TOOL_NAME   = :tool)
          AND (:ok     IS NULL OR OK          = :ok)
        ORDER BY LOG_TIME DESC
        FETCH FIRST v_limit ROWS ONLY
    ) LOOP
        APEX_JSON.OPEN_OBJECT;
        APEX_JSON.WRITE('id',            r.ID);
        APEX_JSON.WRITE('logTime',       r.LOG_TIME);
        APEX_JSON.WRITE('server',        r.SERVER_NAME);
        APEX_JSON.WRITE('tool',          r.TOOL_NAME);
        APEX_JSON.WRITE('args',          r.ARGS);
        APEX_JSON.WRITE('ok',            r.OK);
        APEX_JSON.WRITE('durationMs',    r.DURATION_MS);
        APEX_JSON.WRITE('resultPreview', r.RESULT_PREVIEW);
        APEX_JSON.WRITE('errorMsg',      r.ERROR_MSG);
        APEX_JSON.WRITE('host',          r.HOST_NAME);
        APEX_JSON.WRITE('osUser',        r.OS_USER);
        APEX_JSON.WRITE('ipAddr',        r.IP_ADDR);
        APEX_JSON.WRITE('platform',      r.PLATFORM);
        APEX_JSON.CLOSE_OBJECT;
    END LOOP;
    APEX_JSON.CLOSE_ARRAY;
    APEX_JSON.CLOSE_OBJECT;
    HTP.P(APEX_JSON.GET_CLOB_OUTPUT);
    APEX_JSON.FREE_OUTPUT;
EXCEPTION WHEN OTHERS THEN
    :status_code := 500;
    HTP.PRN('{"status":"error","message":"' || REPLACE(SQLERRM,'"','\"') || '"}');
END;
]'
    );
    COMMIT;
END;
