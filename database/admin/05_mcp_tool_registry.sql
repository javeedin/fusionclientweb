-- ============================================================
-- ORDS Admin CRUD handlers
-- ============================================================
BEGIN
    BEGIN
        ORDS.DEFINE_TEMPLATE(p_module_name => 'reerp', p_pattern => 'admin/mcptools');
    EXCEPTION WHEN OTHERS THEN NULL; END;
    BEGIN
        ORDS.DEFINE_TEMPLATE(p_module_name => 'reerp', p_pattern => 'admin/mcptools/:id');
    EXCEPTION WHEN OTHERS THEN NULL; END;

    -- ── GET /admin/mcptools — list all ───────────────────────────────────────
    BEGIN
        ORDS.DELETE_HANDLER(p_module_name => 'reerp', p_pattern => 'admin/mcptools', p_method => 'GET');
    EXCEPTION WHEN OTHERS THEN NULL; END;
    ORDS.DEFINE_HANDLER(
        p_module_name    => 'reerp',
        p_pattern        => 'admin/mcptools',
        p_method         => 'GET',
        p_source_type    => ORDS.source_type_plsql,
        p_mimes_allowed  => '',
        p_source         => q'[
BEGIN
    :status_code := 200;
    APEX_JSON.INITIALIZE_CLOB_OUTPUT;
    APEX_JSON.OPEN_OBJECT;
    APEX_JSON.WRITE('status', 'success');
    APEX_JSON.OPEN_ARRAY('items');
    FOR r IN (
        SELECT ID, TOOL_NAME, DESCRIPTION, PARAMS_SCHEMA, HTTP_METHOD,
               URL_TEMPLATE, AUTH_TYPE, RESULT_FILTER, IS_ACTIVE,
               CREATED_BY, TO_CHAR(CREATION_DATE,'YYYY-MM-DD HH24:MI') CREATION_DATE,
               LAST_UPDATED_BY, TO_CHAR(LAST_UPDATE_DATE,'YYYY-MM-DD HH24:MI') LAST_UPDATE_DATE
        FROM   RR_MCP_TOOL_REGISTRY
        ORDER BY TOOL_NAME
    ) LOOP
        APEX_JSON.OPEN_OBJECT;
        APEX_JSON.WRITE('id',             r.ID);
        APEX_JSON.WRITE('toolName',       r.TOOL_NAME);
        APEX_JSON.WRITE('description',    r.DESCRIPTION);
        APEX_JSON.WRITE('paramsSchema',   r.PARAMS_SCHEMA);
        APEX_JSON.WRITE('httpMethod',     r.HTTP_METHOD);
        APEX_JSON.WRITE('urlTemplate',    r.URL_TEMPLATE);
        APEX_JSON.WRITE('authType',       r.AUTH_TYPE);
        APEX_JSON.WRITE('resultFilter',   r.RESULT_FILTER);
        APEX_JSON.WRITE('isActive',       r.IS_ACTIVE);
        APEX_JSON.WRITE('createdBy',      r.CREATED_BY);
        APEX_JSON.WRITE('creationDate',   r.CREATION_DATE);
        APEX_JSON.WRITE('lastUpdatedBy',  r.LAST_UPDATED_BY);
        APEX_JSON.WRITE('lastUpdateDate', r.LAST_UPDATE_DATE);
        APEX_JSON.CLOSE_OBJECT;
    END LOOP;
    APEX_JSON.CLOSE_ARRAY;
    APEX_JSON.CLOSE_OBJECT;
    HTP.P(APEX_JSON.GET_CLOB_OUTPUT);
    APEX_JSON.FREE_OUTPUT;
EXCEPTION WHEN OTHERS THEN
    :status_code := 500;
    HTP.PRN('{"status":"error","message":"' || REPLACE(SQLERRM,'"','\"') || '"}');
END;
]'
    );

    -- ── POST /admin/mcptools — create ────────────────────────────────────────
    BEGIN
        ORDS.DELETE_HANDLER(p_module_name => 'reerp', p_pattern => 'admin/mcptools', p_method => 'POST');
    EXCEPTION WHEN OTHERS THEN NULL; END;
    ORDS.DEFINE_HANDLER(
        p_module_name    => 'reerp',
        p_pattern        => 'admin/mcptools',
        p_method         => 'POST',
        p_source_type    => ORDS.source_type_plsql,
        p_mimes_allowed  => 'application/json',
        p_source         => q'[
DECLARE
    l_body   CLOB := :body_text;
    l_id     NUMBER;
BEGIN
    APEX_JSON.PARSE(l_body);
    INSERT INTO RR_MCP_TOOL_REGISTRY
      (TOOL_NAME, DESCRIPTION, PARAMS_SCHEMA, HTTP_METHOD, URL_TEMPLATE,
       AUTH_TYPE, RESULT_FILTER, IS_ACTIVE, CREATED_BY, LAST_UPDATED_BY)
    VALUES (
      APEX_JSON.GET_VARCHAR2(p_path => 'toolName'),
      APEX_JSON.GET_VARCHAR2(p_path => 'description'),
      APEX_JSON.GET_VARCHAR2(p_path => 'paramsSchema'),
      NVL(APEX_JSON.GET_VARCHAR2(p_path => 'httpMethod'), 'GET'),
      APEX_JSON.GET_VARCHAR2(p_path => 'urlTemplate'),
      NVL(APEX_JSON.GET_VARCHAR2(p_path => 'authType'), 'NONE'),
      APEX_JSON.GET_VARCHAR2(p_path => 'resultFilter'),
      NVL(APEX_JSON.GET_VARCHAR2(p_path => 'isActive'), 'Y'),
      NVL(APEX_JSON.GET_VARCHAR2(p_path => 'createdBy'), 'ADMIN'),
      NVL(APEX_JSON.GET_VARCHAR2(p_path => 'createdBy'), 'ADMIN')
    ) RETURNING ID INTO l_id;
    COMMIT;
    :status_code := 201;
    HTP.PRN('{"status":"success","id":' || l_id || '}');
EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    :status_code := 500;
    HTP.PRN('{"status":"error","message":"' || REPLACE(SQLERRM,'"','\"') || '"}');
END;
]'
    );

    -- ── PUT /admin/mcptools/:id — update ─────────────────────────────────────
    BEGIN
        ORDS.DELETE_HANDLER(p_module_name => 'reerp', p_pattern => 'admin/mcptools/:id', p_method => 'PUT');
    EXCEPTION WHEN OTHERS THEN NULL; END;
    ORDS.DEFINE_HANDLER(
        p_module_name    => 'reerp',
        p_pattern        => 'admin/mcptools/:id',
        p_method         => 'PUT',
        p_source_type    => ORDS.source_type_plsql,
        p_mimes_allowed  => 'application/json',
        p_source         => q'[
DECLARE
    l_body CLOB := :body_text;
    l_cnt  NUMBER;
BEGIN
    APEX_JSON.PARSE(l_body);
    UPDATE RR_MCP_TOOL_REGISTRY SET
      TOOL_NAME        = NVL(APEX_JSON.GET_VARCHAR2(p_path => 'toolName'), TOOL_NAME),
      DESCRIPTION      = NVL(APEX_JSON.GET_VARCHAR2(p_path => 'description'), DESCRIPTION),
      PARAMS_SCHEMA    = NVL(APEX_JSON.GET_VARCHAR2(p_path => 'paramsSchema'), PARAMS_SCHEMA),
      HTTP_METHOD      = NVL(APEX_JSON.GET_VARCHAR2(p_path => 'httpMethod'), HTTP_METHOD),
      URL_TEMPLATE     = NVL(APEX_JSON.GET_VARCHAR2(p_path => 'urlTemplate'), URL_TEMPLATE),
      AUTH_TYPE        = NVL(APEX_JSON.GET_VARCHAR2(p_path => 'authType'), AUTH_TYPE),
      RESULT_FILTER    = NVL(APEX_JSON.GET_VARCHAR2(p_path => 'resultFilter'), RESULT_FILTER),
      IS_ACTIVE        = NVL(APEX_JSON.GET_VARCHAR2(p_path => 'isActive'), IS_ACTIVE),
      LAST_UPDATED_BY  = NVL(APEX_JSON.GET_VARCHAR2(p_path => 'updatedBy'), 'ADMIN'),
      LAST_UPDATE_DATE = SYSTIMESTAMP
    WHERE ID = TO_NUMBER(:id);
    l_cnt := SQL%ROWCOUNT;
    COMMIT;
    IF l_cnt = 0 THEN
        :status_code := 404;
        HTP.PRN('{"status":"error","message":"Tool not found"}');
    ELSE
        :status_code := 200;
        HTP.PRN('{"status":"success","rowsUpdated":' || l_cnt || '}');
    END IF;
EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    :status_code := 500;
    HTP.PRN('{"status":"error","message":"' || REPLACE(SQLERRM,'"','\"') || '"}');
END;
]'
    );

    -- ── DELETE /admin/mcptools/:id ───────────────────────────────────────────
    BEGIN
        ORDS.DELETE_HANDLER(p_module_name => 'reerp', p_pattern => 'admin/mcptools/:id', p_method => 'DELETE');
    EXCEPTION WHEN OTHERS THEN NULL; END;
    ORDS.DEFINE_HANDLER(
        p_module_name    => 'reerp',
        p_pattern        => 'admin/mcptools/:id',
        p_method         => 'DELETE',
        p_source_type    => ORDS.source_type_plsql,
        p_mimes_allowed  => '',
        p_source         => q'[
DECLARE
    l_cnt NUMBER;
BEGIN
    DELETE FROM RR_MCP_TOOL_REGISTRY WHERE ID = TO_NUMBER(:id);
    l_cnt := SQL%ROWCOUNT;
    COMMIT;
    IF l_cnt = 0 THEN
        :status_code := 404;
        HTP.PRN('{"status":"error","message":"Tool not found"}');
    ELSE
        :status_code := 200;
        HTP.PRN('{"status":"success"}');
    END IF;
EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    :status_code := 500;
    HTP.PRN('{"status":"error","message":"' || REPLACE(SQLERRM,'"','\"') || '"}');
END;
]'
    );

    COMMIT;
END;
