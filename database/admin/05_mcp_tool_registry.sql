-- ============================================================
-- 05_MCP_TOOL_REGISTRY.SQL   (v1)
--
-- Table: RR_MCP_TOOL_REGISTRY
-- Data-driven tool definitions for the generic MCP server
-- (electron/mcp-registry-server.cjs). Each active row becomes
-- an MCP tool exposed to Claude Desktop — adding a tool is an
-- INSERT, no code change or redeploy.
--
-- Endpoints:
--   GET    reerp/settings/mcptools      — active tools (used by the MCP server)
--   GET    reerp/admin/mcptools         — list all (admin screen)
--   POST   reerp/admin/mcptools         — create
--   PUT    reerp/admin/mcptools/:id     — update
--   DELETE reerp/admin/mcptools/:id     — delete
--
-- HOW TO RUN: APEX SQL Workshop -> SQL Commands -> run whole file.
-- ============================================================

CREATE TABLE RR_MCP_TOOL_REGISTRY (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TOOL_NAME        VARCHAR2(100) NOT NULL UNIQUE,
    DESCRIPTION      VARCHAR2(1000) NOT NULL,
    PARAMS_SCHEMA    CLOB,                      -- JSON: {"properties":{...},"required":[...]}
    HTTP_METHOD      VARCHAR2(10) DEFAULT 'GET' NOT NULL,
    URL_TEMPLATE     VARCHAR2(2000) NOT NULL,   -- full URL, {param} placeholders
    AUTH_TYPE        VARCHAR2(20) DEFAULT 'NONE' NOT NULL, -- NONE | BASIC_ORDS | BASIC_FUSION
    RESULT_FILTER    CLOB,                      -- JSON: {"path":"items[].child","where":{"field":"F","op":"!=","value":0}}
    IS_ACTIVE        VARCHAR2(1) DEFAULT 'Y' NOT NULL,
    CREATED_BY       VARCHAR2(150),
    CREATION_DATE    TIMESTAMP DEFAULT SYSTIMESTAMP,
    LAST_UPDATED_BY  VARCHAR2(150),
    LAST_UPDATE_DATE TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT CHK_RR_MCP_TOOL_ACTIVE CHECK (IS_ACTIVE IN ('Y','N')),
    CONSTRAINT CHK_RR_MCP_TOOL_METHOD CHECK (HTTP_METHOD IN ('GET','POST','PUT','DELETE')),
    CONSTRAINT CHK_RR_MCP_TOOL_AUTH   CHECK (AUTH_TYPE IN ('NONE','BASIC_ORDS','BASIC_FUSION'))
);

COMMENT ON TABLE  RR_MCP_TOOL_REGISTRY IS 'Data-driven MCP tool definitions for the generic MCP server';
COMMENT ON COLUMN RR_MCP_TOOL_REGISTRY.URL_TEMPLATE  IS 'Full URL with {param} placeholders substituted from tool arguments';
COMMENT ON COLUMN RR_MCP_TOOL_REGISTRY.RESULT_FILTER IS 'Optional declarative filter applied to the JSON response';

