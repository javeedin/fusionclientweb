-- ============================================
-- Table: RR_LEGAL_ENTITIES
-- Description: Stores legal entity information from Oracle Fusion
-- ============================================

CREATE TABLE RR_LEGAL_ENTITIES (
    ID                      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LEGAL_ENTITY_ID         NUMBER NOT NULL,
    NAME                    VARCHAR2(360) NOT NULL,
    LEGAL_ENTITY_IDENTIFIER VARCHAR2(60),
    EFFECTIVE_FROM          DATE,
    EFFECTIVE_TO            DATE,
    PARTY_ID                NUMBER,
    CREATED_BY              VARCHAR2(150),
    CREATION_DATE           TIMESTAMP,
    LAST_UPDATE_DATE        TIMESTAMP,
    LAST_UPDATE_LOGIN       VARCHAR2(100),
    LAST_UPDATED_BY         VARCHAR2(150),
    SYNC_DATE               TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT UK_RR_LEGAL_ENTITIES_ID UNIQUE (LEGAL_ENTITY_ID)
);

-- Indexes
CREATE INDEX IDX_RR_LEGAL_ENTITIES_NAME ON RR_LEGAL_ENTITIES(NAME);
CREATE INDEX IDX_RR_LEGAL_ENTITIES_IDENTIFIER ON RR_LEGAL_ENTITIES(LEGAL_ENTITY_IDENTIFIER);
CREATE INDEX IDX_RR_LEGAL_ENTITIES_PARTY ON RR_LEGAL_ENTITIES(PARTY_ID);

-- Comments
COMMENT ON TABLE RR_LEGAL_ENTITIES IS 'Legal entity master data synced from Oracle Fusion';
COMMENT ON COLUMN RR_LEGAL_ENTITIES.LEGAL_ENTITY_ID IS 'Unique legal entity identifier from Fusion';
COMMENT ON COLUMN RR_LEGAL_ENTITIES.NAME IS 'Legal entity name';
COMMENT ON COLUMN RR_LEGAL_ENTITIES.LEGAL_ENTITY_IDENTIFIER IS 'Legal entity identifier/code';
COMMENT ON COLUMN RR_LEGAL_ENTITIES.EFFECTIVE_FROM IS 'Effective from date';
COMMENT ON COLUMN RR_LEGAL_ENTITIES.EFFECTIVE_TO IS 'Effective to date';
COMMENT ON COLUMN RR_LEGAL_ENTITIES.PARTY_ID IS 'Party ID reference';
COMMENT ON COLUMN RR_LEGAL_ENTITIES.SYNC_DATE IS 'Timestamp when record was synced';

-- ============================================
-- Procedure: RR_SYNC_LEGAL_ENTITIES
-- Description: Upsert legal entities from JSON payload
-- ============================================

CREATE OR REPLACE PROCEDURE RR_SYNC_LEGAL_ENTITIES (
    p_json IN CLOB,
    p_count OUT NUMBER,
    p_error OUT VARCHAR2
) AS
    v_legal_entity_id         NUMBER;
    v_name                    VARCHAR2(360);
    v_legal_entity_identifier VARCHAR2(60);
    v_effective_from          DATE;
    v_effective_to            DATE;
    v_party_id                NUMBER;
    v_created_by              VARCHAR2(150);
    v_creation_date           TIMESTAMP;
    v_last_update_date        TIMESTAMP;
    v_last_update_login       VARCHAR2(100);
    v_last_updated_by         VARCHAR2(150);
BEGIN
    p_count := 0;
    p_error := NULL;

    FOR rec IN (
        SELECT *
        FROM JSON_TABLE(p_json, '$.items[*]'
            COLUMNS (
                legal_entity_id         NUMBER          PATH '$.LegalEntityId',
                name                    VARCHAR2(360)   PATH '$.Name',
                legal_entity_identifier VARCHAR2(60)    PATH '$.LegalEntityIdentifier',
                effective_from          DATE            PATH '$.EffectiveFrom',
                effective_to            DATE            PATH '$.EffectiveTo',
                party_id                NUMBER          PATH '$.PartyId',
                created_by              VARCHAR2(150)   PATH '$.CreatedBy',
                creation_date           TIMESTAMP       PATH '$.CreationDate',
                last_update_date        TIMESTAMP       PATH '$.LastUpdateDate',
                last_update_login       VARCHAR2(100)   PATH '$.LastUpdateLogin',
                last_updated_by         VARCHAR2(150)   PATH '$.LastUpdatedBy'
            )
        )
    ) LOOP
        -- Store values in local variables
        v_legal_entity_id         := rec.legal_entity_id;
        v_name                    := rec.name;
        v_legal_entity_identifier := rec.legal_entity_identifier;
        v_effective_from          := rec.effective_from;
        v_effective_to            := rec.effective_to;
        v_party_id                := rec.party_id;
        v_created_by              := rec.created_by;
        v_creation_date           := rec.creation_date;
        v_last_update_date        := rec.last_update_date;
        v_last_update_login       := rec.last_update_login;
        v_last_updated_by         := rec.last_updated_by;

        -- Use MERGE for upsert
        MERGE INTO RR_LEGAL_ENTITIES tgt
        USING (SELECT v_legal_entity_id AS legal_entity_id FROM DUAL) src
        ON (tgt.LEGAL_ENTITY_ID = src.legal_entity_id)
        WHEN MATCHED THEN
            UPDATE SET
                NAME                    = v_name,
                LEGAL_ENTITY_IDENTIFIER = v_legal_entity_identifier,
                EFFECTIVE_FROM          = v_effective_from,
                EFFECTIVE_TO            = v_effective_to,
                PARTY_ID                = v_party_id,
                CREATED_BY              = v_created_by,
                CREATION_DATE           = v_creation_date,
                LAST_UPDATE_DATE        = v_last_update_date,
                LAST_UPDATE_LOGIN       = v_last_update_login,
                LAST_UPDATED_BY         = v_last_updated_by,
                SYNC_DATE               = SYSTIMESTAMP
        WHEN NOT MATCHED THEN
            INSERT (
                LEGAL_ENTITY_ID,
                NAME,
                LEGAL_ENTITY_IDENTIFIER,
                EFFECTIVE_FROM,
                EFFECTIVE_TO,
                PARTY_ID,
                CREATED_BY,
                CREATION_DATE,
                LAST_UPDATE_DATE,
                LAST_UPDATE_LOGIN,
                LAST_UPDATED_BY,
                SYNC_DATE
            ) VALUES (
                v_legal_entity_id,
                v_name,
                v_legal_entity_identifier,
                v_effective_from,
                v_effective_to,
                v_party_id,
                v_created_by,
                v_creation_date,
                v_last_update_date,
                v_last_update_login,
                v_last_updated_by,
                SYSTIMESTAMP
            );

        p_count := p_count + 1;
    END LOOP;

    COMMIT;

EXCEPTION
    WHEN OTHERS THEN
        p_error := SQLERRM;
        ROLLBACK;
END RR_SYNC_LEGAL_ENTITIES;
