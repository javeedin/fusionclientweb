-- Spend from receipts (until AP invoices are linked): by month, category, supplier, cost centre account
CREATE OR REPLACE VIEW RR_PO_V_SPEND AS
SELECT h.BUSINESS_UNIT_ID, TRUNC(t.TRANSACTION_DATE, 'MM') AS SPEND_MONTH, h.SUPPLIER_ID, sm.SUPPLIER AS SUPPLIER_NAME,
       c.CATEGORY_CODE, c.CATEGORY_NAME, rd.CHARGE_ACCOUNT, SUM(rd.AMOUNT_FUNC) AS AMOUNT_FUNC
FROM   RR_PO_RCV_DISTRIBUTIONS rd
JOIN   RR_PO_RCV_TRANSACTIONS t ON t.RCV_TRANSACTION_ID = rd.RCV_TRANSACTION_ID
JOIN   RR_PO_HEADERS h          ON h.PO_HEADER_ID = t.PO_HEADER_ID
JOIN   RR_PO_LINES l            ON l.PO_LINE_ID = t.PO_LINE_ID
LEFT   JOIN RR_PO_CATEGORIES c  ON c.CATEGORY_ID = l.CATEGORY_ID
LEFT   JOIN RR_SUPPLIER_MASTER sm ON sm.SUPPLIER_ID = h.SUPPLIER_ID
GROUP  BY h.BUSINESS_UNIT_ID, TRUNC(t.TRANSACTION_DATE, 'MM'), h.SUPPLIER_ID, sm.SUPPLIER, c.CATEGORY_CODE,
          c.CATEGORY_NAME, rd.CHARGE_ACCOUNT;

-- AI gateway access: when RR_AI_OBJECT_ACL runs in whitelist mode (any 'Y' row), the PO views
-- must be listed; in open mode nothing is added (adding 'Y' rows would switch it to whitelist mode).
DECLARE
    v_whitelist NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_whitelist FROM RR_AI_OBJECT_ACL WHERE ALLOWED_FLAG = 'Y';
    IF v_whitelist > 0 THEN
        FOR v IN (SELECT view_name FROM user_views WHERE view_name LIKE 'RR\_PO\_V\_%' ESCAPE '\'
                  UNION ALL SELECT table_name FROM user_tables WHERE table_name IN
                  ('RR_PO_CATEGORIES','RR_PO_LOCATIONS','RR_PO_UOMS','RR_PO_EXPENSE_ITEMS','RR_PO_BUYERS',
                   'RR_PO_REQUESTER_DEFAULTS','RR_PO_ACCOUNT_RULES','RR_PO_DOC_SEQUENCES','RR_PO_BU_OPTIONS',
                   'RR_PO_SUPPLIER_SITE_OPTIONS','RR_PO_REVISIONS','RR_PO_EXEC_LOG')) LOOP
            MERGE INTO RR_AI_OBJECT_ACL t USING (SELECT v.view_name n FROM dual) s ON (t.OBJECT_NAME = s.n)
            WHEN NOT MATCHED THEN INSERT (OBJECT_NAME, ALLOWED_FLAG) VALUES (s.n, 'Y');
        END LOOP;
        COMMIT;
    END IF;
EXCEPTION WHEN OTHERS THEN NULL;   -- AI gateway not installed: nothing to do
END;
