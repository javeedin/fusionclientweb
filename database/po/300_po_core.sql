MERGE INTO RR_PO_UOMS t
USING (SELECT 'EA' c, 'Each' n, 'COUNT' k FROM dual UNION ALL SELECT 'BOX','Box','COUNT' FROM dual
       UNION ALL SELECT 'PK','Pack','COUNT' FROM dual UNION ALL SELECT 'SET','Set','COUNT' FROM dual
       UNION ALL SELECT 'HR','Hour','TIME' FROM dual UNION ALL SELECT 'DAY','Day','TIME' FROM dual
       UNION ALL SELECT 'MON','Month','TIME' FROM dual UNION ALL SELECT 'YR','Year','TIME' FROM dual
       UNION ALL SELECT 'KG','Kilogram','WEIGHT' FROM dual UNION ALL SELECT 'LTR','Litre','VOLUME' FROM dual
       UNION ALL SELECT 'M','Metre','LENGTH' FROM dual UNION ALL SELECT 'LOT','Lot','COUNT' FROM dual) s
ON (t.UOM_CODE = s.c)
WHEN NOT MATCHED THEN INSERT (UOM_CODE, UOM_NAME, UOM_CLASS, CREATED_BY) VALUES (s.c, s.n, s.k, 'SEED');

