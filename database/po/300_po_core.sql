       UNION ALL SELECT 'FACILITIES.MAINTENANCE','Repairs & Maintenance','FACILITIES','AMOUNT','Y' FROM dual
       UNION ALL SELECT 'FACILITIES.CLEANING','Cleaning Services','FACILITIES','AMOUNT','Y' FROM dual
