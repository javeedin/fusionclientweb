-- =====================================================
-- AR Receipts — Multiple Credit Accounts
-- Table   : RR_AR_RECEIPTS_MULTIPLE_CREDITS
-- Parent  : RR_AR_RECEIPTS (STANDARD_RECEIPT_ID)
-- ORDS    : module 'ar'
--             GET  ar/receipts/:id/credits   — list credit lines
--             PUT  ar/receipts/:id/credits   — replace all lines (atomic,
--                                              validates sum = receipt amount)
-- A receipt is single-credit by default (CR_ACCOUNT on RR_AR_RECEIPTS).
-- When MULTI_CR_FLAG = 'Y' the credit side lives in this table instead.
-- =====================================================

-- DROP TABLE RR_AR_RECEIPTS_MULTIPLE_CREDITS CASCADE CONSTRAINTS;

CREATE TABLE RR_AR_RECEIPTS_MULTIPLE_CREDITS (
    CREDIT_LINE_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STANDARD_RECEIPT_ID   NUMBER         NOT NULL,
    RECEIPT_NUMBER        VARCHAR2(50),
    LINE_NUMBER           NUMBER         NOT NULL,
    CR_ACCOUNT            VARCHAR2(100)  NOT NULL,   -- GL code combination (segments joined by '-')
    CR_ACCOUNT_DESC       VARCHAR2(500),
    AMOUNT                NUMBER(18,2)   NOT NULL,
    CURRENCY              VARCHAR2(15),
    ACCOUNT_STATUS        VARCHAR2(20)   DEFAULT 'Unposted',   -- Unposted | Posted | Error
    COMMENTS              VARCHAR2(1000),
    CREATED_BY            VARCHAR2(240),
    CREATION_DATE         TIMESTAMP      DEFAULT SYSTIMESTAMP,
    LAST_UPDATED_BY       VARCHAR2(240),
    LAST_UPDATE_DATE      TIMESTAMP      DEFAULT SYSTIMESTAMP,
    CONSTRAINT RR_AR_MULTI_CR_FK  FOREIGN KEY (STANDARD_RECEIPT_ID)
        REFERENCES RR_AR_RECEIPTS (STANDARD_RECEIPT_ID) ON DELETE CASCADE,
    CONSTRAINT RR_AR_MULTI_CR_AMT_CK CHECK (AMOUNT > 0),
    CONSTRAINT RR_AR_MULTI_CR_UK UNIQUE (STANDARD_RECEIPT_ID, LINE_NUMBER)
);

CREATE INDEX RR_AR_MULTI_CR_IX1 ON RR_AR_RECEIPTS_MULTIPLE_CREDITS (STANDARD_RECEIPT_ID);

COMMENT ON TABLE RR_AR_RECEIPTS_MULTIPLE_CREDITS IS
    'Credit-side GL distribution lines for AR receipts using multiple credit accounts (MULTI_CR_FLAG = Y on RR_AR_RECEIPTS)';

-- Flag on the parent: 'N' (default) = single Cr Account column, 'Y' = lines in this table
ALTER TABLE RR_AR_RECEIPTS ADD (
    MULTI_CR_FLAG  VARCHAR2(1) DEFAULT 'N'
);

