-- =====================================================
-- 3. GET /ar/receipts/:receiptId/attachments
-- =====================================================
BEGIN
    ORDS.DEFINE_HANDLER(
        p_module_name    => 'ar',
        p_pattern        => 'receipts/:receiptId/attachments',
        p_method         => 'GET',
        p_source_type    => ORDS.source_type_plsql,
        p_items_per_page => 0,
        p_comments       => 'List attachments for an AR receipt (no content)',
        p_source         => q'[
DECLARE
    l_json  CLOB    := '{"items":[';
    l_first BOOLEAN := TRUE;
BEGIN
    FOR r IN (
        SELECT ID, FILE_NAME, FILE_TYPE, FILE_SIZE, CREATED_BY,
               TO_CHAR(CREATED_DATE, 'YYYY-MM-DD"T"HH24:MI:SS') AS CREATED_DATE
          FROM RR_AR_RECEIPTS_ATTACHMENTS
         WHERE STANDARD_RECEIPT_ID = :receiptId
         ORDER BY CREATED_DATE DESC
    ) LOOP
        IF NOT l_first THEN l_json := l_json || ','; END IF;
        l_first := FALSE;
        l_json := l_json
            || '{"id":'         || r.ID
            || ',"fileName":'   || APEX_JSON.STRINGIFY(r.FILE_NAME)
            || ',"fileType":'   || APEX_JSON.STRINGIFY(NVL(r.FILE_TYPE,''))
            || ',"fileSize":'   || NVL(TO_CHAR(r.FILE_SIZE),'null')
            || ',"createdBy":'  || APEX_JSON.STRINGIFY(NVL(r.CREATED_BY,''))
            || ',"createdDate":' || APEX_JSON.STRINGIFY(NVL(r.CREATED_DATE,''))
            || '}';
    END LOOP;
    l_json := l_json || ']}';
    HTP.P(l_json);
EXCEPTION WHEN OTHERS THEN
    HTP.P('{"items":[],"error":' || APEX_JSON.STRINGIFY(SQLERRM) || '}');
END;
]'
    );
    COMMIT;
END;
/

-- =====================================================
-- 4. POST /ar/receipts/:receiptId/attachments
--    Body: { "fileName":"...", "fileType":"...", "fileSize":N, "content":"base64..." }
-- =====================================================
BEGIN
    ORDS.DEFINE_HANDLER(
        p_module_name    => 'ar',
        p_pattern        => 'receipts/:receiptId/attachments',
        p_method         => 'POST',
        p_source_type    => ORDS.source_type_plsql,
        p_mimes_allowed  => 'application/json',
        p_items_per_page => 0,
        p_comments       => 'Upload attachment for an AR receipt — JSON body',
        p_source         => q'[
DECLARE
    v_file_name  VARCHAR2(500);
    v_file_type  VARCHAR2(100);
    v_file_size  NUMBER;
    v_content    CLOB;
    v_new_id     NUMBER;
    v_body       CLOB;
    v_dest_off   INTEGER := 1;
    v_src_off    INTEGER := 1;
    v_lang_ctx   INTEGER := DBMS_LOB.DEFAULT_LANG_CTX;
    v_warning    INTEGER;
BEGIN
    DBMS_LOB.CREATETEMPORARY(v_body, TRUE);
    DBMS_LOB.CONVERTTOCLOB(
        v_body, :body, DBMS_LOB.LOBMAXSIZE,
        v_dest_off, v_src_off,
        NLS_CHARSET_ID('AL32UTF8'), v_lang_ctx, v_warning
    );

    APEX_JSON.PARSE(v_body);
    v_file_name := APEX_JSON.GET_VARCHAR2(p_path => 'fileName');
    v_file_type := APEX_JSON.GET_VARCHAR2(p_path => 'fileType');
    v_file_size := APEX_JSON.GET_NUMBER(p_path  => 'fileSize');
    v_content   := APEX_JSON.GET_CLOB(p_path    => 'content');

    INSERT INTO RR_AR_RECEIPTS_ATTACHMENTS
        (STANDARD_RECEIPT_ID, FILE_NAME, FILE_TYPE, FILE_SIZE, FILE_CONTENT, CREATED_BY)
    VALUES
        (:receiptId, v_file_name, v_file_type, v_file_size, v_content, USER)
    RETURNING ID INTO v_new_id;
    COMMIT;

    :status_code := 201;
    HTP.P('{"status":"success","id":' || v_new_id
        || ',"fileName":'  || APEX_JSON.STRINGIFY(v_file_name)
        || ',"receiptId":' || TO_CHAR(:receiptId)
        || '}');
EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    :status_code := 500;
    HTP.P('{"status":"error","message":' || APEX_JSON.STRINGIFY(SQLERRM) || '}');
END;
]'
    );
    COMMIT;
END;
/

