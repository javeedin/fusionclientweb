-- =====================================================
-- 6. GET /ar/receipts/:receiptId/attachments/:attachmentId
--    Returns full content for preview/download
-- =====================================================
BEGIN
    ORDS.DEFINE_HANDLER(
        p_module_name    => 'ar',
        p_pattern        => 'receipts/:receiptId/attachments/:attachmentId',
        p_method         => 'GET',
        p_source_type    => ORDS.source_type_plsql,
        p_items_per_page => 0,
        p_comments       => 'Fetch single attachment with base64 content',
        p_source         => q'[
DECLARE
    r RR_AR_RECEIPTS_ATTACHMENTS%ROWTYPE;
BEGIN
    SELECT * INTO r
      FROM RR_AR_RECEIPTS_ATTACHMENTS
     WHERE ID = :attachmentId
       AND STANDARD_RECEIPT_ID = :receiptId;

    HTP.P('{"id":'        || r.ID
        || ',"fileName":' || APEX_JSON.STRINGIFY(r.FILE_NAME)
        || ',"fileType":' || APEX_JSON.STRINGIFY(NVL(r.FILE_TYPE,''))
        || ',"fileSize":' || NVL(TO_CHAR(r.FILE_SIZE),'null')
        || ',"content":'  || APEX_JSON.STRINGIFY(NVL(r.FILE_CONTENT,''))
        || '}');
EXCEPTION WHEN NO_DATA_FOUND THEN
    :status_code := 404;
    HTP.P('{"error":"Not found"}');
WHEN OTHERS THEN
    :status_code := 500;
    HTP.P('{"error":' || APEX_JSON.STRINGIFY(SQLERRM) || '}');
END;
]'
    );
    COMMIT;
END;
/

-- =====================================================
-- 7. DELETE /ar/receipts/:receiptId/attachments/:attachmentId
-- =====================================================
BEGIN
    ORDS.DEFINE_HANDLER(
        p_module_name    => 'ar',
        p_pattern        => 'receipts/:receiptId/attachments/:attachmentId',
        p_method         => 'DELETE',
        p_source_type    => ORDS.source_type_plsql,
        p_items_per_page => 0,
        p_comments       => 'Delete an AR receipt attachment',
        p_source         => q'[
BEGIN
    DELETE FROM RR_AR_RECEIPTS_ATTACHMENTS
     WHERE ID = :attachmentId
       AND STANDARD_RECEIPT_ID = :receiptId;

    IF SQL%ROWCOUNT = 0 THEN
        :status_code := 404;
        HTP.P('{"status":"error","message":"Attachment not found"}');
    ELSE
        COMMIT;
        :status_code := 200;
        HTP.P('{"status":"success"}');
    END IF;
EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    :status_code := 500;
    HTP.P('{"status":"error","message":' || APEX_JSON.STRINGIFY(SQLERRM) || '}');
END;
]'
    );
    COMMIT;
END;
