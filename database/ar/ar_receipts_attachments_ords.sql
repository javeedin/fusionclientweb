-- =====================================================
-- 1. Table
-- =====================================================
CREATE TABLE RR_AR_RECEIPTS_ATTACHMENTS (
    ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STANDARD_RECEIPT_ID NUMBER NOT NULL,
    FILE_NAME           VARCHAR2(500) NOT NULL,
    FILE_TYPE           VARCHAR2(100),
    FILE_SIZE           NUMBER,
    FILE_CONTENT        CLOB,   -- Base64-encoded content
    CREATED_BY          VARCHAR2(150),
    CREATED_DATE        TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT FK_AR_RCPT_ATT FOREIGN KEY (STANDARD_RECEIPT_ID)
        REFERENCES RR_AR_RECEIPTS(STANDARD_RECEIPT_ID)
);

CREATE INDEX IDX_RR_ARATT_RCPT ON RR_AR_RECEIPTS_ATTACHMENTS(STANDARD_RECEIPT_ID);

