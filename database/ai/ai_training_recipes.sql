-- =====================================================
-- AI Assistant — Training Recipes ("teach the assistant")
-- Table   : RR_AI_TRAINING
-- ORDS    : module 'reerp'
--             GET    ai/training       — list recipes (?all=Y includes disabled)
--             POST   ai/training       — create a recipe
--             PUT    ai/training/:id   — update a recipe (fields sent are updated)
--             DELETE ai/training/:id   — delete a recipe
--
-- A recipe teaches the in-app AI Assistant one action: a webservice call
-- (usually a page's search GET) with its parameters, labels and example
-- values. Recipes are loaded into the assistant's system prompt at runtime,
-- so anything taught here works immediately for every user — no code.
--
-- Recipes are captured two ways:
--   1. "Teach AI" button on a page after running a search (sends the exact
--      URL + parameter values that page used)
--   2. In chat: the assistant itself POSTs here via its user-approved
--      erp_api_write tool when the user says "learn this: ..."
-- =====================================================

-- DROP TABLE RR_AI_TRAINING CASCADE CONSTRAINTS;

CREATE TABLE RR_AI_TRAINING (
    RECIPE_ID     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    RECIPE_NAME   VARCHAR2(200)  NOT NULL,
    DESCRIPTION   VARCHAR2(2000),                 -- when to use it: phrases, intent
    MODULE        VARCHAR2(30),                   -- GL / AP / AR / CASH / FA / PC ...
    METHOD        VARCHAR2(10)   DEFAULT 'GET' NOT NULL,
    URL_TEMPLATE  VARCHAR2(1000) NOT NULL,        -- path only, e.g. /cash/externaltransactions
    PARAMS_JSON   CLOB,                           -- [{"name","label","example","required","description"}]
    EXAMPLE_JSON  CLOB,                           -- the exact values captured at teach time
    APP_PATH      VARCHAR2(300),                  -- related app page (for navigate_to_page)
    ENABLED       VARCHAR2(1)    DEFAULT 'Y' NOT NULL,
    CREATED_BY    VARCHAR2(240),
    CREATION_DATE TIMESTAMP      DEFAULT SYSTIMESTAMP,
    LAST_UPDATED_BY  VARCHAR2(240),
    LAST_UPDATE_DATE TIMESTAMP,
    CONSTRAINT RR_AI_TRAINING_METHOD_CK  CHECK (METHOD IN ('GET','POST','PUT','DELETE','PATCH')),
    CONSTRAINT RR_AI_TRAINING_ENABLED_CK CHECK (ENABLED IN ('Y','N')),
    CONSTRAINT RR_AI_TRAINING_PARAMS_CK  CHECK (PARAMS_JSON  IS JSON),
    CONSTRAINT RR_AI_TRAINING_EXAMPLE_CK CHECK (EXAMPLE_JSON IS JSON)
);

COMMENT ON TABLE RR_AI_TRAINING IS
    'Taught recipes for the in-app AI Assistant: webservice calls with parameters, captured from pages or from chat';

