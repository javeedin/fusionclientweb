-- ── PUT /ai/training/:id ─────────────────────────────
BEGIN
    ORDS.DEFINE_HANDLER(
        p_module_name   => 'reerp',
        p_pattern       => 'ai/training/:id',
        p_method        => 'PUT',
        p_source_type   => 'plsql/block',
        p_mimes_allowed => 'application/json',
        p_comments      => 'Update an AI training recipe (only fields present in the body change)',
        p_source        => '
DECLARE
    l_body    CLOB := :body_text;
    l_id      NUMBER := :id;
    l_count   NUMBER;
    l_params  CLOB;
    l_example CLOB;
BEGIN
    APEX_JSON.PARSE(l_body);

    SELECT COUNT(*) INTO l_count FROM rr_ai_training WHERE recipe_id = l_id;
    IF l_count = 0 THEN
        :status_code := 404;
        HTP.P(''{"success":false,"message":"Recipe '' || l_id || '' not found"}'');
        RETURN;
    END IF;

    BEGIN l_params  := APEX_JSON.GET_CLOB(p_path => ''paramsJson'');  EXCEPTION WHEN OTHERS THEN l_params  := APEX_JSON.GET_VARCHAR2(p_path => ''paramsJson'');  END;
    BEGIN l_example := APEX_JSON.GET_CLOB(p_path => ''exampleJson''); EXCEPTION WHEN OTHERS THEN l_example := APEX_JSON.GET_VARCHAR2(p_path => ''exampleJson''); END;

    UPDATE rr_ai_training
    SET    recipe_name  = NVL(APEX_JSON.GET_VARCHAR2(p_path => ''recipeName''), recipe_name),
           description  = NVL(APEX_JSON.GET_VARCHAR2(p_path => ''description''), description),
           module       = NVL(UPPER(APEX_JSON.GET_VARCHAR2(p_path => ''module'')), module),
           method       = NVL(UPPER(APEX_JSON.GET_VARCHAR2(p_path => ''method'')), method),
           url_template = NVL(APEX_JSON.GET_VARCHAR2(p_path => ''urlTemplate''), url_template),
           app_path     = NVL(APEX_JSON.GET_VARCHAR2(p_path => ''appPath''), app_path),
           enabled      = NVL(UPPER(APEX_JSON.GET_VARCHAR2(p_path => ''enabled'')), enabled),
           params_json  = NVL(l_params,  params_json),
           example_json = NVL(l_example, example_json),
           last_updated_by  = NVL(APEX_JSON.GET_VARCHAR2(p_path => ''updatedBy''), ''REERP''),
           last_update_date = SYSTIMESTAMP
    WHERE  recipe_id = l_id;
    COMMIT;

    HTP.P(''{"success":true,"recipeId":'' || l_id || '',"message":"Recipe updated"}'');
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        :status_code := 500;
        HTP.P(''{"success":false,"message":"'' || REPLACE(SQLERRM, ''"'', '''''''') || ''"}'');
END;'
    );
    COMMIT;
END;
/

