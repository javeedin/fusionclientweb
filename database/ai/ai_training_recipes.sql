-- ── GET /ai/training ─────────────────────────────────
BEGIN
    ORDS.DEFINE_HANDLER(
        p_module_name => 'reerp',
        p_pattern     => 'ai/training',
        p_method      => 'GET',
        p_source_type => 'json/collection',
        p_comments    => 'List AI training recipes (?all=Y includes disabled)',
        p_source      => '
SELECT recipe_id                                  AS "recipeId",
       recipe_name                                AS "recipeName",
       description                                AS "description",
       module                                     AS "module",
       method                                     AS "method",
       url_template                               AS "urlTemplate",
       params_json                                AS "paramsJson",
       example_json                               AS "exampleJson",
       app_path                                   AS "appPath",
       enabled                                    AS "enabled",
       created_by                                 AS "createdBy",
       TO_CHAR(creation_date,   ''YYYY-MM-DD HH24:MI'') AS "createdAt",
       TO_CHAR(last_update_date,''YYYY-MM-DD HH24:MI'') AS "updatedAt"
FROM   rr_ai_training
WHERE  (NVL(:all, ''N'') = ''Y'' OR enabled = ''Y'')
ORDER  BY module, recipe_name'
    );
    COMMIT;
END;
/

-- ── POST /ai/training ────────────────────────────────
BEGIN
    ORDS.DEFINE_HANDLER(
        p_module_name   => 'reerp',
        p_pattern       => 'ai/training',
        p_method        => 'POST',
        p_source_type   => 'plsql/block',
        p_mimes_allowed => 'application/json',
        p_comments      => 'Create an AI training recipe',
        p_source        => '
DECLARE
    l_body     CLOB := :body_text;
    l_name     VARCHAR2(200);
    l_desc     VARCHAR2(2000);
    l_module   VARCHAR2(30);
    l_method   VARCHAR2(10);
    l_url      VARCHAR2(1000);
    l_params   CLOB;
    l_example  CLOB;
    l_apppath  VARCHAR2(300);
    l_by       VARCHAR2(240);
    l_id       NUMBER;
BEGIN
    APEX_JSON.PARSE(l_body);
    l_name    := APEX_JSON.GET_VARCHAR2(p_path => ''recipeName'');
    l_desc    := APEX_JSON.GET_VARCHAR2(p_path => ''description'');
    l_module  := UPPER(APEX_JSON.GET_VARCHAR2(p_path => ''module''));
    l_method  := UPPER(NVL(APEX_JSON.GET_VARCHAR2(p_path => ''method''), ''GET''));
    l_url     := APEX_JSON.GET_VARCHAR2(p_path => ''urlTemplate'');
    l_apppath := APEX_JSON.GET_VARCHAR2(p_path => ''appPath'');
    l_by      := NVL(APEX_JSON.GET_VARCHAR2(p_path => ''createdBy''), ''REERP'');

    -- params/example are sent as pre-stringified JSON strings
    BEGIN l_params  := APEX_JSON.GET_CLOB(p_path => ''paramsJson'');  EXCEPTION WHEN OTHERS THEN l_params  := APEX_JSON.GET_VARCHAR2(p_path => ''paramsJson'');  END;
    BEGIN l_example := APEX_JSON.GET_CLOB(p_path => ''exampleJson''); EXCEPTION WHEN OTHERS THEN l_example := APEX_JSON.GET_VARCHAR2(p_path => ''exampleJson''); END;

    IF l_name IS NULL OR l_url IS NULL THEN
        :status_code := 400;
        HTP.P(''{"success":false,"message":"recipeName and urlTemplate are required"}'');
        RETURN;
    END IF;
    IF SUBSTR(l_url, 1, 1) <> ''/'' THEN
        :status_code := 400;
        HTP.P(''{"success":false,"message":"urlTemplate must start with /"}'');
        RETURN;
    END IF;

    INSERT INTO rr_ai_training
        (recipe_name, description, module, method, url_template,
         params_json, example_json, app_path, enabled, created_by)
    VALUES
        (l_name, l_desc, l_module, l_method, l_url,
         l_params, l_example, l_apppath, ''Y'', l_by)
    RETURNING recipe_id INTO l_id;
    COMMIT;

    :status_code := 201;
    HTP.P(''{"success":true,"recipeId":'' || l_id || '',"message":"Recipe saved"}'');
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        :status_code := 500;
        HTP.P(''{"success":false,"message":"'' || REPLACE(SQLERRM, ''"'', '''''''') || ''"}'');
END;'
    );
    COMMIT;
END;
