-- ============================================
-- RR_AP_PAYMENTS_ALL Table
-- Stores AP Payment data from Oracle Fusion
-- ============================================

-- Drop table if exists (optional - comment out in production)
-- DROP TABLE RR_AP_PAYMENTS_ALL CASCADE CONSTRAINTS;

CREATE TABLE RR_AP_PAYMENTS_ALL (
    -- Primary Keys
    ID                              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CHECK_ID                        NUMBER NOT NULL,
    PAYMENT_ID                      NUMBER,

    -- Payment Identification
    PAYMENT_REFERENCE               VARCHAR2(240),
    PAPER_DOCUMENT_NUMBER           VARCHAR2(100),
    PAYMENT_NUMBER                  VARCHAR2(100),
    PAYMENT_FILE_REFERENCE          NUMBER,
    PAYMENT_PROCESS_REQUEST         VARCHAR2(500),
    VOUCHER_NUMBER                  VARCHAR2(100),

    -- Payment Amounts
    PAYMENT_AMOUNT                  NUMBER(18,2),
    PAYMENT_BASE_AMOUNT             NUMBER(18,2),
    WITHHELD_AMOUNT                 NUMBER(18,2),
    BANK_CHARGE_AMOUNT              NUMBER(18,2),

    -- Payment Dates
    PAYMENT_DATE                    DATE,
    ACCOUNTING_DATE                 DATE,
    MATURITY_DATE                   DATE,
    ANTICIPATED_VALUE_DATE          DATE,
    STOP_DATE                       DATE,
    VOID_DATE                       DATE,
    VOID_ACCOUNTING_DATE            DATE,

    -- Payment Details
    PAYMENT_DESCRIPTION             VARCHAR2(500),
    PAYMENT_STATUS                  VARCHAR2(50),
    PAYMENT_TYPE                    VARCHAR2(50),
    PAYMENT_MODE                    VARCHAR2(50),
    PAYMENT_FUNCTION                VARCHAR2(100),

    -- Currency Information
    PAYMENT_CURRENCY                VARCHAR2(15),
    PAYMENT_BASE_CURRENCY           VARCHAR2(15),
    CONVERSION_RATE                 NUMBER(18,6),
    CONVERSION_DATE                 DATE,
    CONVERSION_RATE_TYPE            VARCHAR2(50),
    CROSS_CURRENCY_RATE_TYPE        VARCHAR2(50),

    -- Clearing Information
    CLEARING_DATE                   DATE,
    CLEARING_AMOUNT                 NUMBER(18,2),
    CLEARING_LEDGER_AMOUNT          NUMBER(18,2),
    CLEARING_CONVERSION_RATE        NUMBER(18,6),
    CLEARING_CONVERSION_DATE        DATE,
    CLEARING_CONVERSION_RATE_TYPE   VARCHAR2(50),
    CLEARING_VALUE_DATE             DATE,

    -- Maturity Conversion
    MATURITY_CONVERSION_RATE_TYPE   VARCHAR2(50),
    MATURITY_CONVERSION_DATE        DATE,
    MATURITY_CONVERSION_RATE        NUMBER(18,6),

    -- Status Flags
    ACCOUNTING_STATUS               VARCHAR2(50),
    RECONCILED_FLAG                 VARCHAR2(1),
    SEPARATE_REMITTANCE_ADVICE_CREATED VARCHAR2(1),
    IBY_PAYMENT_STATUS              VARCHAR2(50),

    -- Organization
    LEGAL_ENTITY                    VARCHAR2(240),
    BUSINESS_UNIT                   VARCHAR2(240),
    PROCUREMENT_BU                  VARCHAR2(240),

    -- Payee Information
    PAYEE                           VARCHAR2(360),
    PARTY_ID                        NUMBER,
    PAYEE_SITE                      VARCHAR2(240),
    SUPPLIER_NUMBER                 VARCHAR2(100),
    EMPLOYEE_ADDRESS                VARCHAR2(500),
    THIRD_PARTY_SUPPLIER            VARCHAR2(360),
    THIRD_PARTY_ADDRESS_NAME        VARCHAR2(240),

    -- Bank Account Information
    EXTERNAL_BANK_ACCOUNT_ID        NUMBER,
    REMIT_TO_ACCOUNT_NUMBER         VARCHAR2(100),
    DISBURSEMENT_BANK_ACCOUNT_NUMBER VARCHAR2(100),
    DISBURSEMENT_BANK_ACCOUNT_NAME  VARCHAR2(240),
    FUNDING_CARD_ACCOUNT            VARCHAR2(100),
    DIGITAL_PAYMENT_ACCOUNT         VARCHAR2(100),

    -- Payment Method
    PAYMENT_METHOD_CODE             VARCHAR2(50),
    PAYMENT_METHOD                  VARCHAR2(100),
    PAYMENT_DOCUMENT                VARCHAR2(240),
    PAYMENT_PROCESS_PROFILE_CODE    VARCHAR2(100),
    PAYMENT_PROCESS_PROFILE         VARCHAR2(240),

    -- Document Information
    DOCUMENT_CATEGORY               VARCHAR2(100),
    DOCUMENT_SEQUENCE               VARCHAR2(100),

    -- Address Information
    ADDRESS_LINE1                   VARCHAR2(240),
    ADDRESS_LINE2                   VARCHAR2(240),
    ADDRESS_LINE3                   VARCHAR2(240),
    ADDRESS_LINE4                   VARCHAR2(240),
    CITY                            VARCHAR2(100),
    COUNTY                          VARCHAR2(100),
    PROVINCE                        VARCHAR2(100),
    STATE                           VARCHAR2(100),
    COUNTRY                         VARCHAR2(10),
    ZIP                             VARCHAR2(50),

    -- Stop/Void Information
    STOP_REASON                     VARCHAR2(500),
    STOP_REFERENCE                  VARCHAR2(240),

    -- Audit Columns
    CREATED_BY                      VARCHAR2(100),
    CREATION_DATE                   TIMESTAMP WITH TIME ZONE,
    LAST_UPDATED_BY                 VARCHAR2(100),
    LAST_UPDATE_DATE                TIMESTAMP WITH TIME ZONE,
    LAST_UPDATE_LOGIN               VARCHAR2(100),

    -- Local Audit Columns
    LOCAL_CREATED_DATE              TIMESTAMP DEFAULT SYSTIMESTAMP,
    LOCAL_UPDATED_DATE              TIMESTAMP DEFAULT SYSTIMESTAMP,
    SYNC_STATUS                     VARCHAR2(20) DEFAULT 'SYNCED',

    -- Constraints
    CONSTRAINT RR_AP_PAYMENTS_UK1 UNIQUE (CHECK_ID)
);

-- Create indexes for better query performance
CREATE INDEX RR_AP_PAYMENTS_N1 ON RR_AP_PAYMENTS_ALL (PAYMENT_NUMBER);
CREATE INDEX RR_AP_PAYMENTS_N2 ON RR_AP_PAYMENTS_ALL (PAYMENT_DATE);
CREATE INDEX RR_AP_PAYMENTS_N3 ON RR_AP_PAYMENTS_ALL (PAYEE);
CREATE INDEX RR_AP_PAYMENTS_N4 ON RR_AP_PAYMENTS_ALL (PAYMENT_STATUS);
CREATE INDEX RR_AP_PAYMENTS_N5 ON RR_AP_PAYMENTS_ALL (BUSINESS_UNIT);
CREATE INDEX RR_AP_PAYMENTS_N6 ON RR_AP_PAYMENTS_ALL (SUPPLIER_NUMBER);
CREATE INDEX RR_AP_PAYMENTS_N7 ON RR_AP_PAYMENTS_ALL (PARTY_ID);

-- ============================================
-- Migration: fix column data types (table has existing rows)
-- Oracle ORA-01439: MODIFY cannot change type on non-empty table.
-- Workaround: rename old → add new VARCHAR2 → copy → drop old
-- Run each block in order in APEX SQL Workshop or SQLcl
-- ============================================

-- PAYMENT_REFERENCE: NUMBER → VARCHAR2(240)
ALTER TABLE RR_AP_PAYMENTS_ALL RENAME COLUMN PAYMENT_REFERENCE TO PAYMENT_REFERENCE_OLD;
ALTER TABLE RR_AP_PAYMENTS_ALL ADD (PAYMENT_REFERENCE VARCHAR2(240));
UPDATE RR_AP_PAYMENTS_ALL SET PAYMENT_REFERENCE = TO_CHAR(PAYMENT_REFERENCE_OLD)
  WHERE PAYMENT_REFERENCE_OLD IS NOT NULL;
ALTER TABLE RR_AP_PAYMENTS_ALL DROP COLUMN PAYMENT_REFERENCE_OLD;
COMMIT;

-- VOUCHER_NUMBER: NUMBER → VARCHAR2(100)
ALTER TABLE RR_AP_PAYMENTS_ALL RENAME COLUMN VOUCHER_NUMBER TO VOUCHER_NUMBER_OLD;
ALTER TABLE RR_AP_PAYMENTS_ALL ADD (VOUCHER_NUMBER VARCHAR2(100));
UPDATE RR_AP_PAYMENTS_ALL SET VOUCHER_NUMBER = TO_CHAR(VOUCHER_NUMBER_OLD)
  WHERE VOUCHER_NUMBER_OLD IS NOT NULL;
ALTER TABLE RR_AP_PAYMENTS_ALL DROP COLUMN VOUCHER_NUMBER_OLD;
COMMIT;

-- PAPER_DOCUMENT_NUMBER: NUMBER → VARCHAR2(100)
ALTER TABLE RR_AP_PAYMENTS_ALL RENAME COLUMN PAPER_DOCUMENT_NUMBER TO PAPER_DOCUMENT_NUMBER_OLD;
ALTER TABLE RR_AP_PAYMENTS_ALL ADD (PAPER_DOCUMENT_NUMBER VARCHAR2(100));
UPDATE RR_AP_PAYMENTS_ALL SET PAPER_DOCUMENT_NUMBER = TO_CHAR(PAPER_DOCUMENT_NUMBER_OLD)
  WHERE PAPER_DOCUMENT_NUMBER_OLD IS NOT NULL;
ALTER TABLE RR_AP_PAYMENTS_ALL DROP COLUMN PAPER_DOCUMENT_NUMBER_OLD;
COMMIT;

-- PAYMENT_NUMBER: NUMBER → VARCHAR2(100)  (also recreate index for VARCHAR2 column)
DROP INDEX RR_AP_PAYMENTS_N1;
ALTER TABLE RR_AP_PAYMENTS_ALL RENAME COLUMN PAYMENT_NUMBER TO PAYMENT_NUMBER_OLD;
ALTER TABLE RR_AP_PAYMENTS_ALL ADD (PAYMENT_NUMBER VARCHAR2(100));
UPDATE RR_AP_PAYMENTS_ALL SET PAYMENT_NUMBER = TO_CHAR(PAYMENT_NUMBER_OLD)
  WHERE PAYMENT_NUMBER_OLD IS NOT NULL;
ALTER TABLE RR_AP_PAYMENTS_ALL DROP COLUMN PAYMENT_NUMBER_OLD;
CREATE INDEX RR_AP_PAYMENTS_N1 ON RR_AP_PAYMENTS_ALL (PAYMENT_NUMBER);
COMMIT;

