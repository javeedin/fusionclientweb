-- =============================================================================
-- RR_TAX_SETUP.SQL
-- Input/Output Tax Master, BU Assignments, and ORDS Handlers
-- =============================================================================

-- ---------------------------------------------------------------------------
-- TABLE: RR_INPUT_OUTPUT_TAX  — master tax definitions
-- ---------------------------------------------------------------------------
CREATE TABLE RR_INPUT_OUTPUT_TAX (
    TAX_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TAX_NAME        VARCHAR2(200)  NOT NULL,
    TAX_CODE        VARCHAR2(50)   NOT NULL,
    TAX_RATE        NUMBER(10,4)   NOT NULL,           -- percentage, e.g. 5 for 5%
    TAX_TYPE        VARCHAR2(20)   DEFAULT 'BOTH',     -- INPUT | OUTPUT | BOTH
    APPLICABILITY   VARCHAR2(10)   DEFAULT 'BOTH',     -- AP | AR | BOTH
    DESCRIPTION     VARCHAR2(500),
    STATUS          VARCHAR2(20)   DEFAULT 'ACTIVE',   -- ACTIVE | INACTIVE
    CREATED_BY      VARCHAR2(150),
    CREATION_DATE   TIMESTAMP      DEFAULT SYSTIMESTAMP,
    LAST_UPDATED_BY VARCHAR2(150),
    LAST_UPDATE_DATE TIMESTAMP     DEFAULT SYSTIMESTAMP,
    CONSTRAINT RR_TAX_CODE_UK UNIQUE (TAX_CODE)
);

COMMENT ON TABLE  RR_INPUT_OUTPUT_TAX               IS 'Master input/output tax definitions';
COMMENT ON COLUMN RR_INPUT_OUTPUT_TAX.TAX_RATE      IS 'Percentage rate, e.g. 5 = 5%';
COMMENT ON COLUMN RR_INPUT_OUTPUT_TAX.TAX_TYPE      IS 'INPUT | OUTPUT | BOTH';
COMMENT ON COLUMN RR_INPUT_OUTPUT_TAX.APPLICABILITY IS 'AP | AR | BOTH';
COMMENT ON COLUMN RR_INPUT_OUTPUT_TAX.STATUS        IS 'ACTIVE | INACTIVE';

-- ---------------------------------------------------------------------------
-- TABLE: RR_TAX_ASSIGNMENTS  — tax-to-BU assignments with GL account
-- ---------------------------------------------------------------------------
CREATE TABLE RR_TAX_ASSIGNMENTS (
    ASSIGNMENT_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TAX_ID           NUMBER        NOT NULL,
    BUSINESS_UNIT_NAME VARCHAR2(360) NOT NULL,
    TAX_ACCOUNT      VARCHAR2(200),                   -- GL account combination
    EFFECTIVE_FROM   DATE,
    EFFECTIVE_TO     DATE,
    STATUS           VARCHAR2(20)  DEFAULT 'ACTIVE',  -- ACTIVE | INACTIVE
    CREATED_BY       VARCHAR2(150),
    CREATION_DATE    TIMESTAMP     DEFAULT SYSTIMESTAMP,
    LAST_UPDATED_BY  VARCHAR2(150),
    LAST_UPDATE_DATE TIMESTAMP     DEFAULT SYSTIMESTAMP,
    CONSTRAINT RR_TAX_ASGN_FK  FOREIGN KEY (TAX_ID) REFERENCES RR_INPUT_OUTPUT_TAX(TAX_ID) ON DELETE CASCADE,
    CONSTRAINT RR_TAX_ASGN_UK  UNIQUE (TAX_ID, BUSINESS_UNIT_NAME)
);

COMMENT ON TABLE  RR_TAX_ASSIGNMENTS                    IS 'Tax-to-Business-Unit assignments';
COMMENT ON COLUMN RR_TAX_ASSIGNMENTS.TAX_ACCOUNT        IS 'GL account combination for posting tax';
COMMENT ON COLUMN RR_TAX_ASSIGNMENTS.EFFECTIVE_FROM     IS 'Assignment effective start date';
COMMENT ON COLUMN RR_TAX_ASSIGNMENTS.EFFECTIVE_TO       IS 'Assignment effective end date (NULL = open-ended)';

CREATE INDEX RR_TAX_ASGN_TAXID_IDX ON RR_TAX_ASSIGNMENTS (TAX_ID);
CREATE INDEX RR_TAX_ASGN_BU_IDX    ON RR_TAX_ASSIGNMENTS (BUSINESS_UNIT_NAME);

