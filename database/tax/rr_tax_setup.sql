-- ---------------------------------------------------------------------------
-- 1. GET  tax/taxes  — search/list taxes
-- ---------------------------------------------------------------------------
BEGIN
    ORDS.DEFINE_HANDLER(
        p_module_name    => 'reerp',
        p_pattern        => 'tax/taxes',
        p_method         => 'GET',
        p_source_type    => ORDS.source_type_plsql,
        p_source         => q'[
DECLARE
    v_clob  CLOB;
BEGIN
    APEX_JSON.INITIALIZE_CLOB_OUTPUT;
    APEX_JSON.OPEN_OBJECT;
    APEX_JSON.WRITE('status', 'success');
    APEX_JSON.OPEN_ARRAY('items');

    FOR r IN (
        SELECT TAX_ID, TAX_NAME, TAX_CODE, TAX_RATE, TAX_TYPE,
               APPLICABILITY, DESCRIPTION, STATUS,
               CREATED_BY, TO_CHAR(CREATION_DATE,'YYYY-MM-DD"T"HH24:MI:SS') AS CREATION_DATE,
               LAST_UPDATED_BY, TO_CHAR(LAST_UPDATE_DATE,'YYYY-MM-DD"T"HH24:MI:SS') AS LAST_UPDATE_DATE
        FROM   RR_INPUT_OUTPUT_TAX
        WHERE  (:tax_code       IS NULL OR UPPER(TAX_CODE)  LIKE '%'||UPPER(:tax_code)||'%')
        AND    (:tax_name       IS NULL OR UPPER(TAX_NAME)  LIKE '%'||UPPER(:tax_name)||'%')
        AND    (:applicability  IS NULL OR APPLICABILITY    = :applicability)
        AND    (:status         IS NULL OR STATUS           = :status)
        ORDER  BY TAX_NAME
    ) LOOP
        APEX_JSON.OPEN_OBJECT;
        APEX_JSON.WRITE('taxId',          r.TAX_ID);
        APEX_JSON.WRITE('taxName',        r.TAX_NAME);
        APEX_JSON.WRITE('taxCode',        r.TAX_CODE);
        APEX_JSON.WRITE('taxRate',        r.TAX_RATE);
        APEX_JSON.WRITE('taxType',        r.TAX_TYPE);
        APEX_JSON.WRITE('applicability',  r.APPLICABILITY);
        APEX_JSON.WRITE('description',    r.DESCRIPTION);
        APEX_JSON.WRITE('status',         r.STATUS);
        APEX_JSON.WRITE('createdBy',      r.CREATED_BY);
        APEX_JSON.WRITE('creationDate',   r.CREATION_DATE);
        APEX_JSON.WRITE('lastUpdatedBy',  r.LAST_UPDATED_BY);
        APEX_JSON.WRITE('lastUpdateDate', r.LAST_UPDATE_DATE);
        APEX_JSON.CLOSE_OBJECT;
    END LOOP;

    APEX_JSON.CLOSE_ARRAY;
    APEX_JSON.CLOSE_OBJECT;
    v_clob := APEX_JSON.GET_CLOB_OUTPUT;
    APEX_JSON.FREE_OUTPUT;
    HTP.P(v_clob);
EXCEPTION
    WHEN OTHERS THEN
        APEX_JSON.FREE_OUTPUT;
        HTP.P('{"status":"error","message":' || APEX_JSON.STRINGIFY(SQLERRM) || '}');
END;
]',
        p_items_per_page => 0
    );
    COMMIT;
END;
/

-- ---------------------------------------------------------------------------
-- 2. POST  tax/taxes  — create or update a tax
-- ---------------------------------------------------------------------------
BEGIN
    ORDS.DEFINE_HANDLER(
        p_module_name    => 'reerp',
        p_pattern        => 'tax/taxes',
        p_method         => 'POST',
        p_source_type    => ORDS.source_type_plsql,
        p_source         => q'[
DECLARE
    v_body    CLOB;
    v_dest    INTEGER := 1; v_src INTEGER := 1;
    v_lang    INTEGER := DBMS_LOB.DEFAULT_LANG_CTX; v_warn INTEGER;
    v_tax_id      NUMBER;
    v_tax_name    VARCHAR2(200);
    v_tax_code    VARCHAR2(50);
    v_tax_rate    NUMBER;
    v_tax_type    VARCHAR2(20);
    v_applicability VARCHAR2(10);
    v_description VARCHAR2(500);
    v_status      VARCHAR2(20);
    v_user        VARCHAR2(150);
    v_exists      NUMBER := 0;
BEGIN
    DBMS_LOB.CREATETEMPORARY(v_body, TRUE);
    DBMS_LOB.CONVERTTOCLOB(v_body, :body, DBMS_LOB.LOBMAXSIZE, v_dest, v_src,
                           NLS_CHARSET_ID('AL32UTF8'), v_lang, v_warn);

    SELECT jt.tax_id, jt.tax_name, jt.tax_code, jt.tax_rate, jt.tax_type,
           jt.applicability, jt.description, jt.status, jt.user_name
    INTO   v_tax_id, v_tax_name, v_tax_code, v_tax_rate, v_tax_type,
           v_applicability, v_description, v_status, v_user
    FROM   JSON_TABLE(v_body, '$' COLUMNS (
               tax_id       NUMBER        PATH '$.taxId',
               tax_name     VARCHAR2(200) PATH '$.taxName',
               tax_code     VARCHAR2(50)  PATH '$.taxCode',
               tax_rate     NUMBER        PATH '$.taxRate',
               tax_type     VARCHAR2(20)  PATH '$.taxType',
               applicability VARCHAR2(10) PATH '$.applicability',
               description  VARCHAR2(500) PATH '$.description',
               status       VARCHAR2(20)  PATH '$.status',
               user_name    VARCHAR2(150) PATH '$.lastUpdatedBy'
           )) jt;

    v_status := NVL(v_status, 'ACTIVE');
    v_user   := NVL(v_user,   'ERP_USER');

    IF v_tax_id IS NOT NULL THEN
        SELECT COUNT(1) INTO v_exists FROM RR_INPUT_OUTPUT_TAX WHERE TAX_ID = v_tax_id;
    END IF;

    IF v_exists > 0 THEN
        UPDATE RR_INPUT_OUTPUT_TAX SET
            TAX_NAME         = NVL(v_tax_name,      TAX_NAME),
            TAX_CODE         = NVL(v_tax_code,      TAX_CODE),
            TAX_RATE         = NVL(v_tax_rate,      TAX_RATE),
            TAX_TYPE         = NVL(v_tax_type,      TAX_TYPE),
            APPLICABILITY    = NVL(v_applicability, APPLICABILITY),
            DESCRIPTION      = v_description,
            STATUS           = NVL(v_status,        STATUS),
            LAST_UPDATED_BY  = v_user,
            LAST_UPDATE_DATE = SYSTIMESTAMP
        WHERE TAX_ID = v_tax_id;
    ELSE
        INSERT INTO RR_INPUT_OUTPUT_TAX (
            TAX_NAME, TAX_CODE, TAX_RATE, TAX_TYPE, APPLICABILITY,
            DESCRIPTION, STATUS, CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE
        ) VALUES (
            v_tax_name, v_tax_code, v_tax_rate,
            NVL(v_tax_type, 'BOTH'), NVL(v_applicability, 'BOTH'),
            v_description, v_status, v_user, SYSTIMESTAMP, v_user, SYSTIMESTAMP
        ) RETURNING TAX_ID INTO v_tax_id;
    END IF;

    COMMIT;
    HTP.P('{"status":"success","taxId":' || v_tax_id || '}');
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        ROLLBACK;
        HTP.P('{"status":"error","message":"Tax code already exists"}');
    WHEN OTHERS THEN
        ROLLBACK;
        HTP.P('{"status":"error","message":' || APEX_JSON.STRINGIFY(SQLERRM) || '}');
END;
]',
        p_items_per_page => 0
    );
    COMMIT;
END;
/

