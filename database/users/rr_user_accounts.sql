-- ============================================
-- Table: RR_USER_ACCOUNTS
-- Description: Stores user account information from Oracle Fusion
-- ============================================

CREATE TABLE RR_USER_ACCOUNTS (
    ID                          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID                     NUMBER NOT NULL,
    USERNAME                    VARCHAR2(320) NOT NULL,
    SUSPENDED_FLAG              VARCHAR2(5),
    PERSON_ID                   NUMBER,
    PERSON_NUMBER               VARCHAR2(60),
    CREDENTIALS_EMAIL_SENT_FLAG VARCHAR2(5),
    GUID                        VARCHAR2(100),
    CREATED_BY                  VARCHAR2(150),
    CREATION_DATE               TIMESTAMP,
    LAST_UPDATE_DATE            TIMESTAMP,
    LAST_UPDATED_BY             VARCHAR2(150),
    SYNC_DATE                   TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT UK_RR_USER_ACCOUNTS_ID UNIQUE (USER_ID)
);

-- Indexes
CREATE INDEX IDX_RR_USER_ACCOUNTS_USERNAME ON RR_USER_ACCOUNTS(USERNAME);
CREATE INDEX IDX_RR_USER_ACCOUNTS_PERSON ON RR_USER_ACCOUNTS(PERSON_ID);
CREATE INDEX IDX_RR_USER_ACCOUNTS_GUID ON RR_USER_ACCOUNTS(GUID);

-- Comments
COMMENT ON TABLE RR_USER_ACCOUNTS IS 'User account data synced from Oracle Fusion';
COMMENT ON COLUMN RR_USER_ACCOUNTS.USER_ID IS 'Unique user identifier from Fusion';
COMMENT ON COLUMN RR_USER_ACCOUNTS.USERNAME IS 'User login name/email';
COMMENT ON COLUMN RR_USER_ACCOUNTS.SUSPENDED_FLAG IS 'Whether user is suspended (true/false)';
COMMENT ON COLUMN RR_USER_ACCOUNTS.PERSON_ID IS 'Associated person ID';
COMMENT ON COLUMN RR_USER_ACCOUNTS.PERSON_NUMBER IS 'Associated person number';
COMMENT ON COLUMN RR_USER_ACCOUNTS.CREDENTIALS_EMAIL_SENT_FLAG IS 'Whether credentials email was sent';
COMMENT ON COLUMN RR_USER_ACCOUNTS.GUID IS 'Global unique identifier';
COMMENT ON COLUMN RR_USER_ACCOUNTS.SYNC_DATE IS 'Timestamp when record was synced';

-- ============================================
-- Procedure: RR_SYNC_USER_ACCOUNTS
-- Description: Upsert user accounts from JSON payload
-- ============================================

CREATE OR REPLACE PROCEDURE RR_SYNC_USER_ACCOUNTS (
    p_json IN CLOB,
    p_count OUT NUMBER,
    p_error OUT VARCHAR2
) AS
    v_user_id                     NUMBER;
    v_username                    VARCHAR2(320);
    v_suspended_flag              VARCHAR2(5);
    v_person_id                   NUMBER;
    v_person_number               VARCHAR2(60);
    v_credentials_email_sent_flag VARCHAR2(5);
    v_guid                        VARCHAR2(100);
    v_created_by                  VARCHAR2(150);
    v_creation_date               TIMESTAMP;
    v_last_update_date            TIMESTAMP;
    v_last_updated_by             VARCHAR2(150);
BEGIN
    p_count := 0;
    p_error := NULL;

    FOR rec IN (
        SELECT *
        FROM JSON_TABLE(p_json, '$.items[*]'
            COLUMNS (
                user_id                     NUMBER          PATH '$.UserId',
                username                    VARCHAR2(320)   PATH '$.Username',
                suspended_flag              VARCHAR2(5)     PATH '$.SuspendedFlag',
                person_id                   NUMBER          PATH '$.PersonId',
                person_number               VARCHAR2(60)    PATH '$.PersonNumber',
                credentials_email_sent_flag VARCHAR2(5)     PATH '$.CredentialsEmailSentFlag',
                guid                        VARCHAR2(100)   PATH '$.GUID',
                created_by                  VARCHAR2(150)   PATH '$.CreatedBy',
                creation_date               TIMESTAMP       PATH '$.CreationDate',
                last_update_date            TIMESTAMP       PATH '$.LastUpdateDate',
                last_updated_by             VARCHAR2(150)   PATH '$.LastUpdatedBy'
            )
        )
    ) LOOP
        -- Store values in local variables
        v_user_id                     := rec.user_id;
        v_username                    := rec.username;
        v_suspended_flag              := rec.suspended_flag;
        v_person_id                   := rec.person_id;
        v_person_number               := rec.person_number;
        v_credentials_email_sent_flag := rec.credentials_email_sent_flag;
        v_guid                        := rec.guid;
        v_created_by                  := rec.created_by;
        v_creation_date               := rec.creation_date;
        v_last_update_date            := rec.last_update_date;
        v_last_updated_by             := rec.last_updated_by;

        -- Use MERGE for upsert
        MERGE INTO RR_USER_ACCOUNTS tgt
        USING (SELECT v_user_id AS user_id FROM DUAL) src
        ON (tgt.USER_ID = src.user_id)
        WHEN MATCHED THEN
            UPDATE SET
                USERNAME                    = v_username,
                SUSPENDED_FLAG              = v_suspended_flag,
                PERSON_ID                   = v_person_id,
                PERSON_NUMBER               = v_person_number,
                CREDENTIALS_EMAIL_SENT_FLAG = v_credentials_email_sent_flag,
                GUID                        = v_guid,
                CREATED_BY                  = v_created_by,
                CREATION_DATE               = v_creation_date,
                LAST_UPDATE_DATE            = v_last_update_date,
                LAST_UPDATED_BY             = v_last_updated_by,
                SYNC_DATE                   = SYSTIMESTAMP
        WHEN NOT MATCHED THEN
            INSERT (
                USER_ID,
                USERNAME,
                SUSPENDED_FLAG,
                PERSON_ID,
                PERSON_NUMBER,
                CREDENTIALS_EMAIL_SENT_FLAG,
                GUID,
                CREATED_BY,
                CREATION_DATE,
                LAST_UPDATE_DATE,
                LAST_UPDATED_BY,
                SYNC_DATE
            ) VALUES (
                v_user_id,
                v_username,
                v_suspended_flag,
                v_person_id,
                v_person_number,
                v_credentials_email_sent_flag,
                v_guid,
                v_created_by,
                v_creation_date,
                v_last_update_date,
                v_last_updated_by,
                SYSTIMESTAMP
            );

        p_count := p_count + 1;
    END LOOP;

    COMMIT;

EXCEPTION
    WHEN OTHERS THEN
        p_error := SQLERRM;
        ROLLBACK;
END RR_SYNC_USER_ACCOUNTS;
