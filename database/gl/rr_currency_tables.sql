-- ── Currency Master ──────────────────────────────────────────
CREATE TABLE RR_CURRENCY_LIST (
    CURRENCY_CODE          VARCHAR2(10)   NOT NULL,
    NAME                   VARCHAR2(100),
    DESCRIPTION            VARCHAR2(200),
    ENABLED_FLAG           VARCHAR2(1)    DEFAULT 'Y',
    START_DATE_ACTIVE      DATE,
    END_DATE_ACTIVE        DATE,
    SYMBOL                 VARCHAR2(20),
    PRECISION              NUMBER(2)      DEFAULT 2,
    EXTENDED_PRECISION     NUMBER(2)      DEFAULT 5,
    CURRENCY_FORMAT        VARCHAR2(200),
    CURRENCY_FORMAT_SYMBOL VARCHAR2(400),
    CURRENCY_FORMAT_CODE   VARCHAR2(400),
    ISSUING_TERRITORY_CODE VARCHAR2(10),
    CURRENCY_FLAG          VARCHAR2(1)    DEFAULT 'Y',
    LAST_SYNC_DATE         DATE           DEFAULT SYSDATE,
    CREATED_BY             VARCHAR2(100)  DEFAULT USER,
    CREATION_DATE          DATE           DEFAULT SYSDATE,
    CONSTRAINT RR_CURR_LIST_PK PRIMARY KEY (CURRENCY_CODE)
);

-- ── Rate Types ───────────────────────────────────────────────
CREATE SEQUENCE RR_CURR_RATE_TYPE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE RR_CURRENCY_RATE_TYPES (
    RATE_TYPE_ID                  NUMBER         NOT NULL,
    NAME                          VARCHAR2(50)   NOT NULL,
    DESCRIPTION                   VARCHAR2(200),
    DEFAULT_RATE_TYPE             VARCHAR2(1)    DEFAULT 'N',
    ENFORCE_INVERSE_RELATIONSHIP  VARCHAR2(1)    DEFAULT 'N',
    ENABLE_CROSS_RATES            VARCHAR2(1)    DEFAULT 'N',
    ALLOW_CROSS_RATES_OVERRIDE    VARCHAR2(1)    DEFAULT 'N',
    CROSS_RATE_PIVOT_CURRENCY     VARCHAR2(10),
    CREATED_BY                    VARCHAR2(100)  DEFAULT USER,
    CREATION_DATE                 DATE           DEFAULT SYSDATE,
    LAST_UPDATED_BY               VARCHAR2(100)  DEFAULT USER,
    LAST_UPDATE_DATE              DATE           DEFAULT SYSDATE,
    CONSTRAINT RR_CURR_RT_PK      PRIMARY KEY (RATE_TYPE_ID),
    CONSTRAINT RR_CURR_RT_NAME_UQ UNIQUE (NAME)
);

CREATE OR REPLACE TRIGGER RR_CURR_RT_BIR
BEFORE INSERT ON RR_CURRENCY_RATE_TYPES
FOR EACH ROW
BEGIN
    IF :NEW.RATE_TYPE_ID IS NULL THEN
        :NEW.RATE_TYPE_ID := RR_CURR_RATE_TYPE_SEQ.NEXTVAL;
    END IF;
END;
/

