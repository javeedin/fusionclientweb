-- ── Daily Rates ──────────────────────────────────────────────
CREATE SEQUENCE RR_CURR_DAILY_RATE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE RR_CURRENCY_DAILY_RATES (
    RATE_ID          NUMBER         NOT NULL,
    FROM_CURRENCY    VARCHAR2(10)   NOT NULL,
    TO_CURRENCY      VARCHAR2(10)   NOT NULL,
    RATE_DATE        DATE           NOT NULL,
    RATE_TYPE        VARCHAR2(50)   NOT NULL,
    RATE             NUMBER(20,10)  NOT NULL,
    INVERSE_RATE     NUMBER(20,10),
    SOURCE           VARCHAR2(20)   DEFAULT 'MANUAL',
    CREATED_BY       VARCHAR2(100)  DEFAULT USER,
    CREATION_DATE    DATE           DEFAULT SYSDATE,
    CONSTRAINT RR_CURR_DR_PK PRIMARY KEY (RATE_ID),
    CONSTRAINT RR_CURR_DR_UQ UNIQUE (FROM_CURRENCY, TO_CURRENCY, RATE_DATE, RATE_TYPE)
);

CREATE OR REPLACE TRIGGER RR_CURR_DR_BIR
BEFORE INSERT ON RR_CURRENCY_DAILY_RATES
FOR EACH ROW
BEGIN
    IF :NEW.RATE_ID IS NULL THEN
        :NEW.RATE_ID := RR_CURR_DAILY_RATE_SEQ.NEXTVAL;
    END IF;
    IF :NEW.INVERSE_RATE IS NULL AND :NEW.RATE IS NOT NULL AND :NEW.RATE != 0 THEN
        :NEW.INVERSE_RATE := ROUND(1 / :NEW.RATE, 10);
    END IF;
END;
/

CREATE INDEX RR_CURR_DR_DATE_IDX      ON RR_CURRENCY_DAILY_RATES (RATE_DATE DESC);
CREATE INDEX RR_CURR_DR_FROM_TO_IDX   ON RR_CURRENCY_DAILY_RATES (FROM_CURRENCY, TO_CURRENCY);
CREATE INDEX RR_CURR_DR_RATE_TYPE_IDX ON RR_CURRENCY_DAILY_RATES (RATE_TYPE);
