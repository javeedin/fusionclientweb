    CREATED_BY, CREATION_DATE, LAST_UPDATED_BY, LAST_UPDATE_DATE,
    LEDGER_ID, LEDGER_NAME,
    CHANGED_BY, CHANGED_DATE, CHANGED_FROM_MODULE
  ) VALUES (
    :OLD.BATCH_SYNC_ID, :OLD.JE_BATCH_ID, :OLD.ACCOUNTED_PERIOD_TYPE, :OLD.DEFAULT_PERIOD_NAME,
    :OLD.BATCH_NAME, :OLD.STATUS, :OLD.CONTROL_TOTAL, :OLD.BATCH_DESCRIPTION, :OLD.ERROR_MESSAGE,
    :OLD.POSTED_DATE, :OLD.POSTING_RUN_ID, :OLD.REQUEST_ID,
    :OLD.RUNNING_TOTAL_ACCT_CR, :OLD.RUNNING_TOTAL_ACCT_DR, :OLD.RUNNING_TOTAL_CR, :OLD.RUNNING_TOTAL_DR,
    :OLD.ORACLE_CREATED_BY, :OLD.ORACLE_CREATION_DATE, :OLD.ORACLE_LAST_UPDATE_DATE, :OLD.ORACLE_LAST_UPDATED_BY,
    :OLD.ACTUAL_FLAG_MEANING, :OLD.APPROVAL_STATUS_MEANING, :OLD.APPROVER_EMPLOYEE_NAME,
    :OLD.FUNDS_STATUS_MEANING, :OLD.PARENT_JE_BATCH_NAME, :OLD.CHART_OF_ACCOUNTS_NAME,
