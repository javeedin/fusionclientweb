    BATCH_SYNC_ID, JE_BATCH_ID, ACCOUNTED_PERIOD_TYPE, DEFAULT_PERIOD_NAME,
    BATCH_NAME, STATUS, CONTROL_TOTAL, BATCH_DESCRIPTION, ERROR_MESSAGE,
