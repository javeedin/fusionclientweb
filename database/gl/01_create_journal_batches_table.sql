-- ============================================================
-- GL Journal Batches Table
-- Created for ReactERP - Oracle Fusion Data Sync
-- ============================================================

CREATE TABLE REERP_GL_JOURNAL_BATCHES (
    -- Primary Key
    JOURNAL_BATCH_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Journal Header Information
    JOURNAL_NAME              VARCHAR2(240),
    JOURNAL_DESCRIPTION       VARCHAR2(4000),

    -- Period and Dates
    PERIOD_NAME               VARCHAR2(15),
    DEFAULT_EFFECTIVE_DATE    DATE,
    REFERENCE_DATE            DATE,

    -- Currency Information
    CURRENCY_CODE             VARCHAR2(15),
    LEDGER_CURRENCY_CODE      VARCHAR2(15),
    CURRENCY_CONVERSION_DATE  DATE,
    CURRENCY_CONVERSION_RATE  NUMBER,
    INV_CURRENCY_CONV_RATE    NUMBER,
    USER_CURRENCY_CONV_TYPE   VARCHAR2(30),

    -- Amount Totals
    CONTROL_TOTAL             NUMBER,
    RUNNING_TOTAL_DR          NUMBER,
    RUNNING_TOTAL_CR          NUMBER,
    RUNNING_TOTAL_ACCOUNTED_DR NUMBER,
    RUNNING_TOTAL_ACCOUNTED_CR NUMBER,

    -- Ledger and Entity
    LEDGER_NAME               VARCHAR2(240),
    LEGAL_ENTITY_NAME         VARCHAR2(240),

    -- Category and Type
    USER_JE_CATEGORY_NAME     VARCHAR2(80),
    ENCUMBRANCE_TYPE          VARCHAR2(80),

    -- Accrual Reversal
    ACCRUAL_REVERSAL_EFF_DATE DATE,
    ACCRUAL_REVERSAL_PERIOD   VARCHAR2(15),
    ACCRUAL_REVERSAL_STATUS   VARCHAR2(30),
    ACCRUAL_REVERSAL_JE_NAME  VARCHAR2(240),

    -- Sequences
    CLOSE_ACCT_SEQ_VALUE      NUMBER,
    CLOSE_ACCT_SEQ_ASSIGN_NAME VARCHAR2(80),
    POSTING_ACCT_SEQ_VALUE    NUMBER,
    POSTING_ACCT_SEQ_ASSIGN_NAME VARCHAR2(80),

    -- References
    EXTERNAL_REFERENCE        VARCHAR2(240),
    ORIGINATING_BAL_SEG_VALUE VARCHAR2(25),
    REVERSED_JE_HEADER_NAME   VARCHAR2(240),
    JE_FROM_SLA_FLAG_MEANING  VARCHAR2(80),

    -- Audit Columns (from Oracle Fusion)
    FUSION_CREATED_BY         VARCHAR2(64),
    FUSION_CREATION_DATE      TIMESTAMP WITH TIME ZONE,
    FUSION_LAST_UPDATE_DATE   TIMESTAMP WITH TIME ZONE,
    FUSION_LAST_UPDATED_BY    VARCHAR2(64),

    -- Local Audit Columns
    CREATED_BY                VARCHAR2(100) DEFAULT USER,
    CREATION_DATE             TIMESTAMP DEFAULT SYSTIMESTAMP,
    LAST_UPDATED_BY           VARCHAR2(100),
    LAST_UPDATE_DATE          TIMESTAMP,
    SYNC_DATE                 TIMESTAMP DEFAULT SYSTIMESTAMP,
    SYNC_STATUS               VARCHAR2(20) DEFAULT 'SYNCED'
);

-- Create indexes for common queries
CREATE INDEX IDX_JB_PERIOD_NAME ON REERP_GL_JOURNAL_BATCHES(PERIOD_NAME);
CREATE INDEX IDX_JB_LEDGER_NAME ON REERP_GL_JOURNAL_BATCHES(LEDGER_NAME);
CREATE INDEX IDX_JB_JOURNAL_NAME ON REERP_GL_JOURNAL_BATCHES(JOURNAL_NAME);
CREATE INDEX IDX_JB_EFFECTIVE_DATE ON REERP_GL_JOURNAL_BATCHES(DEFAULT_EFFECTIVE_DATE);
CREATE INDEX IDX_JB_SYNC_DATE ON REERP_GL_JOURNAL_BATCHES(SYNC_DATE);

-- Add comments
COMMENT ON TABLE REERP_GL_JOURNAL_BATCHES IS 'GL Journal Batches synced from Oracle Fusion';
COMMENT ON COLUMN REERP_GL_JOURNAL_BATCHES.JOURNAL_NAME IS 'Name of the journal batch';
COMMENT ON COLUMN REERP_GL_JOURNAL_BATCHES.PERIOD_NAME IS 'Accounting period name (e.g., 01-02, May-24)';
COMMENT ON COLUMN REERP_GL_JOURNAL_BATCHES.SYNC_DATE IS 'Timestamp when record was synced from Fusion';
