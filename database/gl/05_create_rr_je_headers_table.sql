CREATE TABLE RR_GL_HEADERS (
    -- Primary Key
    HEADER_ID                       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Foreign Key to Batch
    BATCH_ID                        NUMBER NOT NULL,
    JE_HEADER_ID                    NUMBER NOT NULL,

    -- Journal Details
    JOURNAL_NAME                    VARCHAR2(240),
    JOURNAL_DESCRIPTION             VARCHAR2(4000),
    PERIOD_NAME                     VARCHAR2(15),
    DEFAULT_EFFECTIVE_DATE          DATE,
    REFERENCE_DATE                  DATE,

    -- Currency Information
    CURRENCY_CODE                   VARCHAR2(15),
    LEDGER_CURRENCY_CODE            VARCHAR2(15),
    CURRENCY_CONVERSION_DATE        DATE,
    CURRENCY_CONVERSION_RATE        NUMBER,
    INV_CURRENCY_CONVERSION_RATE    NUMBER,
    USER_CURRENCY_CONVERSION_TYPE   VARCHAR2(30),

    -- Totals
    CONTROL_TOTAL                   NUMBER,
    RUNNING_TOTAL_DR                NUMBER,
    RUNNING_TOTAL_CR                NUMBER,
    RUNNING_TOTAL_ACCOUNTED_DR      NUMBER,
    RUNNING_TOTAL_ACCOUNTED_CR      NUMBER,

    -- Ledger and Entity
    LEDGER_NAME                     VARCHAR2(240),
    LEGAL_ENTITY_NAME               VARCHAR2(240),

    -- Category
    USER_JE_CATEGORY_NAME           VARCHAR2(80),
    ENCUMBRANCE_TYPE                VARCHAR2(80),

    -- Accrual Reversal
    ACCRUAL_REVERSAL_EFFECTIVE_DATE DATE,
    ACCRUAL_REVERSAL_PERIOD_NAME    VARCHAR2(15),
    ACCRUAL_REVERSAL_STATUS         VARCHAR2(30),
    ACCRUAL_REVERSAL_JE_HEADER_NAME VARCHAR2(240),

    -- Sequences
    CLOSE_ACCOUNT_SEQUENCE_VALUE    NUMBER,
    CLOSE_ACCOUNT_SEQ_ASSIGN_NAME   VARCHAR2(80),
    POSTING_ACCOUNT_SEQUENCE_VALUE  NUMBER,
    POSTING_ACCOUNT_SEQ_ASSIGN_NAME VARCHAR2(80),

    -- References
    EXTERNAL_REFERENCE              VARCHAR2(240),
    ORIGINATING_BAL_SEG_VALUE       VARCHAR2(25),
    REVERSED_JE_HEADER_NAME         VARCHAR2(240),
    JE_FROM_SLA_FLAG_MEANING        VARCHAR2(80),

    -- Fusion Audit Columns
    FUSION_CREATED_BY               VARCHAR2(64),
    FUSION_CREATION_DATE            TIMESTAMP WITH TIME ZONE,
    FUSION_LAST_UPDATE_DATE         TIMESTAMP WITH TIME ZONE,
    FUSION_LAST_UPDATED_BY          VARCHAR2(64),

    -- Local Audit Columns
    CREATED_BY                      VARCHAR2(100) DEFAULT USER,
    CREATION_DATE                   TIMESTAMP DEFAULT SYSTIMESTAMP,
    LAST_UPDATED_BY                 VARCHAR2(100),
    LAST_UPDATE_DATE                TIMESTAMP,
    SYNC_DATE                       TIMESTAMP DEFAULT SYSTIMESTAMP,

    -- Constraints
    CONSTRAINT UK_RR_GL_HEADERS_JE_HEADER_ID UNIQUE (JE_HEADER_ID)
);

-- Create indexes
CREATE INDEX IDX_RR_HDR_BATCH_ID ON RR_GL_HEADERS(BATCH_ID);
CREATE INDEX IDX_RR_HDR_JE_HEADER_ID ON RR_GL_HEADERS(JE_HEADER_ID);
CREATE INDEX IDX_RR_HDR_PERIOD ON RR_GL_HEADERS(PERIOD_NAME);
CREATE INDEX IDX_RR_HDR_LEDGER ON RR_GL_HEADERS(LEDGER_NAME);
CREATE INDEX IDX_RR_HDR_CATEGORY ON RR_GL_HEADERS(USER_JE_CATEGORY_NAME);
CREATE INDEX IDX_RR_HDR_SYNC_DATE ON RR_GL_HEADERS(SYNC_DATE);

COMMENT ON TABLE RR_GL_HEADERS IS 'GL Journal Headers synced from Oracle Fusion';
