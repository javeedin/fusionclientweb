-- ============================================================
-- RR_GL_JOURNAL_BATCHES Table
-- Created for ReactERP - Oracle Fusion Data Sync
-- ============================================================

CREATE TABLE RR_GL_JOURNAL_BATCHES (
    -- Primary Key
    BATCH_SYNC_ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    JE_BATCH_ID               NUMBER NOT NULL,

    -- Period Information
    ACCOUNTED_PERIOD_TYPE     VARCHAR2(30),
    DEFAULT_PERIOD_NAME       VARCHAR2(15),

    -- Batch Details
    BATCH_NAME                VARCHAR2(240),
    STATUS                    VARCHAR2(30),
    CONTROL_TOTAL             NUMBER,
    BATCH_DESCRIPTION         VARCHAR2(4000),
    ERROR_MESSAGE             VARCHAR2(4000),

    -- Posting Information
    POSTED_DATE               DATE,
    POSTING_RUN_ID            NUMBER,
    REQUEST_ID                NUMBER,

    -- Running Totals
    RUNNING_TOTAL_ACCT_CR     NUMBER,
    RUNNING_TOTAL_ACCT_DR     NUMBER,
    RUNNING_TOTAL_CR          NUMBER,
    RUNNING_TOTAL_DR          NUMBER,

    -- Oracle Audit (from Fusion)
    ORACLE_CREATED_BY         VARCHAR2(64),
    ORACLE_CREATION_DATE      TIMESTAMP WITH TIME ZONE,
    ORACLE_LAST_UPDATE_DATE   TIMESTAMP WITH TIME ZONE,
    ORACLE_LAST_UPDATED_BY    VARCHAR2(64),

    -- Status Information
    ACTUAL_FLAG_MEANING       VARCHAR2(80),
    APPROVAL_STATUS_MEANING   VARCHAR2(80),
    APPROVER_EMPLOYEE_NAME    VARCHAR2(240),
    FUNDS_STATUS_MEANING      VARCHAR2(80),
    PARENT_JE_BATCH_NAME      VARCHAR2(240),
    CHART_OF_ACCOUNTS_NAME    VARCHAR2(240),
    STATUS_MEANING            VARCHAR2(80),
    COMPLETION_STATUS_MEANING VARCHAR2(80),

    -- Additional Information
    USER_PERIOD_SET_NAME      VARCHAR2(80),
    USER_JE_SOURCE_NAME       VARCHAR2(80),

    -- Reversal Information
    REVERSAL_DATE             DATE,
    REVERSAL_PERIOD           VARCHAR2(15),
    REVERSAL_FLAG             VARCHAR2(1),
    REVERSAL_METHOD_MEANING   VARCHAR2(80),

    -- Sync Tracking
    SYNC_STATUS               VARCHAR2(20) DEFAULT 'SYNCED',
    SYNC_DATE                 TIMESTAMP DEFAULT SYSTIMESTAMP,
    SYNC_ERROR_MESSAGE        VARCHAR2(4000),
    LAST_SYNC_DATE            TIMESTAMP,
    SYNC_COUNT                NUMBER DEFAULT 1,

    -- Local Audit Columns
    CREATED_BY                VARCHAR2(100) DEFAULT USER,
    CREATION_DATE             TIMESTAMP DEFAULT SYSTIMESTAMP,
    LAST_UPDATED_BY           VARCHAR2(100),
    LAST_UPDATE_DATE          TIMESTAMP,

    -- Unique constraint on JE_BATCH_ID to prevent duplicates
    CONSTRAINT UK_RR_GL_BATCHES_JE_BATCH_ID UNIQUE (JE_BATCH_ID)
);

-- Create indexes
CREATE INDEX IDX_RR_BATCH_PERIOD ON RR_GL_JOURNAL_BATCHES(DEFAULT_PERIOD_NAME);
CREATE INDEX IDX_RR_BATCH_STATUS ON RR_GL_JOURNAL_BATCHES(STATUS);
CREATE INDEX IDX_RR_BATCH_SOURCE ON RR_GL_JOURNAL_BATCHES(USER_JE_SOURCE_NAME);
CREATE INDEX IDX_RR_BATCH_SYNC_DATE ON RR_GL_JOURNAL_BATCHES(SYNC_DATE);

COMMENT ON TABLE RR_GL_JOURNAL_BATCHES IS 'GL Journal Batches synced from Oracle Fusion';
